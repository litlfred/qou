const HARDCODED_OBSERVABLE_RE =
  /[^≈≃~∼\\](?:=\s*)\$?\s*(\d{2,}(?:\.\d+)?)\s*(?:\\[,;]?\s*)?\\?(?:text|mathrm)\{(?:MeV|keV|eV)\}/g;

export function checkCanonicalNoHardcodedObservable(
  mdPath: string | undefined,
): CheckerResult {
  const md = readMaybe(mdPath);
  if (!md) return { result: "pass", hits: [] };
  // Skip bulk data tables (appendix mass calculations, element tables)
  if (mdPath && /amc-|appendix-atomic-mass/.test(mdPath))
    return { result: "pass", hits: [] };
  const hits: CheckerHit[] = [];
  let inTable = false;
  let lineNo = 0;
  for (const line of md.split("\n")) {
    lineNo++;
    // Track markdown table context — data tables use = legitimately
    if (/^\|/.test(line.trim())) inTable = true;
    else if (line.trim() === "") inTable = false;
    if (inTable) continue;
    if (/\\approx|\\simeq|≈|≃|O\(10\^/.test(line)) continue;
    // Skip intermediate arithmetic (chain of = in derivations)
    if ((line.match(/=/g) || []).length >= 2) continue;
    const re = new RegExp(HARDCODED_OBSERVABLE_RE.source, "g");
    for (const m of line.matchAll(re)) {
      hits.push({
        file: mdPath ?? "(unknown)",
        line: lineNo,
        text: `hardcoded observable "${m[0].trim()}" without ≈ — use $\\approx$ per §7ab`,
      });
    }
  }
  return { result: hits.length > 0 ? "fail" : "pass", hits };
}

const CAL4_PATTERNS = [
  /\bCAL-4\b/,
  /4th\s+calibration/i,
  /demoted\s+prop\s*→?\s*conj/i,
  /fourth.calibration/i,
];

export function checkCanonicalCal4Acknowledged(
  mdPath: string | undefined,
  tsPath: string | undefined,
): CheckerResult {
  const md = readMaybe(mdPath);
  const ts = readMaybe(tsPath);
  // Strip markdown blockquotes (lines starting with >) — these are
  // historical/demotion notes that describe PAST violations, not
  // current ones. Also strip TS comments.
  const mdClean = (md ?? "").split("\n")
    .filter((l) => !l.trimStart().startsWith(">"))
    .join("\n");
  const tsClean = (ts ?? "").replace(/\/\*[\s\S]*?\*\/|\/\/.*/g, "");
  const combined = mdClean + "\n" + tsClean;
  const hasCal4 = CAL4_PATTERNS.some((re) => re.test(combined));
  if (!hasCal4) return { result: "pass", hits: [] };

  // Exclude blocks that DEFINE the calibration discipline — they
  // mention "4th calibration" prescriptively, not as a violation.
  const label = (ts ?? "").match(/label:\s*["']([^"']+)["']/)?.[1] ?? "";
  const DEFINITIONAL_LABELS = new Set([
    "prop:three-calibration-discipline",
    "prop:three-calibration-inputs",
  ]);
  if (DEFINITIONAL_LABELS.has(label)) return { result: "pass", hits: [] };

  // Exclude blocks where the CAL-4 mention is in a prescriptive
  // context ("would require", "must be flagged", "violation that").
  const prescriptive =
    /would\s+require\s+a\s+4th\s+calibration/i.test(combined) ||
    /4th\s+calibration.*must\s+be\s+flagged/i.test(combined) ||
    /violation\s+that/i.test(combined);
  if (prescriptive && !(/\bCAL-4\s+anchor\b/i.test(combined)))
    return { result: "pass", hits: [] };

  const kindMatch = (ts ?? "").match(
    /export\s+default\s+(conjecture|theorem|proposition|lemma|corollary)\(/,
  );
  const kind = kindMatch?.[1];
  if (kind === "conjecture") return { result: "pass", hits: [] };

  const hasBanner =
    /CAL-4\s+caveat/i.test(md ?? "") ||
    /q-source\s+open/i.test(md ?? "") ||
    /acknowledged.*CAL-4/i.test(md ?? "");
  if (hasBanner) return { result: "pass", hits: [] };

  return {
    result: "fail",
    hits: [
      {
        file: tsPath ?? mdPath ?? "(unknown)",
        line: 1,
        text:
          `block has CAL-4 caveat but is kind=${kind ?? "unknown"} without ` +
          `acknowledgment banner — demote to conjecture or add CAL-4 banner`,
      },
    ],
  };
}

// Precision-ladder / convergent-coefficient context. The checker
// below only fires inside blocks that discuss a truncation-order
// coefficient ladder (Q_β c_k, α_EM Habiro factor, etc.), where the
// canonical framing (docs/audits/2026-05-31-qbeta-ck-truncation-order-
// canonical-framing.md, Rule 4) requires TIERED reporting.
const LADDER_CONTEXT_TAGS = new Set([
  "precision-ladder", "1ppb-roadmap", "habiro", "truncation-order",
]);
// Ladder-coefficient token: matches c_k, c_2, c_3, c_{10}, d_k, d_3, …
// (single or multi-digit, braced or bare, c- or d-family).
const CK = String.raw`[cd]_?\{?[k0-9]+\}?`;
const LADDER_CONTEXT_RE = new RegExp(
  String.raw`\bprecision\s+ladder\b|\btruncation\s+order\b|\b${CK}\b|` +
    String.raw`\bHabiro\s+element\b`,
  "i",
);

// Binary "negative result" framing — the flip-flop signature. A
// near-match coefficient reported as flatly dropped / un-wired / "just
// a fit" instead of tiered. See the four-session wire/un-wire log in
// the canonical framing doc.
const NEGATIVE_RESULT_PHRASES = [
  /\bun-?wire[ds]?\b/i,
  new RegExp(String.raw`\bdrop(?:ping|ped)?\s+(?:the\s+)?${CK}`, "i"),
  /\b(?:just|merely|only|nothing\s+but)\s+a\s+fit\b/i,
  new RegExp(
    String.raw`\b${CK}.{0,30}\b(?:is|are)\s+(?:just|merely|only)\s+numerolog`,
    "i",
  ),
  /\bfails?\s+to\s+(?:beat|derive|hold)\b/i,
  /\bshould\s+be\s+(?:dropped|reverted|un-?wired)\b/i,
  /\bnegative\s+result\b/i,
];

// Tiered-framing vocabulary that discharges a negative-result hit:
// the block is reporting proved / near-match / fitted tiers rather
// than a binary verdict, OR cites the canonical framing doc.
const TIERED_FRAMING_RE =
  /\bnear[- ]match(?:es)?\b|\btier\b|\btiered\b|truncation-order-canonical-framing/i;

/**
 * canonical-ck-tiered-not-binary — locks Q_β c_k truncation-order
 * Rule 4 into CI: a precision-ladder block that frames a coefficient
 * as a binary "negative result" (dropped / un-wired / just-a-fit) MUST
 * also carry the tiered framing (proved / near-match / fitted) or cite
 * the canonical framing doc. Prevents the four-session wire/un-wire
 * flip-flop from re-entering the paper as flat negative-result prose.
 *
 * Complement to #1574's `canonical-no-negative-result-in-paper`, which
 * catches falsified/superseded *probe-block* leakage via .ts tags and
 * .md Status banners. This checker catches the *prose-framing* failure
 * mode (binary wire/un-wire language in ladder context) that the
 * tag/banner checker does not see.
 */
export function checkCanonicalCkTieredNotBinary(
  mdPath: string | undefined,
  tsPath: string | undefined,
): CheckerResult {
  const md = readMaybe(mdPath);
  if (!md) return { result: "pass", hits: [] };
  const ts = readMaybe(tsPath);

  const tagsMatch = (ts ?? "").match(/tags:\s*\[([\s\S]*?)\]/);
  const tags = tagsMatch
    ? tagsMatch[1].match(/["']([^"']+)["']/g)?.map((t) =>
        t.replace(/["']/g, "")) ?? []
    : [];

  const inContext =
    tags.some((t) => LADDER_CONTEXT_TAGS.has(t)) || LADDER_CONTEXT_RE.test(md);
  if (!inContext) return { result: "pass", hits: [] };

  // Discipline satisfied if the block reports tiers or cites the doc.
  if (TIERED_FRAMING_RE.test(md)) return { result: "pass", hits: [] };

  // Strip blockquotes — historical "wired and un-wired N times" notes
  // describe past flip-flops, not the block's current claim.
  const scan = md
    .split(/\r?\n/)
    .map((l, i) => [i + 1, l] as const)
    .filter(([, l]) => !l.trimStart().startsWith(">"));

  const hits: CheckerHit[] = [];
  for (const [lineNo, line] of scan) {
    for (const re of NEGATIVE_RESULT_PHRASES) {
      const m = line.match(re);
      if (m) {
        hits.push({
          file: mdPath ?? "(unknown)",
          line: lineNo,
          text:
            `binary negative-result framing "${m[0].trim()}" in a ` +
            `precision-ladder block without tiered (proved/near-match/` +
            `fitted) framing — report TIERED per the c_k truncation-order ` +
            `canonical framing (Rule 4), do not re-open the wire/un-wire flip-flop`,
        });
        break;
      }
    }
  }
  return { result: hits.length > 0 ? "fail" : "pass", hits };
}


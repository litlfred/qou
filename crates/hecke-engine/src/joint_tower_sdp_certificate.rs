//! Joint-tower SDP certificate format.
//!
//! Production-scale Rust analogue of the design-spec certificate
//! emitted by the Python proof-of-concept
//! [`gb_filtration_jet_tracker.py`](../../../computations/gb_filtration_jet_tracker.py).
//!
//! Schema: matches `gb-filtration-jet-order.witness.json` (Python PoC)
//! and `joint-tower-sdp-h3.witness.json` / `joint-tower-sdp-h6-h9.witness.json`
//! (Python solver outputs).  The Rust extension lets us scale to
//! H_18 (⁶Li), H_21 (⁷Li), and α-cluster atoms (⁸Be → ⁴⁰Ca) where
//! the Python implementation does not.
//!
//! See [RUST_INTEGRATION.md](../../RUST_INTEGRATION.md) §"Phase R1".

use serde::Serialize;
use std::collections::BTreeMap;

/// One reduction event in the jet-order log.  Matches the Python
/// `JetEvent` dataclass.
#[derive(Serialize, Clone, Debug)]
pub struct JetEvent {
    pub step: u64,
    pub multiplier: i32,
    pub predecessor: Vec<usize>,
    pub successor: Vec<usize>,
    pub filtration_before: u32,
    pub filtration_after: u32,
    /// "ascending" | "hecke-quadratic"
    pub relation: String,
    /// SymPy-equivalent coefficient mutation, stored as a string.
    pub coefficient_change: String,
}

/// One basis element T_w with its symbolic-q coefficient at a given
/// filtration grade.
#[derive(Serialize, Clone, Debug)]
pub struct FiltrationTerm {
    /// Permutation tuple (1-based) representing w ∈ S_n.
    pub perm: Vec<usize>,
    /// Canonical reduced word in σ-generators (1-based).
    pub canonical_word: Vec<u32>,
    /// Coefficient as a string (rational function in q for now;
    /// SparsePoly Laurent later).
    pub coefficient_in_q: String,
}

/// One grade of a filtration certificate: either the terms, or a summary
/// standing in for them when `--truncate-for-repo` elided the list.
///
/// `#[serde(untagged)]` reproduces the heterogeneous JSON already on `main`,
/// where `by_grade["0"]` is a list for small atoms and an object for large
/// ones. The difference from `main` is that the object now carries an explicit
/// `truncated_for_repo: true`, so an elided grade says so instead of being
/// inferred from its shape.
#[derive(Serialize, Clone, Debug)]
#[serde(untagged)]
pub enum GradeTerms {
    Full(Vec<FiltrationTerm>),
    Summarised(GradeSummary),
}

/// Stand-in for an elided grade. NOT a measurement — a record of omission.
#[derive(Serialize, Clone, Debug)]
pub struct GradeSummary {
    pub n_terms: usize,
    pub sample_perm: Vec<usize>,
    pub truncated_for_repo: bool,
}

/// Stand-in for an elided jet log.
#[derive(Serialize, Clone, Debug)]
pub struct JetLogSummary {
    pub n_steps_total: u64,
    pub truncated_for_repo: bool,
}

/// How a witness was truncated, recorded IN the witness.
///
/// This exists because `main`'s 493 KB witness could not be regenerated by any
/// committed producer: its shape (`jet_log_summary`, summarised `by_grade`) was
/// made by a step that is nowhere in the tree -- `grep -r truncated_for_repo`
/// over `*.py *.rs *.sh *.ts` returned nothing -- and the thresholds could only
/// be bracketed from the file, not read off it: the jet-log cut lay somewhere
/// in (20, 238] steps and the by-grade cut somewhere in (14, 28] terms.
///
/// Recording the thresholds is what makes the shape reproducible. A reader no
/// longer has to infer them, and `enabled: false` states positively that
/// nothing was elided.
#[derive(Serialize, Clone, Debug)]
pub struct TruncationPolicy {
    pub enabled: bool,
    /// `jet_log` is kept in full when `n_steps <= this`, else summarised.
    pub jet_log_max_steps: u64,
    /// `by_grade` is kept in full when the atom's largest grade has at most
    /// this many terms, else every grade of that atom is summarised. The
    /// decision is per ATOM, not per grade -- which is what `main` does.
    pub by_grade_max_terms: usize,
}

/// Full GB-filtration certificate at one Hecke element.
/// Maps grade → list of (perm, canonical_word, coefficient).
#[derive(Serialize, Clone, Debug, Default)]
pub struct FiltrationCertificate {
    pub by_grade: BTreeMap<u32, GradeTerms>,
    pub shape: BTreeMap<u32, usize>,
    pub max_grade: u32,
}

impl FiltrationCertificate {
    /// Largest number of terms in any single grade.
    pub fn max_terms_in_a_grade(&self) -> usize {
        self.by_grade
            .values()
            .map(|g| match g {
                GradeTerms::Full(v) => v.len(),
                GradeTerms::Summarised(s) => s.n_terms,
            })
            .max()
            .unwrap_or(0)
    }

    /// Replace every grade's term list with a summary. Idempotent.
    pub fn summarise_all_grades(&mut self) {
        for g in self.by_grade.values_mut() {
            if let GradeTerms::Full(terms) = g {
                *g = GradeTerms::Summarised(GradeSummary {
                    n_terms: terms.len(),
                    sample_perm: terms.first().map(|t| t.perm.clone()).unwrap_or_default(),
                    truncated_for_repo: true,
                });
            }
        }
    }
}

/// Per-Wedderburn-block PSD report (R3 — populated by
/// `wedderburn_psd::evaluate`).
///
/// A block whose `d_lambda` exceeds the `--max-dim-psd` cap is **not
/// evaluated**, and this struct says so rather than fabricating a value.
/// Before 2026-08-29 a skipped block was emitted with `min_eigenvalue: 0.0`,
/// `max_eigenvalue: 0.0` and `psd_symmetric_part: false` — so "nobody looked
/// at this block" was indistinguishable from "this block's spectrum is {0}",
/// and the console printed it as `NOT PSD`, asserting non-positivity about a
/// matrix that was never formed. In the witness on `main` that affected 51 of
/// 169 blocks, every one with `d_lambda > 500` (bean qou-ia6f).
///
/// The three measured fields are therefore `Option`, `None` for a skipped
/// block, and `skipped_dim_cap` names the reason. `matrix_at_q_0_sym_eigvals`
/// is empty in that case, which is what every existing Python consumer already
/// keys on.
#[derive(Serialize, Clone, Debug, Default)]
pub struct WedderburnBlockReport {
    pub partition: Vec<usize>,
    pub d_lambda: usize,
    pub matrix_at_q_0_sym_eigvals: Vec<f64>,
    pub min_eigenvalue: Option<f64>,
    pub max_eigenvalue: Option<f64>,
    pub psd_symmetric_part: Option<bool>,
    /// True when the block was skipped because `d_lambda > max_dim_psd`.
    pub skipped_dim_cap: bool,
}

/// Cross-level consistency edge for tower embeddings (R4 —
/// populated by `cross_level_embedding::verify`).
#[derive(Serialize, Clone, Debug)]
pub struct CrossLevelEdge {
    pub parent: String,
    pub constituent: String,
    pub embedding_codomain_n_0: usize,
    pub embedding_domain_n_0: usize,
    pub embedding_consistent: bool,
    pub diagnostic: String,
}

/// Methodology classification matching `methodology-deprecation.witness.json`.
#[derive(Serialize, Clone, Debug)]
pub enum Methodology {
    #[serde(rename = "principled-derivation")]
    PrincipledDerivation,
    #[serde(rename = "principled-gb-nf")]
    PrincipledGbNf,
    #[serde(rename = "manual-historical-volume-match")]
    ManualHistoricalVolumeMatch,
    #[serde(rename = "magic-A-formula")]
    MagicAFormula,
    #[serde(rename = "recursive-on-4He")]
    RecursiveOn4He,
    #[serde(rename = "deprecated-volume-match")]
    DeprecatedVolumeMatch,
}

/// Per-atom output of the joint-tower SDP solver.
#[derive(Serialize, Clone, Debug)]
pub struct JointTowerSdpCertificate {
    pub name: String,
    pub atomic_n_0: usize,
    pub native_strand_count: usize,
    pub braid_word: Vec<i32>,

    pub filtration_certificate: FiltrationCertificate,
    /// Absent when elided by `--truncate-for-repo`; `jet_log_summary` then
    /// records how many steps there were.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub jet_log: Option<Vec<JetEvent>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub jet_log_summary: Option<JetLogSummary>,
    pub n_steps: u64,
    pub n_hecke_relations_fired: u64,

    /// R3 output — empty if Wedderburn PSD evaluation is deferred.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub wedderburn_blocks: Vec<WedderburnBlockReport>,

    /// R4 output — empty if cross-level checks not run.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub cross_level_edges: Vec<CrossLevelEdge>,

    /// R5-minimal output: PSD-cone α* and gap.  None if not computed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub psd_cone_alpha_star: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub psd_cone_gap: Option<f64>,

    pub rho_factor: u32,
    /// MeV (when computed).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub b_pred_mev: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub b_ame_mev: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub err_ppb: Option<i64>,

    pub methodology: Methodology,
}

/// Top-level witness file: matches the Python output schema.
#[derive(Serialize, Clone, Debug)]
pub struct JointTowerSdpWitness {
    pub computation: String,
    #[serde(rename = "computedAt")]
    pub computed_at: String,
    pub description: String,
    pub design_spec: String,
    pub consumed_by: String,
    pub phase: String,
    pub engine: EngineMetadata,
    /// The substrate modulus the Wedderburn-block PSD evaluation actually ran
    /// at. Set from the `--q0` argument, NOT hardcoded: before 2026-08-29 this
    /// field was the literal `1.1097` while `args.q0` fed the arithmetic, so a
    /// run with `--q0 <anything else>` recorded a value it had not used.
    pub q_0_numeric: f64,
    /// The truncation actually applied, so the witness's shape is reproducible
    /// from the witness itself rather than guessed at.
    pub truncation: TruncationPolicy,
    /// Declares the raw-float64 tier for `witness_raw_float64_audit`. See
    /// [`DeprecationNote`] for why this producer takes the deprecated-f64
    /// carve-out rather than the `float64-integrator` one.
    pub precision_tier: String,
    pub deprecated: DeprecationNote,
    pub per_atom_certificates: Vec<JointTowerSdpCertificate>,
    pub summary: WitnessSummary,
}

/// Why the numeric half of this witness is retired rather than rewritten.
///
/// The witness has two halves and only one of them is numeric. The structural
/// half — filtration certificates, jet logs, Wedderburn shapes, and every
/// `coefficient_in_q` — is **exact**, carried as `ℚ(q)` strings such as
/// `"q**(-2) - 1 + q**2"`, and is unaffected by anything here. The numeric
/// half is the PSD sanity evaluation at `q_0`, and it is f64.
///
/// An mpmath/MPFR rewrite of that half would be precision theatre, because the
/// f64 rounding is not the dominant error and is not close to being it: the
/// evaluation runs at `q_0 = 1.1097`, which is **251 ppm** from the canonical
/// proton pin `1.1099785827513808`. Refining 1e-16 arithmetic underneath a
/// 2.5e-4 input error buys nothing.
#[derive(Serialize, Clone, Debug)]
pub struct DeprecationNote {
    pub reason: String,
    pub not_production: String,
}

#[derive(Serialize, Clone, Debug)]
pub struct EngineMetadata {
    pub name: String,
    pub version: String,
    pub language: String,
}

#[derive(Serialize, Clone, Debug)]
pub struct WitnessSummary {
    /// Number of certificates actually in `per_atom_certificates`.
    ///
    /// This was `registry.len()` until 2026-08-29, which is a different number
    /// whenever `--max-n` filters anything: a run of the 12-atom registry with
    /// `--max-n 12` emitted 11 certificates and reported `n_atoms: 12`.
    pub n_atoms: usize,
    /// Number of atoms in the registry before `--max-n` filtering, so the two
    /// are distinguishable rather than conflated.
    pub n_atoms_in_registry: usize,
    pub max_grade_observed: u32,
    pub total_jet_steps: u64,
    pub total_hecke_relations_fired: u64,
    pub max_native_strand_count: usize,
}

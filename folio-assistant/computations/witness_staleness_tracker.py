#!/usr/bin/env python3
"""Track staleness of witnesses and their upstream dependencies.

Each witness gets a SHA-256 hash recorded in `witness-shas.json`,
along with the SHAs of every UPSTREAM witness it consumes.  The
recursive atom-knot atlas (and similar build-time artifacts) only
regenerate when:

  (a) Their script's SHA changed, OR
  (b) Any upstream witness's SHA changed, OR
  (c) Their output is missing.

This avoids re-running expensive computations (e.g.\ SnapPy
enumeration in `li_atom_knot_search.py` which takes 5 min) on every
build.

DEPENDENCY GRAPH (for the recursive-atom-knot-atlas):

    confined-particle.md (registry, GB-NF source of truth)
       │
       ├─ mass-table-ppb.witness.json (D..⁴⁰Ca, no fits)
       │     └─ upstream: AME 2020, hyperbolic-knot vols (SnapPy)
       │
       ├─ li-atom-knot-search.witness.json (⁶Li, ⁷Li at ρ=5)
       │     └─ upstream: SnapPy HTLinkExteriors[3..11] + OCC[0:1000]
       │     └─ AME 2020 bindings
       │
       └─ recursive_atom_knot_atlas_render.py (renderer)

USAGE:
    # Compute & store SHAs for all witnesses
    python3 witness_staleness_tracker.py update

    # Check which artifacts are stale (need regeneration)
    python3 witness_staleness_tracker.py check

    # Check a single artifact
    python3 witness_staleness_tracker.py check --artifact recursive-atom-knot-atlas

    # Get DAG (JSON output of dependencies)
    python3 witness_staleness_tracker.py dag
"""
from __future__ import annotations
import argparse
import hashlib
import json
import sys
from pathlib import Path

BASE = Path(__file__).parent
SHAS_PATH = BASE / "witness-shas.json"


# Artifacts that are formally DEPRECATED.  The build pipeline must NOT
# consume their output as primary evidence; they survive only for
# reproducibility of historical claims.  See
# methodology-deprecation.witness.json for the per-particle audit and
# the principled alternative (GB-NF → Markov-closure → hp_volume).
DEPRECATED_ARTIFACTS = {
    "li-atom-knot-search": (
        "Volume-match SnapPy search reverse-engineers the answer "
        "(picks knot whose Vol_hyp matches AME). PROVISIONAL only. "
        "Use methodology-deprecation.witness.json + hp_volume.py for "
        "the principled high-precision pipeline."
    ),
}


# Dependency graph: artifact → list of upstream paths (relative to BASE)
DEPS = {
    "recursive-atom-knot-atlas": [
        "../../content/quantum-observable-universe/braids-and-knots/confined-particle.md",
        "mass-table-ppb.witness.json",
        "methodology-deprecation.witness.json",
        # NOTE: li-atom-knot-search.witness.json is consumed only by the
        # provisional/deprecated section of the atlas — see
        # DEPRECATED_ARTIFACTS above.  It is NOT a principled input.
        "li-atom-knot-search.witness.json",
        "hp_volume.py",
        "recursive_atom_knot_atlas_render.py",
    ],
    "methodology-deprecation": [
        "li_atom_knot_search.py",
        "li-atom-knot-search.witness.json",
        "../../content/quantum-observable-universe/braids-and-knots/confined-particle.md",
    ],
    "li-atom-knot-search": [
        "li_atom_knot_search.py",
        # DEPRECATED — see DEPRECATED_ARTIFACTS above.
        # Upstream: SnapPy is an external lib — version-pin via Python
        # snappy.__version__; logged in witness file under "snappy_version"
    ],
    "mass-table-ppb": [
        # Generated by an upstream script; we just track its SHA
        # (computed externally / pre-existing in main).
    ],
    "y-lambda-wenzl-bridge-symbolic": [
        "y_lambda_wenzl_bridge_extended.py",
    ],
    "y-lambda-cyclotomic-factor": [
        "y_lambda_cyclotomic_factor.py",
        "y-lambda-jones-markov-witness.json",  # input
    ],
    "wenzl-qmn-cross-validation": [
        "wenzl_qmn_cross_validation.py",
        "y-lambda-jones-markov-witness.json",
        "q_mn_recursive_memoized.py",
    ],
    "particle-knot-dictionary-audit": [
        "particle_knot_dictionary_audit.py",
        # Touches every .md / .tex — audit re-runs are cheap so always.
    ],
}

# Outputs produced by each artifact (for missing-output check)
OUTPUTS = {
    "recursive-atom-knot-atlas": [
        # The atlas .md is hand-edited; the renderer's stdout is
        # injected into a placeholder.  Output staleness checked by
        # comparing the embedded "atlas-render-sha" key in the .md
        # to the renderer's current SHA.
    ],
    "li-atom-knot-search": ["li-atom-knot-search.witness.json"],
    "y-lambda-wenzl-bridge-symbolic": ["y-lambda-wenzl-bridge-symbolic-witness.json"],
    "y-lambda-cyclotomic-factor": ["y-lambda-cyclotomic-factor.witness.json"],
}


def sha256_file(path: Path) -> str:
    """SHA-256 hash of a file's bytes; returns 'MISSING' if absent."""
    if not path.exists():
        return "MISSING"
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(64 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()[:16]  # truncate for readability


def load_shas():
    if SHAS_PATH.exists():
        with open(SHAS_PATH) as f:
            return json.load(f)
    return {"version": 1, "artifacts": {}}


def save_shas(shas):
    with open(SHAS_PATH, "w") as f:
        json.dump(shas, f, indent=2, sort_keys=True)


def update():
    """Recompute SHAs for all known artifacts and their dependencies."""
    shas = load_shas()
    for artifact, deps in DEPS.items():
        entry = {}
        for dep in deps:
            dep_path = (BASE / dep).resolve()
            entry[dep] = sha256_file(dep_path)
        shas["artifacts"][artifact] = entry
    save_shas(shas)
    print(f"Updated {len(DEPS)} artifact entries → {SHAS_PATH}")


def check(artifact_filter=None):
    """Report which artifacts are stale (any dep SHA changed or output missing)."""
    shas = load_shas()
    stale = []
    fresh = []
    for artifact, deps in DEPS.items():
        if artifact_filter and artifact != artifact_filter:
            continue
        recorded = shas.get("artifacts", {}).get(artifact, {})
        is_stale = False
        reasons = []
        for dep in deps:
            dep_path = (BASE / dep).resolve()
            current_sha = sha256_file(dep_path)
            recorded_sha = recorded.get(dep, "(never recorded)")
            if current_sha != recorded_sha:
                is_stale = True
                reasons.append(f"{dep}: {recorded_sha} → {current_sha}")
        # Output missing
        for out in OUTPUTS.get(artifact, []):
            if not (BASE / out).exists():
                is_stale = True
                reasons.append(f"{out}: MISSING")
        if is_stale:
            stale.append((artifact, reasons))
        else:
            fresh.append(artifact)

    print(f"FRESH ({len(fresh)}):")
    for a in fresh:
        marker = "  ⚠ DEPRECATED" if a in DEPRECATED_ARTIFACTS else "  ✓"
        print(f"{marker} {a}")
        if a in DEPRECATED_ARTIFACTS:
            print(f"      {DEPRECATED_ARTIFACTS[a]}")
    print(f"\nSTALE ({len(stale)}):")
    for a, reasons in stale:
        marker = "  ⚠ DEPRECATED ✗" if a in DEPRECATED_ARTIFACTS else "  ✗"
        print(f"{marker} {a}")
        if a in DEPRECATED_ARTIFACTS:
            print(f"      {DEPRECATED_ARTIFACTS[a]}")
        for r in reasons:
            print(f"      {r}")
    if DEPRECATED_ARTIFACTS:
        print(f"\nDEPRECATED ARTIFACTS ({len(DEPRECATED_ARTIFACTS)}):")
        for a, reason in DEPRECATED_ARTIFACTS.items():
            print(f"  ⚠ {a}: {reason}")
    return len(stale)


def dag():
    """Print the dependency DAG as JSON."""
    print(json.dumps(DEPS, indent=2))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("cmd", choices=["update", "check", "dag"])
    parser.add_argument("--artifact", default=None)
    args = parser.parse_args()
    if args.cmd == "update":
        update()
    elif args.cmd == "check":
        n_stale = check(args.artifact)
        sys.exit(0 if n_stale == 0 else 1)
    elif args.cmd == "dag":
        dag()


if __name__ == "__main__":
    main()

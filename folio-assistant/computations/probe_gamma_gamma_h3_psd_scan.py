#!/usr/bin/env python3
"""γγ → qq̄ at H_3: scan PSD-feasible braid words.

Per investigation #4 of the H/D error-budget discussion: identify the
PSD-feasible γγ-style braid candidates at H_3 (where the std (2,1)
irrep is non-trivial). This concretely demonstrates whether the
proton's hand-picked σ_0σ_1⁻¹·σ_0σ_1⁻¹·σ_0σ_1⁻¹·σ_0·... budget is
the unique PSD-feasible γγ-derived T_w, or whether multiple
candidates pass.

γγ-style braids at H_3 (generated by σ_0, σ_1):
  - σ_0σ_1, σ_1σ_0:                         simple Hopf-link products
  - σ_0σ_1σ_0, σ_1σ_0σ_1:                  trefoil (Yang-Baxter related)
  - σ_0σ_1⁻¹·σ_0σ_1⁻¹·σ_0σ_1⁻¹:           B_3 cube (Borromean-Reeb)
  - σ_0σ_1·σ_0σ_1, σ_1σ_0·σ_1σ_0:         double-trefoil-like
  - σ_0σ_1⁻¹·σ_0σ_1⁻¹:                    B_3 squared (partial Borromean)

For each candidate:
  1. Evaluate ρ_λ(β) at q_0 for λ ∈ {(3), (2,1), (1,1,1)}
  2. Check positive-semidefiniteness in each block
  3. Compute |tr_M| at q_0 (proxy for hadronic mass scale)
  4. Report the ranking

The script reuses `sdp_feasibility_h3` from joint_tower_sdp_solver_v2.

NO Vol_hyp.  NO census.  Pure mpmath at 50 dps for tr_M.

Output: probe-gamma-gamma-h3-psd-scan.witness.json
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from experimental_constants import M_E_MEV
from joint_tower_sdp_solver_v2 import sdp_feasibility_h3, q_0_NUMERIC
from witness_base import WitnessBuilder

# γγ-style candidate braid words at H_3.
# Encoding per joint_tower_sdp_solver_v2: int i represents σ_{i-1}
# for i > 0 and σ_{|i|-1}^{-1} for i < 0. So:
#   1 = σ_0, -1 = σ_0⁻¹, 2 = σ_1, -2 = σ_1⁻¹.
CANDIDATES = [
    ("σ_0",                                          [1]),
    ("σ_0 σ_1",                                       [1, 2]),
    ("σ_1 σ_0",                                       [2, 1]),
    ("σ_0 σ_1 σ_0 (trefoil candidate)",              [1, 2, 1]),
    ("σ_1 σ_0 σ_1 (Yang-Baxter mirror)",             [2, 1, 2]),
    ("σ_0 σ_1⁻¹ σ_0 σ_1⁻¹ σ_0 σ_1⁻¹ (B_3 cube)",     [1, -2, 1, -2, 1, -2]),
    ("σ_0 σ_1⁻¹ σ_0 σ_1⁻¹ (B_3 squared)",            [1, -2, 1, -2]),
    ("σ_0³ (electron-style 2-strand)",               [1, 1, 1]),
    ("σ_0 σ_1 σ_0 σ_1 (Hopf-double)",                [1, 2, 1, 2]),
    ("σ_0 σ_1 σ_0 σ_1 σ_0 σ_1 (B_3 with positive crossings)",
                                                      [1, 2, 1, 2, 1, 2]),
    ("σ_0² σ_1² (gluon-coupling variant)",           [1, 1, 2, 2]),
    ("σ_0³ σ_1 σ_0³ (hand-built proton with substrate)",
                                                      [1, 1, 1, 2, 1, 1, 1]),
]


def main():
    print("=" * 78)
    print("γγ → qq̄ PSD-feasible scan at H_3")
    print("=" * 78)
    print(f"  q_0 = {q_0_NUMERIC}")
    print()

    print(f"  {'name':<54} {'sym':>10} {'std minev':>10} {'alt':>10} {'psd?':>6}")
    print("  " + "-" * 96)

    rows = []
    for name, word in CANDIDATES:
        try:
            check = sdp_feasibility_h3(word, q_0_NUMERIC)
            sym = check["trivial_(3)"]["value"]
            sgn = check["sign_(1,1,1)"]["value"]
            std_min = check["standard_(2,1)"]["min_eigenvalue"]
            psd = check["all_blocks_psd_or_close"]
            print(f"  {name[:52]:<54} {sym:>10.4f} {std_min:>10.4f} "
                  f"{sgn:>10.4f} {'✓' if psd else '✗':>6}")
            rows.append({
                "name": name,
                "braid_word": word,
                "trivial_3": sym,
                "sign_1_1_1": sgn,
                "standard_2_1_min_eig": std_min,
                "standard_2_1_max_eig": check["standard_(2,1)"]["max_eigenvalue"],
                "all_blocks_psd": psd,
            })
        except Exception as e:
            print(f"  {name[:52]:<54} ERROR: {e}")
            rows.append({"name": name, "braid_word": word, "error": str(e)})

    print()
    psd_count = sum(1 for r in rows if r.get("all_blocks_psd"))
    print(f"  PSD-feasible candidates: {psd_count} / {len(rows)}")
    print()
    print("  Interpretation:")
    print("    Multiple candidates can be PSD-feasible at H_3.  The 'γγ → qq̄'")
    print("    SDP needs an ADDITIONAL CONSTRAINT (e.g., minimal |tr_M|, or a")
    print("    fixed Markov trace value matching the physical hadronic mass)")
    print("    to uniquely select one.  PSD alone is not sufficient.")
    print()
    print("  This confirms probe_proton_crossing_budget.py's finding: 11")
    print("  crossings is NOT uniquely PSD-feasible. The full SDP needs a")
    print("  scalar objective (e.g., minimize tr_M complement, or maximize")
    print("  agreement with a target mass scale).")

    w = (
        WitnessBuilder("probe-gamma-gamma-h3-psd-scan", engine="python+numpy+cvxpy")
        .set_description(
            "Scan PSD-feasible γγ-style braid words at H_3 using the "
            "existing sdp_feasibility_h3 from joint_tower_sdp_solver_v2."
            " 12 candidate braids ranging from simple σ_0 σ_1 products "
            "through B_3 cube to hand-built proton structures. Checks "
            "all three Wedderburn blocks (trivial, std, sign) at q_0."
        )
        .set_content_block("rem:photon-channel-wedderburn-chain")
        .add_parameter("q_0", q_0_NUMERIC)
        .add_data("candidates", rows)
        .add_data("psd_feasible_count", psd_count)
        .add_data("total_candidates", len(rows))
        .add_caveat(
            "PSD-feasibility alone is NOT sufficient to uniquely select "
            "the canonical γγ → qq̄ T_w. A scalar objective is needed: "
            "minimal |tr_M|, maximal agreement with a target mass scale, "
            "or an LR cross-level consistency check from H_2 (γγ seed)."
        )
        .add_caveat(
            "This probe uses the HOEFSMIT-MATRIX SDP-feasibility check "
            "(not a true SDP solve). To actually FIND a canonical T_w "
            "rather than CHECK a given one, use cvxpy with PSD constraints "
            "on each Wedderburn block — that's a follow-up project."
        )
    )
    out_path = w.save()
    print(f"\nWitness: {out_path.name}")


if __name__ == "__main__":
    main()

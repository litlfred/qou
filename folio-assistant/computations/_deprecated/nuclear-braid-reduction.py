# ── Braid word representation ───────────────────────────────────
#
# A braid word is a list of (generator_index, sign) pairs:
#   (i, +1) = σ_i  (positive crossing)
#   (i, -1) = σ_i^{-1}  (negative crossing)
#
# In the Iwahori--Hecke algebra, σ_i^{-1} is eliminated via the Hecke relation:
#   σ_i^{-1} = σ_i - (q - q^{-1})
# So every element of H_n(q) is a linear combination of POSITIVE
# braid monomials.

class HeckeElement:
    """Element of the Iwahori--Hecke algebra H_n(q).

    Represented as a dict: {braid_word_tuple: coefficient}.
    A braid word is a tuple of generator indices (all positive).
    The empty tuple () represents the identity.
    """

    def __init__(self, terms=None):
        self.terms = dict(terms) if terms else {}
        self._clean()

    def _clean(self):
        """Remove zero terms."""
        self.terms = {k: v for k, v in self.terms.items() if abs(v) > 1e-15}

    @staticmethod
    def identity():
        return HeckeElement({(): 1.0})

    @staticmethod
    def generator(i):
        """σ_i as a Iwahori--Hecke algebra element."""
        return HeckeElement({(i,): 1.0})

    @staticmethod
    def generator_inv(i, q=Q):
        """σ_i^{-1} = σ_i - (q - q^{-1}).

        From the Hecke relation: σ_i² = (q - q⁻¹)σ_i + 1
        => σ_i(σ_i - (q - q⁻¹)) = 1
        => σ_i⁻¹ = σ_i - (q - q⁻¹)
        """
        coeff_sigma = 1.0
        coeff_id = -(q - 1.0/q)
        return HeckeElement({(i,): coeff_sigma, (): coeff_id})

    def __mul__(self, other):
        """Multiply two Hecke elements (concatenation of braid words)."""
        result = {}
        for w1, c1 in self.terms.items():
            for w2, c2 in other.terms.items():
                w = w1 + w2
                result[w] = result.get(w, 0.0) + c1 * c2
        return HeckeElement(result)

    def __add__(self, other):
        result = dict(self.terms)
        for w, c in other.terms.items():
            result[w] = result.get(w, 0.0) + c
        return HeckeElement(result)

    def __rmul__(self, scalar):
        return HeckeElement({w: scalar * c for w, c in self.terms.items()})

    def scalar_mul(self, s):
        return HeckeElement({w: s * c for w, c in self.terms.items()})

    def n_terms(self):
        return len(self.terms)

    def max_word_length(self):
        if not self.terms:
            return 0
        return max(len(w) for w in self.terms)

    def total_weight(self):
        """Sum of absolute coefficients."""
        return sum(abs(c) for c in self.terms.values())


def apply_hecke_relations(elem, n_strands, q=Q, max_iterations=1000):
    """Apply Iwahori--Hecke algebra relations to reduce a braid word.

    Relations (the Gröbner--Shirshov basis G):
    1. σ_i σ_i = (q - q^{-1}) σ_i + 1    (from Skein: σ_i^2 = (q-q^{-1})σ_i + 1)
    2. σ_i σ_{i+1} σ_i = σ_{i+1} σ_i σ_{i+1}  (Yang-Baxter / braid relation)
    3. σ_i σ_j = σ_j σ_i for |i-j| >= 2  (far commutativity)

    The admissible ordering: length-lex (shorter words first, then
    lexicographic on generator indices).

    Returns the Gröbner--Shirshov-reduced element (unique normal form).
    """
    changed = True
    iterations = 0

    while changed and iterations < max_iterations:
        changed = False
        iterations += 1
        new_terms = {}

        for word, coeff in elem.terms.items():
            if abs(coeff) < 1e-15:
                continue

            reduced = False

            # Scan word for reducible patterns
            for pos in range(len(word) - 1):
                i, j = word[pos], word[pos + 1]

                # Relation 1: σ_i σ_i = (q - q^{-1}) σ_i + 1
                if i == j:
                    prefix = word[:pos]
                    suffix = word[pos + 2:]

                    # Replace σ_i² with (q - q^{-1})σ_i + 1
                    w1 = prefix + (i,) + suffix   # the σ_i term
                    w2 = prefix + suffix           # the identity term
                    c1 = coeff * (q - 1.0 / q)
                    c2 = coeff * 1.0

                    new_terms[w1] = new_terms.get(w1, 0.0) + c1
                    new_terms[w2] = new_terms.get(w2, 0.0) + c2
                    reduced = True
                    changed = True
                    break

                # Relation 3: σ_i σ_j = σ_j σ_i for |i-j| >= 2
                # Use this to sort generators (canonical ordering)
                if abs(i - j) >= 2 and i > j:
                    new_word = word[:pos] + (j, i) + word[pos + 2:]
                    new_terms[new_word] = new_terms.get(new_word, 0.0) + coeff
                    reduced = True
                    changed = True
                    break

            # Relation 2: σ_i σ_{i+1} σ_i = σ_{i+1} σ_i σ_{i+1}
            # Apply when it reduces length-lex order
            if not reduced:
                for pos in range(len(word) - 2):
                    i, j, k = word[pos], word[pos + 1], word[pos + 2]
                    if i == k and abs(i - j) == 1:
                        # σ_i σ_j σ_i where j = i±1
                        # Replace with σ_j σ_i σ_j if that's lex-smaller
                        new_trip = (j, i, j)
                        old_trip = (i, j, i)
                        if new_trip < old_trip:
                            new_word = word[:pos] + new_trip + word[pos + 3:]
                            new_terms[new_word] = new_terms.get(new_word, 0.0) + coeff
                            reduced = True
                            changed = True
                            break

            if not reduced:
                new_terms[word] = new_terms.get(word, 0.0) + coeff

        elem = HeckeElement(new_terms)

    return elem, iterations


# ── Nuclear braid word construction ──────────────────────────────

def build_nucleon_braid(nucleon_type, base_strand, q=Q):
    """Build the Iwahori--Hecke algebra element for one nucleon.

    The Borromean braid on 3 strands is:
      σ_1 σ_2^{-1} σ_1 σ_2^{-1} σ_1 σ_2^{-1}

    In the Iwahori--Hecke algebra, σ_2^{-1} = σ_2 - (q - q^{-1}).
    """
    s1 = HeckeElement.generator(base_strand)
    s2_inv = HeckeElement.generator_inv(base_strand + 1, q)

    # Borromean: (σ_1 σ_2^{-1})^3
    one_twist = s1 * s2_inv
    return one_twist * one_twist * one_twist


def build_nuclear_braid(p, n, q=Q):
    """Build the FULL nuclear braid word in the Iwahori--Hecke algebra.

    For computational tractability, we work with the INTER-NUCLEON
    part only (the external crossings). The internal Borromean
    structure contributes the factor [1][2]/[3] = 0.665 per
    converting nucleon, computed separately.

    The inter-nucleon Hopf crossings:
      p-p pair: σ (positive) → Hecke generator σ_i
      n-n pair: σ^{-1} (negative) → σ_i - (q - q^{-1})
      p-n pair: (σ + σ^{-1})/2 → average of positive and negative
    """
    A = p + n
    types = ['p'] * p + ['n'] * n

    # Start with identity
    result = HeckeElement.identity()

    # For tractability, use a SINGLE strand per nucleon (not 3).
    # This gives B_A instead of B_{3A}, capturing the inter-nucleon
    # structure. The internal Borromean factor is applied separately.

    for i in range(A):
        for j in range(i + 1, A):
            ti, tj = types[i], types[j]

            if ti == 'p' and tj == 'p':
                # Positive crossing at strand i
                crossing = HeckeElement.generator(i)
            elif ti == 'n' and tj == 'n':
                # Negative crossing
                crossing = HeckeElement.generator_inv(i, q)
            else:
                # Mixed: average of positive and negative
                pos = HeckeElement.generator(i)
                neg = HeckeElement.generator_inv(i, q)
                crossing = HeckeElement({
                    w: 0.5 * c for w, c in (pos + neg).terms.items()
                })

            result = result * crossing

    return result


def compute_reduction(p, n, q=Q, max_A=5):
    """Compute the Gröbner--Shirshov-reduced nuclear braid word.

    For large A, the braid word has exponentially many terms after
    Hecke reduction. We limit to small nuclei for exact computation
    and use the structure for extrapolation.
    """
    A = p + n
    if A > max_A:
        return None, None, f"A={A} too large for exact reduction (max={max_A})"

    braid = build_nuclear_braid(p, n, q)
    reduced, iters = apply_hecke_relations(braid, A, q)

    return braid, reduced, None


# ── Main ─────────────────────────────────────────────────────────

def main():
    q = Q
    print(f"Nuclear braid Gröbner--Shirshov reduction in H_n(q)")
    print(f"q = {q}")
    print(f"Skein relation: q σ_i - q^{{-1}} σ_i^{{-1}} = (q^{{1/2}} - q^{{-1/2}})")
    print(f"Hecke relation: σ_i² = (q - q^{{-1}}) σ_i + 1")
    print()

    # Small nuclei for exact computation
    test_cases = [
        ("deuteron", 1, 1),
        ("3H", 1, 2),
        ("3He", 2, 1),
        ("4He", 2, 2),
        ("6Li", 3, 3),
    ]

    results = []

    for name, p, n in test_cases:
        A = p + n
        print(f"=== {name}: N({p},{n}), A={A}, B_{A} ===")

        braid, reduced, err = compute_reduction(p, n, q, max_A=6)
        if err:
            print(f"  {err}")
            results.append({'nucleus': name, 'p': p, 'n': n, 'error': err})
            continue

        print(f"  Unreduced: {braid.n_terms()} terms, max length {braid.max_word_length()}")
        print(f"  Reduced:   {reduced.n_terms()} terms, max length {reduced.max_word_length()}")
        print(f"  Total weight: {braid.total_weight():.4f} → {reduced.total_weight():.4f}")

        # Show the reduced terms
        if reduced.n_terms() <= 20:
            print(f"  Terms:")
            for word, coeff in sorted(reduced.terms.items(), key=lambda x: (len(x[0]), x[0])):
                word_str = "1" if not word else " ".join(f"σ_{i}" for i in word)
                print(f"    {coeff:+.6f} × {word_str}")

        # For beta decay: compute the transition element
        # The transition N(p,n) → N(p+1,n-1) changes one σ^{-1} to σ
        # at the (p, p+1) crossing (first neutron becomes proton)
        if n >= 1 and A <= 6:
            braid_dau, reduced_dau, err_dau = compute_reduction(p + 1, n - 1, q, max_A=6)
            if not err_dau:
                print(f"  Daughter N({p+1},{n-1}):")
                print(f"    Reduced: {reduced_dau.n_terms()} terms, "
                      f"max length {reduced_dau.max_word_length()}")
                print(f"    Total weight: {reduced_dau.total_weight():.4f}")

                # The difference in total weights
                dw = reduced_dau.total_weight() - reduced.total_weight()
                print(f"    ΔWeight = {dw:+.6f}")

        print()

        results.append({
            'nucleus': name, 'p': p, 'n': n,
            'unreduced_terms': braid.n_terms(),
            'reduced_terms': reduced.n_terms(),
            'unreduced_max_len': braid.max_word_length(),
            'reduced_max_len': reduced.max_word_length(),
            'unreduced_weight': braid.total_weight(),
            'reduced_weight': reduced.total_weight(),
        })

    # Write witness
    witness = {
        'computation': 'nuclear-braid-reduction',
        'description': 'Gröbner--Shirshov reduction of nuclear braid words in H_n(q)',
        'timestamp': datetime.now(timezone.utc).isoformat(),
        'parameters': {'q': q},
        'admissible_system': {
            'monomial_basis': 'positive braid words in σ_1,...,σ_{n-1}',
            'ordering': 'length-lexicographic',
            'groebner_generators': [
                'σ_i² - (q - q^{-1}) σ_i - 1',
                'σ_i σ_{i+1} σ_i - σ_{i+1} σ_i σ_{i+1}',
                'σ_i σ_j - σ_j σ_i  (|i-j| >= 2)',
            ],
        },
        'results': results,
    }

    out_path = Path(__file__).parent / 'nuclear-braid-reduction.witness.json'
    with open(out_path, 'w') as f:
        json.dump(witness, f, indent=2, default=str)
    print(f"Witness written to {out_path}")


if __name__ == '__main__':
    main()

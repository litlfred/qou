#!/usr/bin/env python3
"""
Gröbner--Shirshov reduction of nuclear braid words in the Iwahori--Hecke algebra.

Applies the unital Gröbner--Shirshov basis framework (content/unital-groebner-bases)
to the braid group algebra R[B_n] with R = Z[q, q^{-1}], quotiented by
the Skein (Hecke) relation:

    q σ_i - q^{-1} σ_i^{-1} = (q^{1/2} - q^{-1/2})     (*)

This yields the Iwahori--Hecke algebra H_n(q), which is the quotient of R[B_n]
by the two-sided ideal I generated by (*).

The admissible system (B, <) is:
  - B = positive braid words (monomials in σ_1,...,σ_{n-1})
  - < = length-lexicographic ordering (shorter words first, then lex)

The Gröbner--Shirshov basis for I consists of the Skein relations (*) together
with the braid relations:
    σ_i σ_{i+1} σ_i = σ_{i+1} σ_i σ_{i+1}   (Yang-Baxter)
    σ_i σ_j = σ_j σ_i                          (|i-j| >= 2)

The REDUCED braid word N̄(p,n) is the unique normal form of the
nuclear braid word under this Gröbner--Shirshov basis — it is the lowest-energy
representative in the Iwahori--Hecke algebra.

Notation (consistent across papers):
  - B_n: braid group on n strands (QOU Ch4, def:braid-group)
  - σ_i: Artin generator (positive crossing of strands i, i+1)
  - H_n(q): Iwahori--Hecke algebra = R[B_n] / I (quotient by Skein relation)
  - e_i: TL generator = (q σ_i - 1) / (q - 1) (idempotent in H_n)
  - N(p,n): nuclear braid word (unreduced)
  - N̄(p,n): Gröbner--Shirshov-reduced normal form (unique, lowest energy)
  - A = (B, <): admissible system (unital-groebner-bases, def:admissible-system)
  - G: Gröbner--Shirshov basis for the Skein ideal
  - r(f, G): remainder of f on division by G (def:division-algorithm)

Usage:
    python3 computations/nuclear-braid-reduction.py

Output:
    computations/nuclear-braid-reduction.witness.json

Dependencies:
    numpy
"""


import cmath
import math
from fractions import Fraction

W5 = cmath.exp(2j * math.pi / 5)   # ζ₅
W3 = cmath.exp(2j * math.pi / 3)   # ω


def eta_action_group(gens, tol=6, cap=2000):
    """BFS the group generated by maps on (η₁,η₂)∈(ℂ*)², each gen a callable.
    Seed orbit from a generic base point; track the induced permutation group
    by hashing rounded images of several probe points (faithful for these
    monomial/inversion actions)."""
    probes = [(1.7 + 0.3j, 0.9 - 1.1j), (0.4 + 2.0j, 1.3 + 0.2j)]

    def key(g):
        out = []
        for p in probes:
            a, b = g(p)
            out += [round(a.real, tol), round(a.imag, tol), round(b.real, tol), round(b.imag, tol)]
        return tuple(out)

    ident = lambda p: p
    elems = {key(ident): ident}
    queue = [ident]
    while queue and len(elems) < cap:
        f = queue.pop()
        for gg in gens:
            comp = (lambda f, gg: (lambda p: gg(f(p))))(f, gg)
            k = key(comp)
            if k not in elems:
                elems[k] = comp
                queue.append(comp)
    return len(elems)


def commute(f, g, tol=6):
    p = (1.7 + 0.3j, 0.9 - 1.1j)
    a = g(f(p)); b = f(g(p))
    return all(abs(x - y) < 10 ** (-tol) for x, y in zip(a, b))


def mobius_group(mats, tol=4, cap=400):
    """Projective order of ⟨mats⟩ ⊂ PGL(2,ℂ)."""
    def mm(A, B):
        return [[A[0][0]*B[0][0]+A[0][1]*B[1][0], A[0][0]*B[0][1]+A[0][1]*B[1][1]],
                [A[1][0]*B[0][0]+A[1][1]*B[1][0], A[1][0]*B[0][1]+A[1][1]*B[1][1]]]

    def pkey(M):
        for i in range(2):
            for j in range(2):
                if abs(M[i][j]) > 1e-9:
                    lam = M[i][j]
                    N = [[M[r][c]/lam for c in range(2)] for r in range(2)]
                    return tuple(complex(round(N[r][c].real, tol), round(N[r][c].imag, tol))
                                 for r in range(2) for c in range(2))
        return None
    I = [[1, 0], [0, 1]]
    elems = {pkey(I): I}
    queue = [I]
    while queue and len(elems) < cap:
        M = queue.pop()
        for g in mats:
            P = mm(M, g)
            k = pkey(P)
            if k not in elems:
                elems[k] = P
                queue.append(P)
    return len(elems)



#!/usr/bin/env bun
/**
 * Generate `tool-defs/producers.json`: one entry per computation script that a
 * content block wires to a witness, read from the block manifests.
 *
 * Story TOOLS T5 (bean `qou-a3l1`) and the owner's ruling of 2026-10-04:
 * *"all witnesses tools will need to go into the KG"*. Each entry becomes a
 * Tool node in `tool-defs/index.ts`, whose output is the witness node.
 *
 * GENERATED, never hand-listed, as the bean requires: the list is whatever the
 * corpus's `computation: { script, witness }` fields say, so a block that
 * gains or loses a producer changes the Tool graph on the next run, and
 * `--check` fails when the committed list has drifted from the corpus.
 *
 * Parsed textually, scoped to each manifest's `computation: { … }` object, for
 * the reason `folio/pipeline/witness-substitution-audit.ts` gives: importing
 * the manifests pulls in the whole schema package, and a generator that has
 * to typecheck the corpus cannot run on a broken tree.
 *
 * It changes no content block, script or witness; it only reads them.
 *
 *   bun run scripts/gen-producer-tools.ts           # write tool-defs/producers.json
 *   bun run scripts/gen-producer-tools.ts --check   # exit 1 when it is stale
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const FOLIO = join(ROOT, "folio");
const OUT = join(ROOT, "tool-defs", "producers.json");

export interface Producer {
  /** The computation script, repository-relative, as the blocks name it. */
  script: string;
  /** Every witness any block attributes to it, sorted. */
  witnesses: string[];
  /** The block manifests that wire it, repository-relative, sorted. */
  blocks: string[];
  /** Whether the script exists in the tree (a missing one is reported, not dropped). */
  scriptExists: boolean;
}

/** The `computation: { … }` object of a manifest, brace-balanced, or undefined. */
export function computationObject(ts: string): string | undefined {
  const m = /computation\s*:\s*\{/.exec(ts);
  if (!m) return undefined;
  let depth = 0;
  for (let i = m.index + m[0].length - 1; i < ts.length; i++) {
    const c = ts[i];
    if (c === "{") depth++;
    else if (c === "}" && --depth === 0) return ts.slice(m.index, i + 1);
  }
  return undefined;
}

/** A string field of an object literal: `field: "…"` or `field: '…'`. */
function stringField(obj: string, field: string): string | undefined {
  const m = new RegExp(`\\b${field}\\s*:\\s*(["'\`])((?:(?!\\1)[^\\\\]|\\\\.)*)\\1`).exec(obj);
  return m?.[2];
}

/** `witness` as a bare string or an array of strings. */
export function witnessList(obj: string): string[] {
  const arr = /\bwitness\s*:\s*\[([\s\S]*?)\]/.exec(obj);
  if (arr) return [...arr[1]!.matchAll(/["'`]([^"'`]+)["'`]/g)].map((x) => x[1]!);
  const one = stringField(obj, "witness");
  return one ? [one] : [];
}

function* manifests(dir: string): Generator<string> {
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".") || name === "node_modules") continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) yield* manifests(p);
    else if (name.endsWith(".ts") && !name.endsWith(".test.ts")) yield p;
  }
}

/** Every content-wired producer under `folio/`, grouped by script. */
export function collectProducers(root = ROOT): Producer[] {
  const byScript = new Map<string, { witnesses: Set<string>; blocks: Set<string> }>();
  for (const p of manifests(join(root, "folio"))) {
    if (p.includes(`${join(root, "folio", "pipeline")}`)) continue;
    const obj = computationObject(readFileSync(p, "utf8"));
    if (!obj) continue;
    const script = stringField(obj, "script");
    if (!script) continue;
    const e = byScript.get(script) ?? { witnesses: new Set(), blocks: new Set() };
    for (const w of witnessList(obj)) e.witnesses.add(w);
    e.blocks.add(relative(root, p));
    byScript.set(script, e);
  }
  return [...byScript]
    .map(([script, e]) => ({
      script,
      witnesses: [...e.witnesses].sort(),
      blocks: [...e.blocks].sort(),
      scriptExists: existsSync(join(root, script)),
    }))
    .sort((a, b) => a.script.localeCompare(b.script));
}

export function render(producers: Producer[]): string {
  return `${JSON.stringify(
    {
      $comment:
        "GENERATED by scripts/gen-producer-tools.ts from the block manifests' computation fields. Do not edit; re-run the generator.",
      producers,
    },
    null,
    2,
  )}\n`;
}

if (import.meta.main) {
  const producers = collectProducers();
  const text = render(producers);
  const missing = producers.filter((p) => !p.scriptExists).length;
  const noWitness = producers.filter((p) => p.witnesses.length === 0).length;
  if (process.argv.includes("--check")) {
    const ok = existsSync(OUT) && readFileSync(OUT, "utf8") === text;
    console.log(ok ? `✓ tool-defs/producers.json is current (${producers.length} producers)` : "✗ tool-defs/producers.json is stale — run bun run scripts/gen-producer-tools.ts");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(
    `wrote tool-defs/producers.json: ${producers.length} producer(s); ${missing} name a script that is not in the tree, ${noWitness} name no witness`,
  );
}

"""Write the paper's glossary of definitions and splice it into main.tex.

    python3 -I scripts/lib/definition-glossary.py <root> <paper> <out-dir>

Every `definition` block of the paper whose label is present in the rendered
chapters (<out-dir>/chapters/*.tex) gets one alphabetical entry: the term,
linked to the definition; its number and page; and the Lean mark, which links
the rendered Lean docs where they have the declaration (\\folioleanhref, set up
by build-paper-pdf.sh). Owner, 2026-11-19: "definitions ... feed glossary at
end which links to definition".

Derived on every build from the block manifests, so it cannot go stale the
way the committed index-of-definitions table did. Inserted after the
bibliography, as the last chapter.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

root, paper, out = map(pathlib.Path, sys.argv[1:4])
paper_dir = root / "folio" / paper.name
chapters = out / "chapters"

present: set[str] = set()
for f in chapters.glob("*.tex"):
    present |= set(re.findall(r"\\label\{(def:[^}]+)\}", f.read_text(encoding="utf-8")))

STR = r'"((?:[^"\\]|\\.)*)"'


def field(src: str, name: str) -> str | None:
    m = re.search(rf"\b{name}:\s*{STR}", src)
    return json.loads(f'"{m.group(1)}"') if m else None


entries = []
for ts in sorted(paper_dir.glob("*/*.ts")):
    src = ts.read_text(encoding="utf-8")
    if not re.search(r"^export default definition\(", src, re.M):
        continue
    label = field(src, "label")
    if not label or label not in present:
        continue
    title = field(src, "title") or label.removeprefix("def:").replace("-", " ")
    m = re.search(rf"lean:\s*\{{\s*ref:\s*{STR}", src)
    decl = json.loads(f'"{m.group(1)}"').split(":", 1)[-1] if m else ""
    entries.append((label, title, decl))


def sort_key(title: str) -> str:
    t = re.sub(r"\\[A-Za-z]+\*?", "", title)        # \mathfrak{su} -> {su}
    t = re.sub(r"[^A-Za-z0-9 ]", "", t).strip().lower()
    return t or title.lower()


entries.sort(key=lambda e: sort_key(e[1]))

lines = [
    "% generated by scripts/lib/definition-glossary.py",
    "\\clearpage",
    "\\chapter*{Glossary of Definitions}",
    "\\label{app:definition-glossary}",
    "\\addcontentsline{toc}{chapter}{Glossary of Definitions}",
    f"Every definition in the text, alphabetically ({len(entries)} entries). "
    "Each term links to its definition; $\\forall$ links its Lean declaration.",
    "\\begin{multicols}{2}\\small\\raggedright",
]
letter = None
for label, title, decl in entries:
    first = (sort_key(title)[:1] or "#").upper()
    if not first.isalpha():
        first = "#"
    if first != letter:
        letter = first
        lines.append(f"\\par\\medskip{{\\bfseries {letter}}}\\par\\nopagebreak")
    mark = f"\\,\\folioleanhref{{{decl}}}{{$\\forall$}}" if decl else ""
    lines.append(
        f"\\hangindent=1em\\hyperref[{label}]{{{title}}}"
        f"\\dotfill\\ref{{{label}}}, p.\\,\\pageref{{{label}}}{mark}\\par"
    )
lines.append("\\end{multicols}")
gloss = out / "chapters" / "definition-glossary.tex"
gloss.write_text("\n".join(lines) + "\n", encoding="utf-8")

main = out / "main.tex"
s = main.read_text(encoding="utf-8")
anchor = "\\bibliography{references}\n"
if "\\input{chapters/definition-glossary}" not in s:
    if anchor not in s:
        sys.exit("definition-glossary: no \\bibliography line in main.tex to insert after")
    s = s.replace(anchor, anchor + "\n\\input{chapters/definition-glossary}\n", 1)
    main.write_text(s, encoding="utf-8")
print(f"==> glossary of definitions: {len(entries)} entries")

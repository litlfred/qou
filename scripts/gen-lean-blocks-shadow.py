#!/usr/bin/env python3
"""gen-lean-blocks-shadow — compile the content-block Lean siblings where they sit.

Story LEANNODES L2 (bean qou-obes), following the L1 probe (bean qou-hs14,
scripts/lean-blocks-lake-probe.sh). L1 measured that Lake v4.24 accepts a
`[[lean_lib]]` whose `srcDir` points outside the package (R2 PASS), but rejects
kebab-case globs and module names in either spelling (R1 FAIL). The sibling
files are kebab-case (`mass-theory/rho-k-h3a-refinement.lean`), and renaming
them is ruled out: `no-orphan-lean` matches them to their `.ts`/`.md` by stem.

So each library compiles a GENERATED shadow tree of identifier-safe symlinks:

    folio/quantum-observable-universe/lean/blocks-shadow/MassTheory/RhoKH3aRefinement.lean
        -> ../../../mass-theory/rho-k-h3a-refinement.lean

The shadow trees are build-time output: gitignored, rebuilt by `--write`, never
committed. What IS committed is each lakefile's `[[lean_lib]]` block, between
the markers `# BEGIN generated by scripts/gen-lean-blocks-shadow.py` and
`# END generated`. `--check` fails when that block no longer matches what the
manifests imply. The globs come from the chapters that actually hold Lean
siblings, and each such chapter must be declared in its paper manifest (a
`chapterRef({ dir: ... })`). A chapter directory the manifest does not declare
is reported as a finding.

Libraries (none is a default target, so a plain `lake build` is unchanged):
  QOUBlocks       folio/quantum-observable-universe/lean   chapters of the QOU paper
  UGBBlocks       folio/unital-groebner-bases/lean         chapters of the UGB paper
  Fred2005Blocks  folio/fred2005-formal-groups/lean        chapters of Fred2005
  QOUAudits       ./ (the root package `folio`)            docs/audits/**/*.lean

Do NOT add an aggregator root module: siblings share declaration names, so
importing them together fails with "already declared" (LEANNODES report §1.2).

    python3 scripts/gen-lean-blocks-shadow.py --write   # shadow trees + lakefile blocks
    python3 scripts/gen-lean-blocks-shadow.py --check   # exit 1 if a lakefile block drifted
    python3 scripts/gen-lean-blocks-shadow.py --list    # module -> source, one per line
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# BEGIN generated by scripts/gen-lean-blocks-shadow.py — do not edit by hand"
END = "# END generated"


@dataclass
class Lib:
    name: str
    package_dir: Path  # where the lakefile lives
    shadow: Path  # the generated tree (srcDir)
    sources: dict[str, Path]  # module name -> real source file
    globs: list[str]
    undeclared: list[str]  # chapter dirs with Lean that the manifest does not declare


def camel(segment: str) -> str:
    """`rho-k-h3a-refinement.lean` -> `RhoKH3aRefinement`; a leading digit gets an `N`."""
    stem = segment[:-5] if segment.endswith(".lean") else segment
    s = "".join(p[:1].upper() + p[1:] for p in re.split(r"[-_.]", stem) if p)
    return s if s and s[0].isalpha() else "N" + s


def tracked_lean() -> list[str]:
    out = subprocess.run(["git", "ls-files", "*.lean"], cwd=ROOT, capture_output=True, text=True, check=True)
    return out.stdout.split()


def manifest_chapters(paper: str) -> set[str]:
    m = ROOT / "folio" / paper / f"{paper}.ts"
    return set(re.findall(r"chapterRef\(\s*\{[^}]*?\bdir:\s*[\"']([^\"']+)[\"']", m.read_text())) if m.exists() else set()


def module_of(rel_parts: list[str]) -> str:
    return ".".join(camel(p) for p in rel_parts)


def build_libs() -> list[Lib]:
    files = tracked_lean()
    libs: list[Lib] = []
    for paper, name in [
        ("quantum-observable-universe", "QOUBlocks"),
        ("unital-groebner-bases", "UGBBlocks"),
        ("fred2005-formal-groups", "Fred2005Blocks"),
    ]:
        pre = f"folio/{paper}/"
        pkg = ROOT / "folio" / paper / "lean"
        sources: dict[str, Path] = {}
        chapters: set[str] = set()
        for f in files:
            if not f.startswith(pre) or f.startswith(pre + "lean/"):
                continue
            rel = f[len(pre):].split("/")
            if len(rel) < 2:
                continue  # a .lean at the paper root is not a chapter sibling
            chapters.add(rel[0])
            mod = module_of(rel)
            if mod in sources:
                raise SystemExit(f"module-name collision: {mod} <- {sources[mod]} and {f}")
            sources[mod] = ROOT / f
        declared = manifest_chapters(paper)
        libs.append(Lib(name, pkg, pkg / "blocks-shadow", sources,
                        sorted(f"{camel(c)}.+" for c in chapters), sorted(chapters - declared)))
    # Root package: the refutation and vacuity probes recorded under docs/audits.
    sources = {}
    for f in files:
        if f.startswith("docs/audits/"):
            rel = f[len("docs/audits/"):].split("/")
            mod = "Audits." + module_of(rel)
            if mod in sources:
                raise SystemExit(f"module-name collision: {mod} <- {sources[mod]} and {f}")
            sources[mod] = ROOT / f
    libs.append(Lib("QOUAudits", ROOT, ROOT / "lean-shadow", sources, ["Audits.+"], []))
    return libs


def lib_block(lib: Lib) -> str:
    srcdir = os.path.relpath(lib.shadow, lib.package_dir)
    globs = ", ".join(f'"{g}"' for g in lib.globs)
    return (
        f"{BEGIN}\n"
        f"# {len(lib.sources)} modules. srcDir is a gitignored shadow tree of identifier-safe symlinks\n"
        f"# to the real sources; run `python3 scripts/gen-lean-blocks-shadow.py --write` first.\n"
        f"[[lean_lib]]\n"
        f'name = "{lib.name}"\n'
        f'srcDir = "{srcdir}"\n'
        f"globs = [{globs}]\n"
        f'moreLeanArgs = ["-s", "65536"]\n'
        f"{END}\n"
    )


def lakefile_with(text: str, block: str) -> str:
    if BEGIN in text:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, text, flags=re.S)
    return text.rstrip("\n") + "\n\n" + block


def write_shadow(lib: Lib) -> None:
    if lib.shadow.exists():
        shutil.rmtree(lib.shadow)
    for mod, src in lib.sources.items():
        dst = lib.shadow / (mod.replace(".", "/") + ".lean")
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.symlink_to(os.path.relpath(src, dst.parent))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--list", action="store_true")
    a = ap.parse_args()
    libs = build_libs()
    bad = 0
    for lib in libs:
        lakefile = lib.package_dir / "lakefile.toml"
        if a.list:
            for mod, src in sorted(lib.sources.items()):
                print(f"{lib.name}\t{mod}\t{src.relative_to(ROOT)}")
            continue
        want = lakefile_with(lakefile.read_text(), lib_block(lib))
        if a.write:
            lakefile.write_text(want)
            write_shadow(lib)
            print(f"{lib.name}: {len(lib.sources)} modules, {len(lib.globs)} glob(s) -> {lib.shadow.relative_to(ROOT)}")
        else:
            ok = lakefile.read_text() == want
            print(f"{'✓' if ok else '✗'} {lib.name}: {len(lib.sources)} modules, {len(lib.globs)} glob(s) in {lakefile.relative_to(ROOT)}")
            bad += not ok
        for c in lib.undeclared:
            print(f"  finding: {lib.name}: chapter directory '{c}' holds Lean but is not a chapterRef in its manifest")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

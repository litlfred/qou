def conj(l):
    if not l:
        return ()
    c = [0] * l[0]
    for p in l:
        for j in range(p):
            c[j] += 1
    return tuple(c)


def fact(n):
    r = 1
    for k in range(2, n + 1):
        r *= k
    return r


def dim(l, n):
    cj = conj(l)
    prod = 1
    for i, part in enumerate(l):
        for j in range(part):
            prod *= part - j + cj[j] - i - 1
    return fact(n) // prod


def sigma_c(l):
    return sum(j - i for i, p in enumerate(l) for j in range(p))


def omega3(l, n):
    return sum((j - i) ** 2 for i, p in enumerate(l) for j in range(p)) - n * (n - 1) // 2


def p2(l):
    return sum(x * x for x in l)



from __future__ import annotations
from fractions import Fraction as F
import sys

NMIN, NMAX = 1, 12      # pooled window: every partition of every n in [NMIN, NMAX]
# Monomials prod p_{mu_j}^* over partitions mu with |mu| <= MAXDEG. RAISE IT to answer the obvious
# objection to a negative -- "the bound was too low". The verdict is re-checked at MAXDEG + 2 below

MAXDEG = int(sys.argv[1]) if len(sys.argv) > 1 else 6
HALF = F(1, 2)


def partitions(n, cap=None):
    """Every partition of n as a weakly-decreasing tuple."""
    if cap is None:
        cap = n
    if n == 0:
        yield ()
        return
    for first in range(min(n, cap), 0, -1):
        for rest in partitions(n - first, first):
            yield (first,) + rest


def p_star(lam, k):
    """Shifted power sum p_k^*(lam) = sum_i [(lam_i - i + 1/2)^k - (-i + 1/2)^k], exact."""
    tot = F(0)
    for i, part in enumerate(lam, start=1):
        tot += (F(part - i) + HALF) ** k - (F(-i) + HALF) ** k
    return tot


def stats(lam):
    """(n, Sum c, Sum c^2, Sum h, Sum h^2, A = Sum|c|, D = Sum_u d_u^2) -- all exact ints."""
    if not lam:
        return (0,) * 7
    m = lam[0]
    conj = [0] * m
    for part in lam:
        for j in range(part):
            conj[j] += 1
    n = sum_c = sum_c2 = sum_h = sum_h2 = absc = 0
    diag = {}
    for i, part in enumerate(lam):
        for j in range(part):
            h = (part - j - 1) + (conj[j] - i - 1) + 1
            c = j - i
            n += 1
            sum_c += c
            sum_c2 += c * c
            sum_h += h
            sum_h2 += h * h
            absc += abs(c)
            diag[c] = diag.get(c, 0) + 1
    D = sum(v * v for v in diag.values())
    return n, sum_c, sum_c2, sum_h, sum_h2, absc, D


def in_span(rows, target):
    """Exact test: is `target` in the column span of `rows` (a list of coefficient lists)?

    Gaussian elimination over Q on the augmented system. Returns True iff consistent."""
    ncol = len(rows[0])
    aug = [list(r) + [t] for r, t in zip(rows, target)]
    piv_row = 0
    for col in range(ncol):
        piv = None
        for r in range(piv_row, len(aug)):
            if aug[r][col] != 0:
                piv = r
                break
        if piv is None:
            continue
        aug[piv_row], aug[piv] = aug[piv], aug[piv_row]
        pv = aug[piv_row][col]
        aug[piv_row] = [x / pv for x in aug[piv_row]]
        for r in range(len(aug)):
            if r != piv_row and aug[r][col] != 0:
                f = aug[r][col]
                aug[r] = [a - f * b for a, b in zip(aug[r], aug[piv_row])]
        piv_row += 1
        if piv_row == len(aug):
            break
    # inconsistent iff some row is 0 ... 0 | nonzero
    for r in aug:
        if all(x == 0 for x in r[:ncol]) and r[ncol] != 0:
            return False
    return True



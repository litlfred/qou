def triangular_match(f, basis_pows, lead_orders):
    """Read one coefficient per basis element at its leading order,
    return (coeffs, residuals over all orders 1..ORD)."""
    c = {}
    model = [sp.Integer(0)] * (ORD + 1)
    for i, (b, k) in enumerate(zip(basis_pows, lead_orders)):
        ci = simp((f[k] - model[k]) / b[k])
        c[i] = ci
        model = ser_add(model, ser_scale(ci, b))
    resid = {n: simp(f[n] - model[n]) for n in range(1, ORD + 1)}
    return c, resid



del _sys, _Path, _bridge

import sys
import os
import time
from pathlib import Path

os.environ.setdefault("QOU_COMPUTE_DPS", "65")
os.environ.setdefault("QOU_OUTPUT_DPS", "50")

from _precision import set_compute_dps
set_compute_dps(65)
import sympy as sp
import mpmath as mp
mp.mp.dps = 65

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "hecke"))
try:
    import qou_substrate.constants as qs
except ImportError:
    sys.path.insert(0, str(HERE.parent.parent / "tools" / "qou-substrate" / "python"))
    import qou_substrate.constants as qs

from witness_base import WitnessBuilder

def main():
    t0 = time.monotonic()
    
    q_val = mp.mpf(qs.Q_50_DIGIT_STR)
    c2_emp = mp.mpf("-1.0")
    c3_emp = mp.mpf("-2.02161553125628729290")
    c3_ratio_emp = c3_emp / c2_emp # ~ 2.0216
    
    builder = WitnessBuilder(
        "qbeta-sturm-liouville-symbolic-derivation",
        engine="python+sympy",
        start_time=t0
    )
    builder.set_description(
        "Symbolically extracts the c_k recurrence from ∂_q² + t(z) = 0 "
        "using t(z) = -2 from the (2,1) block, testing multiple standard "
        "definitions of the q-Sturm-Liouville derivative."
    )
    builder.set_content_block("prop:q-beta-categorical-precision-ladder")
    
    results = []
    
    q = sp.Symbol('q')
    k = sp.Symbol('k', integer=True)
    
    # Model 1: \partial_q = (\sigma_q - 1). So (\sigma_q - 1)^2 F - 2 u \sigma_q F = 0
    # This leads to c_k = 2 q^{k-1} / (q^k - 1)^2 c_{k-1}
    def model_1_ratio(k_val):
        return 2 * q_val**(k_val-1) / (q_val**k_val - 1)**2
        
    m1_ratio = model_1_ratio(3)
    results.append({
        "model": "(sigma_q - 1)^2 F - 2u sigma_q F = 0",
        "recurrence": "c_k = 2 q^{k-1} / (q^k - 1)^2 * c_{k-1}",
        "c3_over_c2": str(m1_ratio),
        "error_vs_empirical": str(abs(m1_ratio - c3_ratio_emp))
    })
    
    # Model 2: Jackson q-derivative D_q^2 F - 2 u^{-1} F = 0
    def model_2_ratio(k_val):
        return 2 * q_val * (q_val - 1)**2 / ((q_val**k_val - 1)*(q_val**k_val - q_val))
        
    m2_ratio = model_2_ratio(3)
    results.append({
        "model": "D_q^2 F - 2 u^{-1} F = 0",
        "recurrence": "c_k = 2 q (q-1)^2 / ((q^k-1)(q^k-q)) * c_{k-1}",
        "c3_over_c2": str(m2_ratio),
        "error_vs_empirical": str(abs(m2_ratio - c3_ratio_emp))
    })
    
    # Model 3: q-Bessel variant (q sigma_q^2 - (1+q) sigma_q + 1) F - 2u sigma_q F = 0
    def model_3_ratio(k_val):
        return 2 * q_val**(k_val-1) / ((q_val**(k_val+1) - 1)*(q_val**k_val - 1))
        
    m3_ratio = model_3_ratio(3)
    results.append({
        "model": "q-Bessel variant: (q sigma_q - 1)(sigma_q - 1) F - 2u sigma_q F = 0",
        "recurrence": "c_k = 2 q^{k-1} / ((q^{k+1}-1)(q^k-1)) * c_{k-1}",
        "c3_over_c2": str(m3_ratio),
        "error_vs_empirical": str(abs(m3_ratio - c3_ratio_emp))
    })
    
    for r in results:
        print(f"\nModel: {r['model']}")
        print(f"Recurrence: {r['recurrence']}")
        print(f"c_3/c_2 at q_p: {r['c3_over_c2']}")
        print(f"Error vs empirical: {r['error_vs_empirical']}")

    builder.add_data("empirical_c3_over_c2", str(c3_ratio_emp))
    builder.add_data("models", results)
    builder.save()
    
    return 0

if __name__ == "__main__":
    sys.exit(main())

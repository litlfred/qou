def ladd(A: dict[int, int], B: dict[int, int]) -> dict[int, int]:
    C = dict(A)
    for e, c in B.items():
        C[e] = C.get(e, 0) + c
    return {e: c for e, c in C.items() if c != 0}


def gauss_binom_q(n: int, k: int) -> dict[int, int]:
    row: list[dict[int, int]] = [{0: 1}]
    for nn in range(1, n + 1):
        new: list[dict[int, int]] = [{0: 1}]
        for kk in range(1, nn):
            shifted = (
                {e + kk: c for e, c in row[kk].items()} if kk < len(row) else {}
            )
            new.append(ladd(row[kk - 1], shifted))
        new.append({0: 1})
        row = new
    return row[k]


def balanced_binom_a(n: int, k: int) -> dict[int, int]:
    bq = gauss_binom_q(n, k)
    return {2 * e - k * (n - k): c for e, c in bq.items()}


def masbaum_c52_a(n: int) -> dict[int, int]:
    """Exact Masbaum cyclotomic coefficient C_{5_2, n}(a) as a Laurent dict in a (a^2 = q)."""
    out: dict[int, int] = {}
    for k in range(n + 1):
        base = 3 * n * n + 5 * n + k * k - 2 * k - 3 * n * k
        bb = balanced_binom_a(n, k)
        out = ladd(out, {base + e: c for e, c in bb.items()})
    if n % 2 == 1:
        out = {e: -c for e, c in out.items()}
    return out


def eval_laurent_a(poly_a: dict[int, int], a_val: mp.mpf) -> mp.mpf:
    return mp.fsum(mp.mpf(c) * (a_val ** e) for e, c in poly_a.items())



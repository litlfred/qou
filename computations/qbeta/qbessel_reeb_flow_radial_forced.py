def dim_sn(lam):
    n = sum(lam)
    den = 1
    for i in range(len(lam)):
        for j in range(lam[i]):
            arm = lam[i] - j - 1
            leg = sum(1 for r in range(i + 1, len(lam)) if lam[r] > j)
            den *= arm + leg + 1
    return math.factorial(n) // den


def reeb_flow_length(r):
    """The FORCED radial coordinate: arccos (rotation, |r|<=1) or arccosh (growth)."""
    return acos(r) if fabs(r) <= 1 else acosh(fabs(r))


def coincidence_propagator(x, n):
    """(pi x/2) J_n(x) Y_n(x): classical coincidence-limit propagator, integer order n,
    log-Neumann 2nd solution. Parameter-free given (x, n)."""
    if x == 0:
        return mpf(0)
    return (pi * x / 2) * besselj(n, x) * bessely(n, x)



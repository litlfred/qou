from __future__ import annotations

import sys as _s0, pathlib as _p0; _s0.path.insert(0, str(next(p for p in _p0.Path(__file__).resolve().parents if p.name == "computations") / "qbeta")); import qbeta_e0 as _qbeta_e0  # noqa: E401,E402,E702 (#8590) order-zero E_0 routed + labelled, owner ruling 2026-11-20
import json
import subprocess
import time
from pathlib import Path

import mpmath as mp

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

DPS = 30
mp.mp.dps = DPS
Q0 = mp.mpf("1.1099785827513808075916690956107688798744991218736")
M_E = mp.mpf("0.51099895069")
E0 = _qbeta_e0.order_zero_scaled(M_E, Q0)
H = Q0 - 1/Q0
Z_M = Q0**3 / (Q0**2 + 1)
DELTA = (Q0 - 1)**2 * (1 - Q0**-4) / 3          # flavour_split_leading

STRANDS_PER_NUCLEON = 3                          # atom_braid_word_3A, base_g0 = 3k

#: the three interface letters `(c, d)` meaning `c.sigma + d`, convention D
LETTERS = {
    "pp": (mp.mpf(1), mp.mpf(0)),
    "pn": (mp.mpf(1), -H*(mp.mpf(1)/2 - DELTA/4)),
    "nn": (mp.mpf(1), -H),
}

AME = ROOT / "qou-mass/src/qou_mass/data/ame2020.json"


def _head_sha() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def letter_pow_trace(c, d, m: int):
    """`tr_2((c.sigma + d)^m)`, reduced by `sigma^2 = h.sigma + 1`.

    This is what `atom_braid_word_3A`'s `m_pp`/`m_pn`/`m_nn` actually produce:
    the same letter repeated on the SAME generator, so the product stays in the
    2-dimensional subalgebra generated by that one `sigma`. The two-strand trace
    is affine in the offset, `tr(a.sigma + b) = a.z + b`.
    """
    a, b = mp.mpf(0), mp.mpf(1)                  # identity = 0.sigma + 1
    for _ in range(m):
        a, b = a*c*H + a*d + b*c, a*c + b*d
    return a*Z_M + b


def _pct(vals, num, den=100):
    v = sorted(vals)
    return v[min(len(v) - 1, len(v)*num//den)]


def main() -> int:
    t0 = time.monotonic()
    a = []

    def chk(name, computed, expected, note=""):
        ok = computed == expected
        a.append({"name": name, "computed": computed, "expected": expected,
                  "passed": bool(ok), **({"note": note} if note else {})})
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {computed!r}")
        return ok

    ok = True
    L = {k: -mp.log(letter_pow_trace(c, d, 1)) for k, (c, d) in LETTERS.items()}
    coef = E0 * (L["pp"] + L["nn"]) / 2

    rows, bpa_all = [], []
    for e in json.loads(AME.read_text())["entries"]:
        Z, N, A = e["Z"], e["N"], e["A"]
        b = e.get("binding_energy_per_A_keV")
        if Z < 1 or N < 1 or not b or e.get("binding_energy_per_A_estimated"):
            continue
        B = mp.mpf(str(b))*A/1000
        if B > 0:
            rows.append((A, Z, N, B))
            bpa_all.append((mp.mpf(str(b))/1000, A))
    peak_bpa, peak_A = max(bpa_all)
    median_bpa = _pct([v for v, _ in bpa_all], 50)

    print("=" * 78)
    print(f"1. THE NUMBER — {len(rows)} measured nuclides")
    print("=" * 78)
    for k in ("pp", "pn", "nn"):
        print(f"    -ln b_{k} = {mp.nstr(L[k], 10)}")
    print(f"    per-nucleon coefficient at N=Z:  E_0 . {mp.nstr((L['pp']+L['nn'])/2, 8)}"
          f" = {mp.nstr(coef, 8)} MeV")
    print(f"    strands per nucleon (atom_braid_word_3A) = {STRANDS_PER_NUCLEON}")
    comps = [("peak B/A (A = %d)" % peak_A, peak_bpa),
             ("qou-ib3g's quoted 8.790", mp.mpf("8.790")),
             ("qou-59j5's plateau 8.5", mp.mpf("8.5")),
             ("median B/A over the table", median_bpa)]
    table = []
    for nm, v in comps:
        req = v/coef
        off = 100*(STRANDS_PER_NUCLEON - req)/req
        table.append({"comparison": nm, "B_over_A_MeV": mp.nstr(v, 8),
                      "required_factor": mp.nstr(req, 10),
                      "three_off_by_pct": mp.nstr(off, 6)})
        print(f"    {nm:<28} {mp.nstr(v,7):>9} MeV -> factor "
              f"{mp.nstr(req,8):>10}   3 is {mp.nstr(off,4)}% off")
    req_peak = peak_bpa/coef
    ok &= chk("against_the_PEAK_the_required_factor_is_within_a_quarter_percent_of_three",
              abs(mp.mpf(STRANDS_PER_NUCLEON)/req_peak - 1) < mp.mpf("0.005"), True,
              "a law with no surface/Coulomb/asymmetry/pairing term is a pure "
              "volume term, so the peak is the honest comparison -- against the "
              "median it is 7.3 % off, and that difference IS the missing terms")
    ok &= chk("the_peak_of_B_over_A_is_at_the_iron_peak",
              50 <= peak_A <= 70, True,
              f"A = {peak_A}, which is where the ratio ceiling of 3.00-3.01 was "
              "measured on 2026-09-04 -- the ceiling and this factor are one "
              "observation")

    print("\n" + "=" * 78)
    print("2. THE MECHANISM ALREADY IN THE WORD IS REFUTED")
    print("=" * 78)
    print("    atom_braid_word_3A repeats the SAME letter on the SAME generator,")
    print("    so m=3 is X^3 in a 2-dim subalgebra, not b^3.\n")
    print(f"    {'bond':>5}{'m=1':>13}{'m=2':>13}{'m=3':>13}{'factor at m=3':>15}")
    mrows, factors, neg_at_2 = [], [], []
    for k, (c, d) in LETTERS.items():
        vals = [-mp.log(letter_pow_trace(c, d, m)) for m in (1, 2, 3)]
        factors.append(vals[2]/vals[0])
        if vals[1] < 0:
            neg_at_2.append(k)
        mrows.append({"bond": k, **{f"minus_ln_b_m{m}": mp.nstr(v, 12)
                                    for m, v in zip((1, 2, 3), vals)},
                      "factor_at_m3": mp.nstr(vals[2]/vals[0], 10)})
        print(f"    {k:>5}{mp.nstr(vals[0],8):>13}{mp.nstr(vals[1],8):>13}"
              f"{mp.nstr(vals[2],8):>13}{mp.nstr(vals[2]/vals[0],7):>15}")
    ok &= chk("the_multiplicity_parameter_does_not_supply_a_factor_of_three",
              max(factors) < 2, True,
              "0.335 / 0.984 / 1.709 -- non-uniform and nowhere near 3, and the "
              "p-p bond gets WEAKER")
    ok &= chk("at_m_equals_two_two_letters_give_a_NEGATIVE_bond_energy",
              len(neg_at_2) == 2, True,
              f"{neg_at_2} have b > 1 at m=2, so `m` is not a multiplicity of "
              "bond strength at all -- whatever supplies the factor, it is not "
              "this parameter")

    print("\n" + "=" * 78)
    print("3. THE SURVIVING CANDIDATE — disjoint colour-tube tripling")
    print("=" * 78)
    print("    IF three crossings sat on three INDEPENDENT strand pairs AND the")
    print("    trace factorised over disjoint supports, b -> b^3 exactly:")
    for k in ("pp", "pn", "nn"):
        print(f"      {k}: {mp.nstr(L[k], 8)} -> {mp.nstr(3*L[k], 8)}")
    tripled = 3*coef
    print(f"    coefficient = {mp.nstr(tripled, 8)} MeV/nucleon vs peak "
          f"{mp.nstr(peak_bpa, 8)}  ->  {mp.nstr(tripled/peak_bpa, 8)}")
    ok &= chk("disjoint_tripling_lands_within_one_percent_of_the_peak",
              abs(tripled/peak_bpa - 1) < mp.mpf("0.01"), True,
              "0.25 % below. But see the two assumptions: disjoint-support "
              "factorisation of tr_M is ASSUMED not verified, and the 3A layout "
              "cannot express a colour tube -- colour-matched pairs across an "
              "interface are distance 3 apart, needing a braid rather than the "
              "single generator sigma_{3k+2} the word emits")

    print("\n" + "=" * 78)
    print("4. AND IT OVER-BINDS EVERYTHING BELOW THE PEAK, AS IT MUST")
    print("=" * 78)

    def S(Z, N):
        return (Z - 1)*L["pp"] + L["pn"] + (N - 1)*L["nn"]

    laws = {}
    print(f"    {'law':<28}{'median':>10}{'p25-p75':>10}{'p5-p95':>10}")
    for nm, mult in (("E_0 . S       (m = 1)", 1), ("3 . E_0 . S", 3)):
        v = [B/(mult*E0*S(Z, N)) for (A, Z, N, B) in rows]
        laws[nm] = {"median": mp.nstr(_pct(v, 50), 8),
                    "p25_p75": mp.nstr(_pct(v, 75)/_pct(v, 25), 8),
                    "p5_p95": mp.nstr(_pct(v, 95)/_pct(v, 5), 8)}
        print(f"    {nm:<28}{mp.nstr(_pct(v,50),6):>10}"
              f"{mp.nstr(_pct(v,75)/_pct(v,25),6):>10}"
              f"{mp.nstr(_pct(v,95)/_pct(v,5),6):>10}")
    ok &= chk("a_constant_cannot_change_the_spread_only_the_median",
              laws["E_0 . S       (m = 1)"]["p5_p95"] == laws["3 . E_0 . S"]["p5_p95"],
              True,
              "identical to every digit -- so the median moving to 0.895 "
              "(10.5 % over-bound) is the expected signature of a pure volume "
              "term, not evidence FOR the factor. It is the absence of evidence "
              "against it")

    print("\n  🎯 required 3.0075 against a strand count of 3 — recorded as a")
    print("     target to check a future derivation AGAINST, per the anti-fit")
    print("     discipline. Nothing here was searched for.")
    print("  🛑 The mechanism is NOT the m_* parameter, and the 3A layout cannot")
    print("     express the one that would work.")

    print("\n" + ("ALL PASSED" if ok else "SOME FAILED"))

    witness = {
        "computation": "qbeta-strand-multiplicity",
        "q0Anchor": "proton",
        "assertions": a,
        "allPassed": bool(ok),
        "parameters": {"q0": mp.nstr(Q0, 30), "dps": DPS,
                       "E_0_MeV": mp.nstr(E0, 20),
                       "E_0_expression": "m_e/(q0*(q0-1))  [CAL-1, a calibration]",
                       "strands_per_nucleon": STRANDS_PER_NUCLEON,
                       "source": "qou-mass/src/qou_mass/data/ame2020.json"},
        "data": {
            "n_measured": len(rows),
            "per_nucleon_coefficient_MeV": mp.nstr(coef, 15),
            "bond_energies": {k: mp.nstr(v, 15) for k, v in L.items()},
            "required_factor_by_comparison": table,
            "peak_B_over_A": {"MeV": mp.nstr(peak_bpa, 12), "A": peak_A},
            "multiplicity_parameter": mrows,
            "negative_bond_energy_at_m2": neg_at_2,
            "disjoint_tripling_coefficient_MeV": mp.nstr(tripled, 15),
            "disjoint_tripling_over_peak": mp.nstr(tripled/peak_bpa, 12),
            "laws": laws,
        },
        "provenance": {"headSha": _head_sha(),
                       "producer": "computations/qbeta/qbeta_strand_multiplicity_probe.py",
                       # `elapsed_sec`, not `elapsed_s` — the raw-float64
                       # ratchet's wall-clock carve-out matches field names
                       # exactly and does not carry the `_s` spelling. Key
                       # only; no value changes. Fourth site of this class on
                       # this branch; see qbeta_binding_law_options_probe.py.
                       "elapsed_sec": round(time.monotonic() - t0, 3)},
    }
    out = HERE / "qbeta-strand-multiplicity.witness.json"
    out.write_text(json.dumps(witness, indent=2, ensure_ascii=False) + "\n")
    print(f"\nwitness -> {out.relative_to(ROOT)}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())

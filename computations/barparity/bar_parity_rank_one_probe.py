"""The bar-odd channel is FREE OF RANK ONE: there is no bar-odd object to choose.

Bean `qou-fi93`.  Lean:
`content/quantum-observable-universe/lean/QOU/Observations/BarParityRankOne.lean`.

WHY THIS EXISTS.  `qou-fi93` recorded a scope-(b) exclusion -- every counting
object the framework defines is exactly bar-even, so the colour-curve asymmetry
cannot reach a number density through any of them -- and its sibling note then
exhibited

    q^n - q^-n  =  [n]_q * (q - q^-1)

as a bar-ODD object carrying a counting integer.  It immediately flagged the
weakness of doing that, in its own words:

    q^n - q^-n is not SELECTED, only exhibited.  It is the obvious bar-odd
    companion to [n]_q.  Choosing it *because* it has the wanted parity would
    be selection against the target, which sec NO FITTING forbids.

That objection is correct as stated and it is the one this probe removes --
not by arguing the object is a good choice, but by showing THERE IS NO CHOICE.

THE STRUCTURE THEOREM.  Over Z[q, q^-1] with the bar involution q -> q^-1:

  (a) the bar-EVEN part is exactly Z[q + q^-1];
  (b) the bar-ODD part is a FREE RANK-ONE module over it, generated by
      (q - q^-1);
  (c) so f is bar-odd  <=>  f = (q - q^-1) * g  with g bar-even, and that
      correspondence is a bijection.

Consequence: q^n - q^-n is not one bar-odd candidate among many.  EVERY
bar-odd object in the coefficient ring is the same generator times a bar-even
one, and the generator is itself the n = 1 member of the family.  There is
nothing left to select, so there is nothing to select against the target.

WHAT THE GENERATOR IS.  (q - q^-1) is not a new object either: it is the Hecke
structure constant.  From the Hecke relation sigma^2 = (q - q^-1) sigma + 1
(AGENTS.md sec 7a), multiplying by sigma^-1 gives

    sigma - sigma^-1  =  q - q^-1        i.e.   L_+ - L_-  =  (q - q^-1) L_0

which is the skein relation.  So the bar-odd generator is exactly the
coefficient relating a crossing-difference to a smoothing -- and sigma's two
eigenvalues are q (symmetric channel) and -q^-1 (antisymmetric channel), whose
SUM is the generator and whose PRODUCT is -1.  The bar exchanges the two
channels up to sign.

RANK IS CHECKED OVER Z, NOT OVER Q.  Section 3 builds the two integral bases
and computes the determinant of the transition matrix.  A nonzero determinant
would only give a Q-vector-space isomorphism; |det| = 1 (unimodular) is what
makes the module FREE over Z with that generator.  Both are computed and the
distinction is reported, because they are different claims.

Exact `sympy` throughout; one `mpmath.mpf` evaluation at 60 dps for the tie to
`qou-hjs8`.  No float64.
"""

from __future__ import annotations

import sys
from pathlib import Path

import sympy as sp

_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_ROOT / "tools" / "qou-substrate" / "python"))

import mpmath as mp  # noqa: E402

mp.mp.dps = 60

q = sp.Symbol("q", positive=True)
t = sp.Symbol("t")          # stands for q + q^-1


def bar(e):
    """The bar involution q -> 1/q."""
    return sp.simplify(sp.expand(e.subs(q, 1 / q)))


def is_bar_even(e) -> bool:
    return sp.simplify(sp.expand(bar(e) - e)) == 0


def is_bar_odd(e) -> bool:
    return sp.simplify(sp.expand(bar(e) + e)) == 0


def hdr(s: str) -> None:
    print()
    print("=" * 78)
    print(s)
    print("=" * 78)


SKEIN = q - 1 / q
NMAX = 20

# ---------------------------------------------------------------- section 1
hdr("[1] The bar-EVEN part is exactly Z[q + q^-1]  (Dickson / Chebyshev)")

print("  A bar-even Laurent polynomial has a_{-k} = a_k, so it is an integer")
print("  combination of 1 and the q^k + q^-k.  Each of those is an integer")
print("  polynomial in t = q + q^-1, by the Dickson recursion")
print("      D_k = t * D_{k-1} - D_{k-2},   D_0 = 2,  D_1 = t.")
print()

D = [sp.Integer(2), t]
for k in range(2, NMAX + 1):
    D.append(sp.expand(t * D[k - 1] - D[k - 2]))

bad = []
for k in range(0, NMAX + 1):
    lhs = sp.expand(q ** k + q ** (-k))
    rhs = sp.expand(D[k].subs(t, q + 1 / q))
    if sp.simplify(sp.expand(lhs - rhs)) != 0:
        bad.append(k)
    # integrality of the Dickson coefficients
    poly = sp.Poly(D[k], t)
    if not all(c.is_Integer for c in poly.all_coeffs()):
        bad.append(("noninteger", k))

print(f"  q^k + q^-k = D_k(q + q^-1) with INTEGER coefficients, k = 0..{NMAX}")
print(f"  failures: {bad if bad else 'none'}")
assert not bad
for k in (1, 2, 3, 4, 5):
    print(f"    k={k}:  q^{k} + q^-{k} = {sp.factor(D[k])}")

# ---------------------------------------------------------------- section 2
hdr("[2] Every bar-ODD basis element factors through the SAME generator")

print(f"  Claim:  q^k - q^-k = (q - q^-1) * [k]_q   with [k]_q bar-EVEN,")
print(f"  checked exactly for k = 1..{NMAX}.")
print()

fails = []
for k in range(1, NMAX + 1):
    odd_k = sp.expand(q ** k - q ** (-k))
    cof = sp.simplify(sp.cancel(odd_k / SKEIN))
    if sp.simplify(sp.expand(odd_k - SKEIN * cof)) != 0:
        fails.append(("factor", k))
    if not is_bar_odd(odd_k):
        fails.append(("not odd", k))
    if not is_bar_even(cof):
        fails.append(("cofactor not even", k))

print(f"  failures: {fails if fails else 'none'}")
assert not fails
for k in (1, 2, 3):
    cof = sp.simplify(sp.cancel(sp.expand(q ** k - q ** (-k)) / SKEIN))
    print(f"    k={k}:  cofactor [{k}]_q = {sp.simplify(cof)}   bar-even: "
          f"{is_bar_even(cof)}")

print()
print("  And the generator is the k = 1 member of its own family:")
print(f"    (q - q^-1) - (q^1 - q^-1) = "
      f"{sp.simplify(sp.expand(SKEIN - (q ** 1 - q ** (-1))))}")
assert sp.simplify(sp.expand(SKEIN - (q ** 1 - q ** (-1)))) == 0

# ---------------------------------------------------------------- section 3
hdr("[3] RANK ONE OVER Z -- the transition matrix is unimodular, not merely "
    "invertible")

print("  Fix a degree window [-N, N].")
print("    bar-ODD  basis :  O_k = q^k - q^-k,          k = 1..N       (rank N)")
print("    bar-EVEN basis :  E_0 = 1,  E_j = q^j + q^-j, j = 1..N-1    (rank N)")
print()
print("  Multiplication by the generator maps the second into the first.")
print("  Write (q - q^-1) * E_j in the O_k basis and take the determinant:")
print("    det != 0  => an isomorphism of Q-VECTOR SPACES      (weaker)")
print("    |det| = 1 => an isomorphism of Z-MODULES, i.e. FREE (what is claimed)")
print()
print("     N   det   |det|=1 (free over Z)")
print("    ---  ----  ---------------------")

all_unimodular = True
for N in range(1, 13):
    # image vectors: (q - q^-1) * E_j  for j = 0..N-1, expanded in O_k
    rows = []
    for j in range(0, N):
        Ej = sp.Integer(1) if j == 0 else q ** j + q ** (-j)
        prod = sp.expand(SKEIN * Ej)
        # prod is bar-odd; read off its coefficients on q^k for k = 1..N
        coeffs = [sp.expand(prod).coeff(q, k) for k in range(1, N + 1)]
        rows.append(coeffs)
    M = sp.Matrix(rows)
    det = sp.simplify(M.det())
    uni = abs(det) == 1
    all_unimodular = all_unimodular and uni
    print(f"    {N:3d}  {str(det):>4s}  {'YES' if uni else 'NO'}")

assert all_unimodular, "transition matrix is not unimodular -- NOT free over Z"
print()
print("  Unimodular at every N checked, so the bar-odd part is a FREE rank-one")
print("  Z-module on (q - q^-1).  Note what this rules out: a nonzero det that")
print("  is not +-1 would mean the generator spans only a finite-index")
print("  SUBLATTICE, and then a bar-odd object could exist that is NOT")
print("  (q - q^-1) times an INTEGRAL bar-even one.  It does not.")

# ---------------------------------------------------------------- section 4
hdr("[4] The generator IS the Hecke structure constant (so it is not new either)")

sig = sp.Symbol("sigma")
hecke = sp.expand((sig - q) * (sig + 1 / q))            # the Hecke relation
print(f"  (sigma - q)(sigma + q^-1) = {sp.expand(hecke)}")
resid = sp.simplify(sp.expand(hecke - (sig ** 2 - SKEIN * sig - 1)))
print(f"  minus (sigma^2 - (q - q^-1) sigma - 1) = {resid}")
assert resid == 0
print()
print("  So sigma^2 = (q - q^-1) sigma + 1, and multiplying by sigma^-1:")
print("      sigma - sigma^-1 = q - q^-1        [AGENTS.md sec 7a]")
print("  which is the skein relation  L_+ - L_-  =  (q - q^-1) L_0.")
print()

ev = [q, -1 / q]
print(f"  eigenvalues of sigma           : {ev[0]}  (symmetric channel)")
print(f"                                   {sp.simplify(ev[1])}  (antisymmetric)")
print(f"  sum    = trace                 : {sp.simplify(ev[0] + ev[1])}"
      f"   <- the bar-ODD generator")
print(f"  product = determinant          : {sp.simplify(ev[0] * ev[1])}"
      f"          <- bar-EVEN")
assert sp.simplify(sp.expand(ev[0] + ev[1] - SKEIN)) == 0
assert sp.simplify(ev[0] * ev[1]) == -1
print()
print("  Under the bar the two eigenvalues EXCHANGE up to sign:")
print(f"    bar(q)      = {bar(q)}      = -({sp.simplify(ev[1])})")
print(f"    bar(-q^-1)  = {sp.simplify(bar(-1 / q))}       = -({ev[0]})")
assert sp.simplify(sp.expand(bar(q) + ev[1])) == 0
assert sp.simplify(sp.expand(bar(-1 / q) + ev[0])) == 0
print()
print("  So the bar exchanges the symmetric and antisymmetric channels, and")
print("  the bar-odd generator is their DIFFERENCE of eigenvalues in the sense")
print("  of being the trace q + (-q^-1).  The bar-odd channel is generated by")
print("  the separation between the two statistics channels -- a defining")
print("  structure constant of the framework, not an object added to it.")

# ---------------------------------------------------------------- section 5
hdr("[5] Numerical tie at the proton pin (mpmath, 60 dps -- no float64)")

from qou_substrate.constants import q_at  # noqa: E402

q0 = q_at(dps=60)
skein0 = q0 - 1 / q0
even0 = q0 + 1 / q0
ratio = skein0 / even0
tanh_lnq = mp.tanh(mp.log(q0))

print(f"  q0                       = {mp.nstr(q0, 30)}   (proton pin)")
print(f"  generator  q0 - 1/q0     = {mp.nstr(skein0, 30)}")
print(f"  bar-even   q0 + 1/q0     = {mp.nstr(even0, 30)}")
print(f"  odd/even ratio           = {mp.nstr(ratio, 30)}")
print(f"  tanh(ln q0)              = {mp.nstr(tanh_lnq, 30)}")
print(f"  difference               = {mp.nstr(abs(ratio - tanh_lnq), 5)}")
assert abs(ratio - tanh_lnq) < mp.mpf("1e-55")
print()
print("  This is qou-hjs8's delta_CP, and the identification is now explained")
print("  rather than observed: delta_CP is the generator over the bar-even")
print("  companion, i.e. the bar-odd FRACTION of the degree-one channel.")


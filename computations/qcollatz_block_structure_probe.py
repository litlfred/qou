#!/usr/bin/env python3
"""Block structure of q-Collatz orbits on D_inf, and which heights descend.

Companion to the Lean reduction
content/quantum-observable-universe/lean/QOU/AppendixSurreals/collatz_block_descent.lean
(`reaches_cycle_of_block_descent_domainStable`), which weakens the convergence
requirement from per-STEP descent to per-BLOCK descent. This probe measures what
the blocks actually look like, and tests candidate N-valued heights against the
weaker requirement.

A block is one odd step followed by its run of even steps. Two questions:

  Q1. Are there blocks with v = 0 -- i.e. TWO CONSECUTIVE ODD STEPS? Nothing
      proved rules this out. If they occur, the tidy "odd then v evens" picture
      is incomplete.
  Q2. Does a natural height descend across each block? Candidates must be
      N-valued and strictly positive off the attractor (forced by
      block_descent_measure_pos_off_target), which is exactly what rules out
      every valuation -- so only heights are tested.

D_inf elements are generated by backward orbit from the attractor cycle (in
D_inf by construction) and each is re-verified forward. Exact integer Laurent
arithmetic; no float.

Exploratory research probe (NOT canonical production).
"""
import sys, json
from collections import Counter, deque
from pathlib import Path  # witness path must be FILE-relative, not cwd-relative

TWO = {1: 1, 0: 1}
THREE = {2: 1, 1: 1, 0: 1}
ONE = {0: 1}
ATTR_A = {-1: 1}
ATTR_B = {-1: 1, 0: 1}


def add(a, b, sb=1):
    r = dict(a)
    for e, c in b.items():
        r[e] = r.get(e, 0) + sb * c
        if r[e] == 0:
            del r[e]
    return r


def mul(a, b):
    r = {}
    for e1, c1 in a.items():
        for e2, c2 in b.items():
            r[e1 + e2] = r.get(e1 + e2, 0) + c1 * c2
    return {e: c for e, c in r.items() if c != 0}


def exact_div(num, den):
    if not num:
        return {}
    nmin, dmin = min(num), min(den)
    N = {e - nmin: c for e, c in num.items()}
    D = {e - dmin: c for e, c in den.items()}
    Ndeg, Ddeg = max(N), max(D)
    if Ndeg < Ddeg:
        return None
    dlead = D[Ddeg]
    rem, quot = dict(N), {}
    for k in range(Ndeg - Ddeg, -1, -1):
        rk = rem.get(k + Ddeg, 0)
        if rk == 0:
            continue
        if rk % dlead != 0:
            return None
        qk = rk // dlead
        quot[k] = qk
        for e, c in D.items():
            rem[e + k] = rem.get(e + k, 0) - qk * c
            if rem[e + k] == 0:
                del rem[e + k]
    if rem:
        return None
    return {e + (nmin - dmin): c for e, c in quot.items()}


def parity(P):
    v = sum(c * ((-1) ** e) for e, c in P.items())
    return 'E' if v == 0 else ('O' if v == -1 else None)


def step(P):
    p = parity(P)
    if p == 'E':
        return exact_div(P, TWO), 'E'
    if p == 'O':
        return exact_div(add(mul(THREE, P), ONE), TWO), 'O'
    return None, None


def key(P):
    return tuple(sorted(P.items()))


CYCLE = {key(ATTR_A), key(ATTR_B)}

# --- candidate N-valued heights, each strictly positive off the attractor ---
def h_l1(P):
    return sum(abs(c) for c in P.values())

def h_span(P):
    return (max(P) - min(P) + 1) if P else 0

def h_l1_span(P):
    return h_l1(P) + h_span(P)

CANDIDATES = {'L1': h_l1, 'span': h_span, 'L1+span': h_l1_span}


def orbit_to_cycle(P, budget=4000):
    """Forward orbit until the attractor cycle; returns the list of (P, branch)."""
    out, cur, n = [], dict(P), 0
    while n < budget:
        if key(cur) in CYCLE:
            return out, True
        nxt, br = step(cur)
        if nxt is None:
            return out, False
        out.append((cur, br))
        cur, n = nxt, n + 1
    return out, False


def blocks_of(trace):
    """Split an orbit trace into blocks: one 'O' step then its run of 'E's.
    Returns list of (start_P, v) where v = number of even steps after the odd."""
    res, i = [], 0
    while i < len(trace):
        P, br = trace[i]
        if br == 'O':
            v = 0
            j = i + 1
            while j < len(trace) and trace[j][1] == 'E':
                v += 1
                j += 1
            res.append((P, v, j))
            i = j
        else:
            i += 1
    return res


def even_preimage(P):
    return mul(TWO, P)


def odd_preimage(P):
    return exact_div(add(mul(TWO, P), ONE, sb=-1), THREE)


def run(depth=22):
    seen = set(CYCLE)
    frontier = deque([(dict(ATTR_A), 0), (dict(ATTR_B), 0)])
    nodes = 0
    v_hist = Counter()
    consecutive_odd = []          # blocks with v = 0 => two odd steps in a row
    block_desc = {c: Counter() for c in CANDIDATES}     # 'down'/'flat'/'up'
    step_desc = {c: Counter() for c in CANDIDATES}
    while frontier:
        P, d = frontier.popleft()
        if d >= depth:
            continue
        for Q in (even_preimage(P), odd_preimage(P)):
            if Q is None or not Q:
                continue
            kq = key(Q)
            if kq in seen:
                continue
            seen.add(kq)
            nodes += 1
            trace, ok = orbit_to_cycle(Q)
            if not ok:
                continue
            # per-STEP behaviour of each candidate (expected to fail)
            for i, (X, _br) in enumerate(trace):
                nxt, _ = step(X)
                for name, h in CANDIDATES.items():
                    a, b = h(X), h(nxt)
                    step_desc[name]['down' if b < a else ('flat' if b == a else 'up')] += 1
            # per-BLOCK behaviour
            for (X, v, j) in blocks_of(trace):
                v_hist[v] += 1
                if v == 0:
                    consecutive_odd.append(poly_str(X))
                endP = trace[j][0] if j < len(trace) else dict(ATTR_A)
                for name, h in CANDIDATES.items():
                    a, b = h(X), h(endP)
                    block_desc[name]['down' if b < a else ('flat' if b == a else 'up')] += 1
            frontier.append((Q, d + 1))
    return dict(
        depth=depth, nodes=nodes,
        block_v_histogram=dict(sorted(v_hist.items())),
        blocks_with_v_zero=len(consecutive_odd),
        consecutive_odd_examples=consecutive_odd[:5],
        per_step={c: dict(step_desc[c]) for c in CANDIDATES},
        per_block={c: dict(block_desc[c]) for c in CANDIDATES},
    )


def poly_str(P):
    if not P:
        return "0"
    return " ".join(f"{P[e]:+d}*q^{e}" for e in sorted(P, reverse=True))



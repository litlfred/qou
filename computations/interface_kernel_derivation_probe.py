#!/usr/bin/env python3
"""The interface kernel R_k(q,x), DERIVED and verified — not fitted.

`conj:binding-manybody-eq-jet-filtration` leaves the n=3 body-order weight
free: two anchors, three unknowns. Its own scope note says what would pin it
is the derived kernel R(q,x) of the q-difference equation

    G(qx; q) = R(q,x) * G(x; q)

and that deriving it is open. `binding_n3_forcing_probe` separately measured
that EXTRACTING the weights cannot substitute -- A=3 does not test the n=3
term, it defines it. So the kernel has to be derived or it is nothing.

## The derivation

Track jet degree with x. For an element E of H_n(q) define the grade
generating function

    G_E(x) = sum_g (total coefficient at grade g) * x^g       in Z[q,q^-1][x]

`QOU.Knot.JetGradePromotion` says a generator meeting no existing inversion
raises every grade by exactly one with coefficients intact. In this language
that is exactly

    G_{E.T}(x) = x * G_E(x)

-- multiplication by a fresh interface IS multiplication by x. That is the
whole bridge between the filtration and the generating function, and it is a
theorem rather than an ansatz.

For k crossings on one interface, the subalgebra generated by a single T is
2-dimensional (T^2 = A*T + 1, with A = q - q^-1), so

    T^k = f_k * T + f_{k-1} * 1,     f_1 = 1, f_2 = A, f_{k+1} = A f_k + f_{k-1}

and therefore

    R_k(q, x) = f_k(q) * x + f_{k-1}(q).

The recursion's characteristic equation is t^2 - A t - 1 = 0 with
A^2 + 4 = (q - q^-1)^2 + 4 = (q + q^-1)^2, so its roots are exactly

    t = q   and   t = -q^-1

-- the two Hecke eigenvalues, the symmetric and antisymmetric channels. Hence
the closed form

    f_k(q) = (q^k - (-1)^k q^-k) / (q + q^-1),

the alternating (balanced) q-integer. The kernel is not a free function: it
is fixed by the Hecke relation and the promotion theorem together.

## Verified, not asserted

Against the actual algebra on two disjoint nucleon blocks in H_6, for
k = 1..5: R_k predicts G_{E.T^k} EXACTLY -- every grade, every Laurent
coefficient. And the closed form agrees with the recursion for k = 1..6.

## Scope -- what this is and is not

It IS the single-interface kernel, derived from a proved theorem plus the
Hecke relation, with no fitted constant and no anchor.

It is NOT yet the kernel of the conjecture. That one governs the body-order
series across A, where interfaces are added between blocks that are no longer
disjoint once earlier bridges exist; the promotion hypothesis (no existing
inversion) has to be re-established at each step, and it is exactly the step
where `deuteron_bond_grade_split_probe` measured the split beginning. Nor is
the canonical interface a bare T^k -- it is sigma_g + d*I, whose scalar part
adds a further term this derivation does not carry.

So this pins the shape of R and where its q-dependence comes from, and leaves
the composition across A open. Stating that boundary because the temptation
here is to call a single-interface result the kernel.

Exact throughout: sparse Laurent over Z[q,q^-1]. No floats, no anchor.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from hecke_exact_laurent import (  # noqa: E402
    coxeter_length, lau_add, lau_mul, word_to_elem_fast,
)
from isospin_triplet_filtration_probe import P_A, N_B  # noqa: E402

A_COEF = {1: 1, -1: -1}


def grade_gf(E) -> dict:
    """G_E(x) as {x-power: Laurent(q)}."""
    out: dict = {}
    for w, c in E.terms.items():
        g = coxeter_length(w)
        out[g] = lau_add(out.get(g, {}), c)
    return {g: v for g, v in out.items() if v}


def f_rec(k: int) -> dict:
    """f_k by the recursion f_1=1, f_2=A, f_{k+1} = A f_k + f_{k-1}."""
    a, b = {}, {0: 1}
    for _ in range(k - 1):
        a, b = b, lau_add(lau_mul(A_COEF, b), a)
    return b


def f_closed(k: int) -> dict:
    """f_k = (q^k - (-1)^k q^-k) / (q + q^-1), by exact Laurent division."""
    r = {k: 1, -k: -(-1) ** k}
    den, out = {1: 1, -1: 1}, {}
    while r:
        hi = max(r)
        c, e = r[hi], hi - 1
        out[e] = out.get(e, 0) + c
        for de, dc in den.items():
            v = r.get(e + de, 0) - c * dc
            if v:
                r[e + de] = v
            else:
                r.pop(e + de, None)
    return {e: c for e, c in out.items() if c}


def main():
    print("The interface kernel R_k(q,x) = f_k(q)*x + f_{k-1}(q)\n")
    print("  closed form vs recursion:")
    for k in range(1, 7):
        ok = f_rec(k) == f_closed(k)
        print(f"    k={k}: {dict(sorted(f_rec(k).items()))}   match: {ok}")
        assert ok, f"closed form disagrees with the recursion at k={k}"

    print("\n  R_k against the actual algebra (two disjoint blocks, H_6):")
    base = word_to_elem_fast(6, P_A + N_B)
    G0, E = grade_gf(base), word_to_elem_fast(6, P_A + N_B)
    for k in range(1, 6):
        E = E.mul_gen(3)
        pred: dict = {}
        for g, c in G0.items():
            for shift, coef in ((1, f_rec(k)), (0, f_rec(k - 1) if k > 1 else {})):
                if not coef:
                    continue
                t = lau_mul(c, coef)
                if t:
                    pred[g + shift] = lau_add(pred.get(g + shift, {}), t)
        pred = {g: v for g, v in pred.items() if v}
        ok = pred == grade_gf(E)
        print(f"    k={k}: R_k predicts G exactly: {ok}")
        assert ok, f"the derived kernel failed at k={k}"

    print("\n  Roots of t^2 - A t - 1 are q and -q^-1 -- the Hecke eigenvalues.")
    print("  The kernel is fixed by the Hecke relation plus the promotion")
    print("  theorem. No fitted constant, no anchor, no free function.")
    return {"verified_k": list(range(1, 6))}


if __name__ == "__main__":
    main()

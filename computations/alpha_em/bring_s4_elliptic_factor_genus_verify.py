def perm_char(g):  # permutation character on 5 letters
    return sum(1 for i in range(5) if g(i) == i)


def chi_std(g):        # standard rep (4,1)
    return perm_char(g) - 1


def chi_std_sign(g):   # (2,1,1,1) = std ⊗ sign
    return (perm_char(g) - 1) * g.signature()


def inv_dim(gens, chi):
    H = PermutationGroup(gens)
    He = list(H.generate())
    return sum(chi(h) for h in He) // len(He)



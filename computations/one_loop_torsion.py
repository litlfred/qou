#!/usr/bin/env python3
# polynomial_q_not_applicable: hyperbolic-geometry numeric helper.
"""one_loop_torsion.py — the Dimofte-Garoufalidis 1-loop invariant, any number of cusps.

WHY THIS EXISTS

Three implementations of "the 1-loop determinant" exist in this repo and they
disagree. This is the one that is correct, promoted out of a probe so the
others can point at it instead of re-deriving it.

    whitehead_c_sigma_torsion.py     |tau(4_1)| = sqrt(3)     NOT invariant
    probes/one_loop_vs_nu_sdp_probe  |tau(4_1)| = sqrt(3)/2   INVARIANT   <- this
    probes/torsion_nu_sdp_probe.py   |T_mu(4_1)| = 3          Porti convention

`sqrt(3)/2` is Dimofte-Garoufalidis' own worked figure-eight example
(arXiv:1202.6268, eq. 3.2). The `sqrt(3)` in the first is exactly twice it —
the `1/2` that file's docstring claims is unnecessary "because the calibration
reproduces the known value sqrt(3)". See
`docs/audits/2026-08-07-one-loop-fix-impact-analysis.md`.

THE FORMULA (DG Defn 1.2 / Garoufalidis-Yoon 2411.03801 Defn 2.1)

    tau = +- (1/2) det( B ; P_1 ; ... ; P_c ) / prod_j zeta_j^{f_j} zeta'_j^{f'_j} zeta''_j^{f''_j}

with `zeta = 1/z`, `zeta' = 1/(1-z)`, `zeta'' = 1/(z(z-1))`; `P_i` the chosen
peripheral row at cusp `i` (meridian by default); `B` a basis of the edge
lattice (below); and `(f, f', f'')` a combinatorial flattening:

    f + f' + f'' = 1  per tetrahedron,     G f + G' f' + G'' f'' = 2  on edges

That flattening convention is DG Definition 2.1. It is worth stating because
reasoning from `z z' z'' = -1` suggests `f + f' + f'' = -1`, which has NO
integer solution at all (bean qou-fl4t).

MULTIPLE CUSPS — DERIVED HERE, NOT TAKEN FROM DG

DG state Definition 1.2 for one cusp and say only (Section 1.9): *"The
generalization to multiple cusps is also quite straightforward, but left out
mainly for simplicity of exposition."* There is no formula in the paper to
copy, so the `c >= 2` case below is derived. Three facts drive it, each
measured on 13 manifolds by
`probes/one_loop_multicusp_derivation_probe.py`:

 1. `sum_I G_Ii = sum_I G'_Ii = sum_I G''_Ii = 2` for EVERY cusp number, not
    just one. Each tetrahedron has six edges in three opposite pairs, one pair
    per shape type, and each is glued into exactly one edge class — cusps do
    not enter. DG attribute this identity to one-cuspedness ("every edge
    begins and ends at the cusp"), and an earlier version of the audit above
    repeated that and concluded the extension was blocked. It is not.
 2. Because `zeta + zeta' + zeta'' = 0`, fact 1 makes the N specialised edge
    rows sum to ZERO. Their rank is exactly `N - c` (measured), so the matrix
    needs `N - c` edge rows and `c` peripheral rows. That much is the obvious
    guess and it is right.
 3. The part that is NOT obvious: *which* `N - c` rows. Any independent SUBSET
    of edge rows spans the right complex subspace but can generate a proper
    SUBLATTICE of the edge lattice — index 2 in the cases observed — and the
    determinant then comes out doubled. Taking a Hermite-normal-form basis of
    the lattice generated by all N edge rows removes this. With a subset,
    `L6a4` and `L7a1` each show a stray factor of 2 in ~1 randomised
    triangulation in 30; with an HNF basis, 13 manifolds are invariant across
    every trial.

The specialised row depends only on the Neumann-Zagier pair
`(a_j, b_j) = (G_j - G''_j, G'_j - G''_j)`, since `zeta'' = -zeta - zeta'`; the
lattice in fact 3 is the lattice these pairs generate in `Z^{2N}`.

NORMALIZATION — READ THIS BEFORE USING MULTI-CUSP VALUES

The `1/2` is DG's, pinned at `c = 1` by their `4_1` example. Neither
triangulation invariance nor the change-of-curve law below can see a constant
that depends only on `c`, so THIS CONSTRUCTION CANNOT SETTLE WHETHER THE
MULTI-CUSP NORMALIZATION CARRIES AN EXTRA c-DEPENDENT FACTOR. That is exactly
the shape of the `2^{(c-1)/2}` per-cusp factor the `c_sigma` arc wanted
(bean qou-pn5j), so this module does not settle that question and must not be
cited as doing so. Ratios of these values at fixed `c`, and the change-of-curve
law at any `c`, are unaffected.

VALIDATION

`self_test()` checks, at ~60 digits:

  * DG's worked example, `|tau(4_1)| = sqrt(3)/2`.
  * The CHANGE-OF-CURVE LAW, cusp by cusp: replacing the meridian row of cusp
    `k` by that cusp's longitude row multiplies tau by the conjugate of the
    CUSP SHAPE of cusp `k` — which SnapPy computes from the cusp cross-section
    geometry with no reference to any of this. This is the check with real
    content at `c >= 2`: it tests each cusp separately, so it would fail if the
    peripheral rows were combined wrongly.
  * Agreement across independent presentations of the same manifold
    (`L5a1` = `5^2_1` = `m129`; `L6a4` = `t12067`; `L6a2` = `m203`).

Garoufalidis-Yoon prove 1-loop = adjoint torsion for TWO-BRIDGE knots, which
covers 4_1, 5_2, 6_2 — so the one-cusped leg is validated against a theorem.
There is no comparable theorem available for `c >= 2`.

PRECISION

Shapes are read at `bits_prec` derived from `mp.mp.dps` and converted through
decimal strings; the determinant is an mpmath determinant. The probe this came
from used `complex(s['rect'])` and `np.linalg.det`, i.e. float64 throughout
(bean qou-t0rf's class). The flattening is solved over the integers with sympy.

-- Ref: [dimofte-garoufalidis2013] arXiv:1202.6268, Defn 1.2, Defn 2.1, eq 3.2, Sec 1.9
-- Ref: [garoufalidis-yoon] arXiv:2411.03801, Defn 2.1 (symmetric normalization)
-- Ref: [neumann-zagier1985] volumes of hyperbolic 3-manifolds, cusp shape as d(log lambda)/d(log m)
"""
from __future__ import annotations

import itertools
import sys
from pathlib import Path

import mpmath as mp
import sympy as sp

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "substrate"))
from _precision import set_compute_dps  # noqa: E402

set_compute_dps()

_ZERO_TOL = mp.mpf(10) ** -40
_FLATTENING_SEARCH_CAP = 200_000


def _bits() -> int:
    return int(mp.mp.dps * 3.3219) + 16


def _shapes(M):
    """Tetrahedra shapes as mpc via decimal strings — never through float().

    SnapPy renders high-precision exponents with a space (`' E-79'`), which
    `mp.mpf` cannot parse, so the spaces are stripped. Without this the reader
    raises on any triangulation with a near-zero shape component.
    """
    return [mp.mpc(mp.mpf(str(s.real()).replace(" ", "")),
                   mp.mpf(str(s.imag()).replace(" ", "")))
            for s in M.tetrahedra_shapes("rect", bits_prec=_bits())]


def _log_rows(M):
    """Integer log-form gluing rows: N edges, then (meridian, longitude) per cusp."""
    return [[int(x) for x in r] for r in M.gluing_equations(form="log")]


def nz_pair(row, N):
    """Neumann-Zagier coordinates (a | b) = (G - G'', G' - G'') of a log row.

    The specialised row is `sum_j (a_j zeta_j + b_j zeta'_j) e_j`, because
    `zeta'' = -zeta - zeta'`. So `(a, b)` carries everything the determinant
    sees, and the edge LATTICE lives in `Z^{2N}`.
    """
    return ([row[3 * j] - row[3 * j + 2] for j in range(N)]
            + [row[3 * j + 1] - row[3 * j + 2] for j in range(N)])


def row_hnf(rows):
    """Echelon integer basis of the ROW LATTICE spanned by `rows`.

    Unimodular row operations only, so the lattice — not merely its rational
    span — is preserved. Using this instead of a subset of the generating rows
    is what makes the `c >= 2` determinant well defined; see fact 3 above.
    """
    A = [list(map(int, r)) for r in rows]
    if not A:
        return []
    m, n = len(A), len(A[0])
    r = 0
    for col in range(n):
        piv = next((i for i in range(r, m) if A[i][col] != 0), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        again = True
        while again:
            again = False
            for i in range(r + 1, m):
                if A[i][col] != 0:
                    if abs(A[i][col]) < abs(A[r][col]):
                        A[r], A[i] = A[i], A[r]
                    q = A[i][col] // A[r][col]
                    A[i] = [x - q * y for x, y in zip(A[i], A[r])]
                    if A[i][col] != 0:
                        again = True
        if A[r][col] < 0:
            A[r] = [-x for x in A[r]]
        r += 1
    return A[:r]


def _specialise(v, N, zeta, zetap):
    return [v[j] * zeta[j] + v[N + j] * zetap[j] for j in range(N)]


def _independent(rows, k):
    """Indices of the first `k` rows independent over C (Gaussian elimination)."""
    basis, chosen = [], []
    for i, v in enumerate(rows):
        v = list(v)
        for b in basis:
            p = next(t for t, x in enumerate(b) if abs(x) > _ZERO_TOL)
            if abs(v[p]) > _ZERO_TOL:
                f = v[p] / b[p]
                v = [a - f * bb for a, bb in zip(v, b)]
        if any(abs(x) > _ZERO_TOL for x in v):
            basis.append(v)
            chosen.append(i)
        if len(chosen) == k:
            break
    return chosen


def flattening(M, full_neumann: bool = True):
    """A combinatorial flattening (f, f', f''), DG Defn 2.1, over the integers.

    With `full_neumann` the peripheral conditions (every meridian and longitude
    row evaluating to 0) are imposed as well, which is Neumann's actual
    definition; free parameters are then searched modulo the denominators for
    an integral point. Falls back to the edge conditions alone if that search
    would be too large or finds nothing.

    `|tau|` does not depend on the choice: the kernel of the edge conditions
    moves the monomial only by a phase, measured to ~1e-70 on every manifold in
    the probe. DG prove full flattening-independence (their Section 3.5).
    """
    N, c = M.num_tetrahedra(), M.num_cusps()
    R = _log_rows(M)
    ne = len(R) - 2 * c
    f = sp.symbols(f"f0:{N}")
    fp = sp.symbols(f"fp0:{N}")
    fpp = sp.symbols(f"fpp0:{N}")
    syms = list(f) + list(fp) + list(fpp)

    def solve(extra):
        eqs = [sp.Eq(f[i] + fp[i] + fpp[i], 1) for i in range(N)]
        for I in list(range(ne)) + list(extra):
            tgt = 2 if I < ne else 0
            eqs.append(sp.Eq(sum(R[I][3 * j] * f[j] + R[I][3 * j + 1] * fp[j]
                                 + R[I][3 * j + 2] * fpp[j] for j in range(N)), tgt))
        sols = list(sp.linsolve(eqs, syms))
        if not sols:
            return None
        sol = list(sols[0])
        free = sorted({s for e in sol for s in e.free_symbols}, key=str)
        if not free:
            v = [sp.nsimplify(e) for e in sol]
            return [int(x) for x in v] if all(x.is_Integer for x in v) else None
        d = 1
        for e in sol:
            terms = sp.Poly(e, *free).coeffs() + [e.subs({s: 0 for s in free})]
            for q in terms:
                d = sp.ilcm(d, sp.Rational(q).q)
        d = int(d)
        if d ** len(free) > _FLATTENING_SEARCH_CAP:
            v = [sp.nsimplify(e.subs({s: sp.Integer(0) for s in free})) for e in sol]
            return [int(x) for x in v] if all(x.is_Integer for x in v) else None
        for t in itertools.product(range(d), repeat=len(free)):
            v = [sp.nsimplify(e.subs(dict(zip(free, t)))) for e in sol]
            if all(x.is_Integer for x in v):
                return [int(x) for x in v]
        return None

    v = solve([ne + k for k in range(2 * c)]) if full_neumann else None
    if v is None:
        v = solve([])
    if v is None:
        raise ValueError("no integral flattening")
    return v[:N], v[N:2 * N], v[2 * N:]


def _curve_row(R, ne, i, spec):
    """Log row of the peripheral curve `spec` on cusp `i`.

    `spec` is either the legacy `0` / `1` (meridian / longitude) or a pair
    `(p, q)` meaning `p*meridian + q*longitude`. The log-form gluing equation
    of a peripheral curve is LINEAR in its homology class, so the general row
    is that integer combination of the two stored rows — no new geometry, and
    `nz_pair` stays valid downstream because it is linear too.
    """
    mer, lon = R[ne + 2 * i], R[ne + 2 * i + 1]
    if isinstance(spec, (tuple, list)):
        p, q = int(spec[0]), int(spec[1])
    elif spec == 0:
        p, q = 1, 0
    elif spec == 1:
        p, q = 0, 1
    else:
        raise ValueError(f"curve spec {spec!r} must be 0, 1, or a pair (p, q)")
    if (p, q) == (0, 0):
        raise ValueError(f"curve spec on cusp {i} is (0, 0) — not a curve")
    return [p * a + q * b for a, b in zip(mer, lon)]


def one_loop(M, curves=None):
    """DG 1-loop invariant tau of a hyperbolic manifold with any cusp number.

    `curves` picks the peripheral row per cusp. Legacy form: 0 = meridian
    (default), 1 = longitude; changing one entry multiplies tau by that cusp's
    shape (conjugated), see the module docstring. General form: a pair
    `(p, q)` meaning `p*meridian + q*longitude` — which is what a Dehn twist
    along the cusp does to the framing, and is the only way to ask about the
    SAME manifold carrying a different peripheral structure (bean qou-vdvT).
    The two forms may be mixed across cusps.

    Returns an `mpc`. The sign is not determined — DG's tau is defined up to
    one — and at `c >= 2` the overall normalization is inherited from `c = 1`,
    so read moduli and ratios, not the absolute constant.
    """
    N, c = M.num_tetrahedra(), M.num_cusps()
    curves = [0] * c if curves is None else list(curves)
    if len(curves) != c:
        raise ValueError(f"curves has length {len(curves)}, expected {c}")
    R = _log_rows(M)
    ne = len(R) - 2 * c
    z = _shapes(M)
    zeta = [1 / x for x in z]
    zetap = [1 / (1 - x) for x in z]
    zetapp = [1 / (x * (x - 1)) for x in z]

    basis = row_hnf([nz_pair(R[i], N) for i in range(ne)])
    spec = [_specialise(v, N, zeta, zetap) for v in basis]
    keep = _independent(spec, N - c)
    if len(keep) < N - c:
        raise ValueError(
            f"edge lattice specialises to rank {len(keep)} < N - c = {N - c}; "
            "the triangulation may not be geometric"
        )
    periph = [_specialise(nz_pair(_curve_row(R, ne, i, curves[i]), N),
                          N, zeta, zetap)
              for i in range(c)]

    rows = [spec[i] for i in keep] + periph
    A = mp.matrix(N, N)
    for i in range(N):
        for j in range(N):
            A[i, j] = rows[i][j]
    det = mp.det(A)

    fv, fpv, fppv = flattening(M)
    denom = mp.mpc(1)
    for j in range(N):
        denom *= zeta[j] ** fv[j] * zetap[j] ** fpv[j] * zetapp[j] ** fppv[j]
    return det / (2 * denom)


def cusp_shape_residuals(M):
    """Per-cusp change-of-curve residuals against SnapPy's cusp shapes.

    `tau_lambda_k / tau_mu` must equal `conj(cusp shape of cusp k)`. Returns one
    relative deviation per cusp. SnapPy's cusp shapes come from the cusp
    cross-section, so this is an outside check, not self-consistency.
    """
    import snappy

    c = M.num_cusps()
    base = one_loop(M)
    hp = snappy.ManifoldHP(M.name()) if hasattr(M, "name") else snappy.ManifoldHP(str(M))
    shapes = [mp.mpc(mp.mpf(str(x.real).replace(" ", "")),
                     mp.mpf(str(x.imag).replace(" ", "")))
              for x in hp.cusp_info("shape")]
    targets = [mp.conj(s) for s in shapes]
    out, used = [], [False] * c
    for k in range(c):
        cur = [0] * c
        cur[k] = 1
        r = one_loop(M, cur) / base
        best, bi = None, None
        for i, t in enumerate(targets):
            if used[i]:
                continue
            d = abs(r - t) / abs(t)
            if best is None or d < best:
                best, bi = d, i
        used[bi] = True
        out.append(best)
    return out


def self_test() -> int:
    import snappy

    ok = True
    tau41 = one_loop(snappy.Manifold("4_1"))
    target = mp.sqrt(3) / 2
    rel = abs(abs(tau41) - target) / target
    good = rel < mp.mpf("1e-20")
    ok &= bool(good)
    print(f"  |tau(4_1)|  = {mp.nstr(abs(tau41), 25)}")
    print(f"  sqrt(3)/2   = {mp.nstr(target, 25)}   rel={mp.nstr(rel, 4)}"
          f"   {'OK (DG eq 3.2)' if good else 'FAIL'}")

    print("  one-cusped:")
    for k in ("5_2", "6_2", "7_4"):
        print(f"    |tau({k})| = {mp.nstr(abs(one_loop(snappy.Manifold(k))), 20)}")
    print("  multi-cusped (derived; normalization inherited from c=1):")
    for k in ("L5a1", "L6a2", "L6a1", "L6a4", "s776"):
        M = snappy.Manifold(k)
        print(f"    |tau({k})| = {mp.nstr(abs(one_loop(M)), 20)}   "
              f"(c={M.num_cusps()}, N={M.num_tetrahedra()})")

    print("  change-of-curve law vs SnapPy cusp shapes (per cusp):")
    for k in ("4_1", "L5a1", "L6a4", "s776"):
        M = snappy.Manifold(k)
        devs = cusp_shape_residuals(M)
        worst = max(devs)
        hit = worst < mp.mpf("1e-25")
        ok &= bool(hit)
        print(f"    {k:6} c={M.num_cusps()}  max rel dev = {mp.nstr(worst, 4)}"
              f"   {'OK' if hit else 'FAIL'}")

    print("  independent presentations of the same manifold agree:")
    for names in (("L5a1", "5^2_1", "m129"), ("L6a4", "t12067"), ("L6a2", "m203")):
        vals = [abs(one_loop(snappy.Manifold(n))) for n in names]
        agree = all(abs(v - vals[0]) / vals[0] < mp.mpf("1e-25") for v in vals)
        ok &= bool(agree)
        print(f"    {' = '.join(names):28} {mp.nstr(vals[0], 20)}"
              f"   {'OK' if agree else 'FAIL'}")

    print("SELF-TEST", "PASSED" if ok else "FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(self_test())

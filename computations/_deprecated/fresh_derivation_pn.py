#!/usr/bin/env python3
"""
Fresh p/n derivation, Steps A-D (descriptive):

  A. Build proton/neutron NF (reuse hecke_core chains)
  B. Enumerate channel branches at each mixed (1, -h/2) factor
  C. For each branch, construct the physical braid as tuple of ±σ_i
     integers and take the trace closure
  D. Identify closure topology via SnapPy; report V_hyp if hyperbolic

Output: fresh-derivation-pn-steps-A-D.witness.json

After this baseline, Steps E-G (SDP dual y_λ, partition sum with
Hecke energy weighting, mass assembly) require user input on three
architectural questions flagged in docs/fresh-derivation-pn-2026-04.md.
"""

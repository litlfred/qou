try:
    import snappy
    HAVE_SNAPPY = True
except Exception:
    HAVE_SNAPPY = False


def factor_to_braid_sign(c: float, d: float, h: float) -> list:
    """Map a Hecke factor (c, d) at generator index `gen` to a list of
    possible ±1 signs (for σ_gen^±1) with their weight.

    - (1, 0)         → σ  (positive), single branch, weight +1
    - (1, -h)        → σ⁻¹, single branch, weight +1 (since σ⁻¹ = σ - h)
    - (1, -h/2)      → (σ + σ⁻¹)/2, two branches with weight 1/2 each
    - (0, 1)         → identity, no crossing; weight +1, sign 0
    - (c, d) other   → fall back to 'algebraic' (no single physical sign)

    Returns list of (sign ∈ {+1, -1, 0}, weight).
    """
    # (1, 0) → σ  (plain crossing)
    if abs(c - 1) < 1e-9 and abs(d) < 1e-9:
        return [(+1, 1.0)]
    # (1, -h) → σ⁻¹
    if abs(c - 1) < 1e-9 and abs(d + h) < 1e-9:
        return [(-1, 1.0)]
    # (1, -h/2) → mixed  (σ + σ⁻¹)/2
    if abs(c - 1) < 1e-9 and abs(d + h / 2) < 1e-9:
        return [(+1, 0.5), (-1, 0.5)]
    # (0, 1) → identity (no braid generator)
    if abs(c) < 1e-9 and abs(d - 1) < 1e-9:
        return [(0, 1.0)]
    # Unknown algebraic factor — keep symbolic weight
    return [(None, (c, d))]


def enumerate_branches(g0_chain: list, g1_chain: list, h: float) -> list:
    """Enumerate (sign_sequence_g0, sign_sequence_g1, weight) for all
    physical-braid branches generated by channel choices at mixed
    factors."""
    # Build per-factor branch list for g0 and g1
    g0_branches = [factor_to_braid_sign(c, d, h) for (c, d) in g0_chain]
    g1_branches = [factor_to_braid_sign(c, d, h) for (c, d) in g1_chain]

    def _expand(branches):
        """Take list of branch lists (per factor) and return the
        cartesian product of (sign_seq, total_weight)."""
        results = [([], 1.0)]
        for factor_options in branches:
            new = []
            for (seq, w) in results:
                for (sgn, sw) in factor_options:
                    if not isinstance(sw, float):
                        # algebraic fall-through
                        continue
                    seq2 = list(seq)
                    if sgn != 0:
                        seq2.append(sgn)
                    new.append((seq2, w * sw))
            results = new
        return results

    g0_expanded = _expand(g0_branches)
    g1_expanded = _expand(g1_branches)

    out = []
    for (s0, w0) in g0_expanded:
        for (s1, w1) in g1_expanded:
            out.append((tuple(s0), tuple(s1), w0 * w1))
    return out


def physical_braid_word(s0_seq: tuple, s1_seq: tuple) -> list:
    """Convert (σ_0 sign sequence, σ_1 sign sequence) into a single
    braid word in B_3 notation.

    SnapPy convention: braid word is a list of ±(i+1) for generator
    σ_i^±1. So gen 0 = ±1, gen 1 = ±2.
    """
    word = []
    # Put g0 sequence first, then g1 sequence (matches how the NF was
    # constructed in nucleon_gen_chains: g0 factors accumulated, then g1).
    for s in s0_seq:
        word.append(s * 1)   # gen 0 → ±1
    for s in s1_seq:
        word.append(s * 2)   # gen 1 → ±2
    return word


def closure_topology(braid_word: list):
    """Build the braid closure via SnapPy and try to identify the link.

    Returns dict with: n_components, volume, volume_str, is_hyperbolic,
    identification string (triangulation name if matches catalog), and
    the underlying raw link data for inspection.
    """
    if not HAVE_SNAPPY:
        return {"snappy_available": False,
                "note": "SnapPy not installed; cannot compute closure"}
    if len(braid_word) == 0:
        return {"braid_word": [], "n_components": 3,
                "note": "empty braid — 3-component unlink",
                "volume_str": "0"}
    try:
        L = snappy.Link(braid_closure=braid_word)
    except Exception as e:
        return {"braid_word": braid_word,
                "error_link_build": f"{type(e).__name__}: {e}"}
    n_components = len(L.link_components)

    # Try to get a manifold + volume
    out = {"braid_word": list(braid_word),
            "n_components": n_components,
            "n_crossings": L.crossings and len(L.crossings) or 0}
    try:
        M = L.exterior()
        try:
            v = M.volume()
            v_real = float(v.real if hasattr(v, "real") else v)
            out["volume"] = v_real
            out["volume_str"] = f"{v_real:.10f}"
            # "Hyperbolic" heuristic: nonzero volume and solution
            # type indicates geometric structure is found.
            out["is_hyperbolic"] = abs(v_real) > 1e-6
        except Exception as e:
            out["volume"] = None
            out["note_volume"] = f"volume failed: {type(e).__name__}"
            out["is_hyperbolic"] = False
        try:
            # Try high-precision volume if manifold is hyperbolic
            if out.get("is_hyperbolic"):
                Mh = M.high_precision()
                import mpmath
                with mpmath.workdps(40):
                    vh = Mh.volume()
                    vh_r = vh.real if hasattr(vh, "real") else vh
                    out["volume_high_precision"] = mpmath.nstr(
                        mpmath.mpf(str(vh_r)), 30)
        except Exception:
            pass
        try:
            # Identify against catalog if possible
            from snappy import CensusKnots
            # SnapPy doesn't have a direct "identify from braid word"
            # but we can get the manifold's name if it matches a known
            # triangulation
            out["manifold_name"] = getattr(M, "name", lambda: "unknown")()
        except Exception:
            pass
    except Exception as e:
        out["error_exterior"] = f"{type(e).__name__}: {e}"
    return out


def process_particle(name: str, g0: list, g1: list, h: float) -> dict:
    print(f"\n{'=' * 90}")
    print(f"{name}")
    print(f"{'=' * 90}")
    print(f"  g0 chain ({len(g0)} factors): {g0}")
    print(f"  g1 chain ({len(g1)} factors): {g1}")
    branches = enumerate_branches(g0, g1, h)
    print(f"  → {len(branches)} physical-braid branches")
    print()
    print(f"  {'branch':<4} {'weight':>10} {'braid word':<34} "
          f"{'ncomp':>5} {'volume':>14} {'hyp?':>5}")
    print(f"  {'-'*76}")
    details = []
    for k, (s0, s1, w) in enumerate(branches):
        word = physical_braid_word(s0, s1)
        topo = closure_topology(word)
        vstr = (f"{topo.get('volume'):.6f}" if topo.get("volume") is not None
                 else "n/a")
        hyp = "y" if topo.get("is_hyperbolic") else "n"
        word_str = str(word) if len(str(word)) < 34 else str(word)[:30] + "..."
        print(f"  {k:<4} {w:>10.5f} {word_str:<34} "
              f"{topo.get('n_components','?'):>5} {vstr:>14} {hyp:>5}")
        details.append({
            "branch_idx": k,
            "channel_weight": w,
            "s0_signs": list(s0),
            "s1_signs": list(s1),
            "braid_word": word,
            **topo,
        })
    return {"name": name,
            "n_branches": len(branches),
            "g0_chain": [[c, d] for (c, d) in g0],
            "g1_chain": [[c, d] for (c, d) in g1],
            "branches": details}


def main() -> int:
    print("=" * 90)
    print("FRESH DERIVATION — STEPS A-D")
    print("=" * 90)
    print(f"  q_0 = {float(Q0):.10f}")
    print(f"  H_A = {float(H_A_VAL):.10f}")
    print(f"  SnapPy available: {HAVE_SNAPPY}")

    h = float(H_A_VAL)
    p_data = process_particle("PROTON (uud)",
                                _PROTON_G0, _PROTON_G1, h)
    n_data = process_particle("NEUTRON (udd)",
                                _NEUTRON_G0, _NEUTRON_G1, h)

    # Summary
    print(f"\n{'=' * 90}")
    print("SUMMARY")
    print('=' * 90)
    for name, d in [("proton", p_data), ("neutron", n_data)]:
        vols = [b.get("volume") for b in d["branches"]
                if b.get("volume") is not None and b.get("is_hyperbolic")]
        weights = [b["channel_weight"] for b in d["branches"]]
        hyp_count = sum(1 for b in d["branches"] if b.get("is_hyperbolic"))
        weighted_v = sum(b["channel_weight"] * b.get("volume", 0)
                          for b in d["branches"]
                          if b.get("volume") is not None)
        print(f"  {name}: {d['n_branches']} branches, {hyp_count} hyperbolic")
        if hyp_count:
            print(f"    hyperbolic volumes: {vols}")
            print(f"    channel-weighted mean V_hyp = {weighted_v:.6f}")

    witness = {
        "computation": "fresh-derivation-pn-steps-A-D",
        "description": (
            "Steps A-D of the fresh derivation: enumerate physical-"
            "braid branches for proton/neutron via channel choices at "
            "mixed ud factors, take trace closure, report topology and "
            "hyperbolic volume.  Steps E-G (SDP dual + mass assembly) "
            "deferred pending user input on architectural choices "
            "flagged in docs/fresh-derivation-pn-2026-04.md."
        ),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "q_0": float(Q0),
        "H_A": float(H_A_VAL),
        "snappy_available": HAVE_SNAPPY,
        "proton": p_data,
        "neutron": n_data,
    }
    out = Path(__file__).parent / "fresh-derivation-pn-steps-A-D.witness.json"
    out.write_text(json.dumps(witness, indent=2, default=str))
    print(f"\n  Witness: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

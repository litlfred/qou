"""
Explicit level-1 V̂_i^(1) for the proton and neutron via brane-tower
prolongation A_{n+1} = A_n ⊗ Ω¹(A_n).

For a Frobenius algebra A over a base carrying q-parameter, Ω¹(A) is
generated by Kähler differentials.  The Hecke-algebra realisation
uses the JUCYS–MURPHY elements L_k as a basis for the "transient"
level-1 contributions; acting with L_k twists each per-generator
V̂_i^(0) to a level-1 V̂_i^(1).

For our pragmatic purposes, a computationally tractable proxy for
the Ω¹ contribution is the **logarithmic q-derivative** of V̂:

    V̂_i^(1) := q · ∂V̂_i^(0) / ∂q

This mirrors how Kähler differentials on the Hecke algebra act: the
Ω¹-direction is generated by ∂/∂ln q at each per-generator chain.
The jet-scale factor from the recursive tower then suppresses the
level-1 contribution by ℏ_q²:

    m^(1) = ℏ_q² · Σ_i  V̂_i^(1)·∂Φ_q/∂V̂ + cross-terms

giving

    m_corrected = m^(0) · (1 − α · ℏ_q²)   with  α = [2]_q   (first test)

For the NEUTRON, we additionally test:
    (a) the SAME α (proton-fitted) — expected to fail per the earlier
        −56% tower result
    (b) a NEUTRON-SPECIFIC α from the ratio of ∂V̂_0/∂q(n) to
        ∂V̂_0/∂q(p) — if the Ω¹ direction shifts differently for
        udd, this captures it

Output: level1-vhat-brane-tower.witness.json
"""
from __future__ import annotations

import math
import sys
import warnings

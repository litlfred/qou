def Phi_q(v, q, max_iter=2000, tol=1e-16):
    if abs(v) >= abs(q):
        return float('inf')
    qi = 1.0 / q
    prod = 1.0
    coef = qi
    for k in range(1, max_iter + 1):
        term = 1.0 - coef * v
        if abs(term) < 1e-300:
            return float('inf')
        prod /= term
        if abs(coef * v) < tol:
            break
        coef *= qi
    return prod


def vertex_volume_at_q(chain, q: float) -> float:
    """V̂^full evaluated at arbitrary q (for finite differences)."""
    qi = 1.0 / q
    h = q - qi
    # Same Plancherel weights regardless of q (structural) — these
    # are held fixed for a (differential) comparison.
    a, b = 0.0, 1.0
    sp, ap = 1.0, 1.0
    for (c, d_cd) in chain:
        # For the ℏ-chain, the (c, d) tuples depend on q (since d = -h or -h/2).
        # Detect and re-evaluate h-dependent d at the new q.
        if abs(d_cd) < 1e-12:
            d_q = 0.0
        elif abs(d_cd + float(H_A_VAL)) < 1e-9:
            d_q = -h
        elif abs(d_cd + 0.5 * float(H_A_VAL)) < 1e-9:
            d_q = -h / 2.0
        else:
            d_q = d_cd
        a, b = a * c * h + a * d_q + b * c, a * c + b * d_q
        sp *= c * q + d_q
        ap *= -c * qi + d_q
    V_std = float(Z_MARKOV) * a + b  # using fixed z (Jones-Ocneanu)
    return float(W_SYM) * sp + float(W_STD) * V_std + float(W_ALT) * ap


def q_derivative_of_V(chain, q: float, h_step: float = 1e-6) -> float:
    """∂V̂/∂q via central finite difference."""
    v_plus = vertex_volume_at_q(chain, q + h_step)
    v_minus = vertex_volume_at_q(chain, q - h_step)
    return (v_plus - v_minus) / (2 * h_step)


def tower(V0, V1, z_val, q):
    absV0 = abs(V0)
    absV1 = abs(V1)
    prod = abs(V0 * V1)
    return (prod + Phi_q(absV0, q) + Phi_q(absV1, q)
             + z_val ** 2 * Phi_q(prod, q))


def main():
    w = WitnessBuilder("level1-vhat-brane-tower",
                        engine="finite-diff q-derivative")
    w.set_description(
        "Compute explicit level-1 V̂_i^(1) = q·∂V̂/∂q via finite "
        "difference, apply ℏ_q² jet suppression, and test whether "
        "this closes the proton −0.14% residual and/or the neutron "
        "−56% gap."
    )

    q = float(Q_NUM)
    h = float(H_A_VAL)
    hbar_q_sq = ((q - 1) / q) ** 2
    two_q = q + 1 / q
    z_val = float(Z_MARKOV)

    # Level-0 V̂
    Ve = vertex_volume_at_q([(1.0, 0.0)] * 3, q)
    Vp0 = vertex_volume_at_q(_PROTON_G0, q)
    Vp1 = vertex_volume_at_q(_PROTON_G1, q)
    Vn0 = vertex_volume_at_q(_NEUTRON_G0, q)
    Vn1 = vertex_volume_at_q(_NEUTRON_G1, q)

    # Level-1 V̂^(1) = q·∂V̂/∂q
    dVe = q * q_derivative_of_V([(1.0, 0.0)] * 3, q)
    dVp0 = q * q_derivative_of_V(_PROTON_G0, q)
    dVp1 = q * q_derivative_of_V(_PROTON_G1, q)
    dVn0 = q * q_derivative_of_V(_NEUTRON_G0, q)
    dVn1 = q * q_derivative_of_V(_NEUTRON_G1, q)

    print("=" * 100)
    print("LEVEL-1 V̂^(1) = q·∂V̂/∂q   (brane-tower Ω¹ proxy)")
    print("=" * 100)
    print(f"  q_0 = {q:.10f}   ℏ_q² = {hbar_q_sq:.6f}")
    print()
    print(f"  {'chain':<10} {'V̂^(0)':>14} {'V̂^(1) = q·∂V̂/∂q':>20} "
          f"{'ℏ_q² · V̂^(1)':>18} {'frac V̂^(0)':>12}")
    for name, V0, dV in [("e", Ve, dVe),
                          ("p g0", Vp0, dVp0), ("p g1", Vp1, dVp1),
                          ("n g0", Vn0, dVn0), ("n g1", Vn1, dVn1)]:
        frac = (hbar_q_sq * dV / V0) if abs(V0) > 1e-12 else 0
        print(f"  {name:<10} {V0:>+14.6f} {dV:>+20.6f} "
              f"{hbar_q_sq*dV:>+18.6f} {frac*100:>+11.3f}%")
    print()

    # Mass-endomorphism tower at level 0 + level 1 shift
    m_e_0 = abs(Ve) + Phi_q(abs(Ve), q)
    m_p_0_H = tower(Vp0, Vp1, z_val, q)
    m_n_0_H = tower(Vn0, Vn1, z_val, q)
    m_p_0 = (m_p_0_H / m_e_0) * M_E_MEV
    m_n_0 = (m_n_0_H / m_e_0) * M_E_MEV

    # Level-1 shift: apply V̂_i^(0) → V̂_i^(0) + ℏ_q² · V̂_i^(1)
    Vp0_1 = Vp0 + hbar_q_sq * dVp0
    Vp1_1 = Vp1 + hbar_q_sq * dVp1
    Vn0_1 = Vn0 + hbar_q_sq * dVn0
    Vn1_1 = Vn1 + hbar_q_sq * dVn1
    Ve_1 = Ve + hbar_q_sq * dVe

    m_e_1 = abs(Ve_1) + Phi_q(abs(Ve_1), q)
    m_p_1_H = tower(Vp0_1, Vp1_1, z_val, q)
    m_n_1_H = tower(Vn0_1, Vn1_1, z_val, q)
    m_p_1 = (m_p_1_H / m_e_1) * M_E_MEV
    m_n_1 = (m_n_1_H / m_e_1) * M_E_MEV

    print("─" * 100)
    print(f"{'':<10} {'m^(0) MeV':>14} {'m^(0+1) MeV':>14} "
          f"{'CODATA':>12} {'err (L0)':>10} {'err (L0+1)':>12}")
    print(f"  {'m_p':<10} {m_p_0:>14.4f} {m_p_1:>14.4f} {M_P_MEV:>12.4f} "
          f"{(m_p_0-M_P_MEV)/M_P_MEV*100:>+9.3f}% "
          f"{(m_p_1-M_P_MEV)/M_P_MEV*100:>+11.3f}%")
    print(f"  {'m_n':<10} {m_n_0:>14.4f} {m_n_1:>14.4f} {M_N_MEV:>12.4f} "
          f"{(m_n_0-M_N_MEV)/M_N_MEV*100:>+9.3f}% "
          f"{(m_n_1-M_N_MEV)/M_N_MEV*100:>+11.3f}%")
    print()

    # Try a DIFFERENT level-1 correction: multiplicative on m, not on V̂.
    # m_corrected = m^(0) / (1 + α · ℏ_q²)
    # Fit α from proton to close -0.136% exactly, apply same α to n.
    target_p = M_P_MEV / m_p_0  # geometric-series limit factor
    alpha_fit = (1.0 / target_p - 1.0) / hbar_q_sq
    m_p_mult = m_p_0 / (1 + alpha_fit * hbar_q_sq)
    m_n_mult = m_n_0 / (1 + alpha_fit * hbar_q_sq)
    print("─" * 100)
    print(f"MULTIPLICATIVE level-1 correction m/(1 + α·ℏ_q²):")
    print(f"  fit α from proton CODATA: α = {alpha_fit:.6f}  (vs [2]_q = {two_q:.4f})")
    print(f"  m_p corrected = {m_p_mult:.4f} MeV   err = {(m_p_mult-M_P_MEV)/M_P_MEV*100:+.5f}% (exact by construction)")
    print(f"  m_n corrected = {m_n_mult:.4f} MeV   err = {(m_n_mult-M_N_MEV)/M_N_MEV*100:+.3f}%")
    print()

    # Now try NEUTRON-SPECIFIC α from neutron's V̂ structure
    # Rationale: if Ω¹ direction for udd differs from uud, neutron
    # should have its own α.  Use ∂V̂_0^n/∂q · ∂V̂_0^p/∂q ratio as a
    # structural handle.
    ratio_dV0_n_over_p = dVn0 / dVp0 if abs(dVp0) > 1e-12 else 1.0
    alpha_n_candidate = alpha_fit * ratio_dV0_n_over_p
    target_n_correction = (m_n_0 / M_N_MEV - 1.0) / hbar_q_sq
    print("─" * 100)
    print("NEUTRON-SPECIFIC α probe:")
    print(f"  ∂V̂_0^n/∂q / ∂V̂_0^p/∂q = {ratio_dV0_n_over_p:+.6f}")
    print(f"  α_n (= α_p · ratio)    = {alpha_n_candidate:.6f}")
    print(f"  m_n / (1 + α_n·ℏ_q²)   = {m_n_0/(1+alpha_n_candidate*hbar_q_sq):.4f} MeV")
    print(f"  required α_n to hit CODATA exactly = {-target_n_correction:.6f}")
    print()

    # Alternative: LOG-FORM binding-style for neutron
    # Use B = -α · Φ_1 = -α · (log |V_atom| - log |V_free|) form
    print("─" * 100)
    print("NEUTRON ALTERNATIVE tower shape (log-form):")
    # m = α · exp(log|V_0 V_1|) = α · |V_0 V_1|  at leading order
    # but full = α · [|V_0 V_1| · (1 + ℏ_q-correction)]
    # Try: replace Φ_q(V) with ln|Φ_q(V)| in each term
    def log_Phi(v, q):
        return math.log(abs(Phi_q(v, q))) if abs(v) < abs(q) else float('inf')

    m_n_log = (abs(Vn0 * Vn1) + log_Phi(abs(Vn0), q) + log_Phi(abs(Vn1), q)
                + z_val**2 * log_Phi(abs(Vn0*Vn1), q))
    m_p_log = (abs(Vp0 * Vp1) + log_Phi(abs(Vp0), q) + log_Phi(abs(Vp1), q)
                + z_val**2 * log_Phi(abs(Vp0*Vp1), q))
    m_e_log = abs(Ve) + log_Phi(abs(Ve), q)
    m_p_log_MeV = (m_p_log / m_e_log) * M_E_MEV
    m_n_log_MeV = (m_n_log / m_e_log) * M_E_MEV
    print(f"  log-form m_p = {m_p_log_MeV:.4f} MeV  err = {(m_p_log_MeV-M_P_MEV)/M_P_MEV*100:+.3f}%")
    print(f"  log-form m_n = {m_n_log_MeV:.4f} MeV  err = {(m_n_log_MeV-M_N_MEV)/M_N_MEV*100:+.3f}%")
    print()

    print("=" * 100)
    print("VERDICT on items 1 and 3:")
    print("=" * 100)
    print(f"  Item 3 (proton residual): Multiplicative correction with")
    print(f"    α_fit = {alpha_fit:.4f} closes proton exactly to CODATA.")
    print(f"    Required α_fit is close to [2]_q = {two_q:.4f} (within 7%),")
    print(f"    consistent with the [2]_q·ℏ_q² structural ansatz but not")
    print(f"    exact.  Explicit brane-tower V̂^(1) via q-derivative gives")
    print(f"    a direction but doesn't pin the magnitude.")
    print()
    print(f"  Item 1 (neutron): Proton's α_fit applied to neutron gives")
    print(f"    m_n = {m_n_mult:.2f} MeV, still {(m_n_mult-M_N_MEV)/M_N_MEV*100:+.2f}% off.")
    print(f"    Required α_n to close neutron exactly = {-target_n_correction:.4f},")
    print(f"    but this is not physically structural — it's fitting a")
    print(f"    −56% gap that requires DIFFERENT physics (e.g., a new")
    print(f"    inter-nucleon tower term for udd, beyond the proton-")
    print(f"    calibrated geometric series).")

    w.add_data("params", {
        "q_0": q, "hbar_q_sq": hbar_q_sq, "two_q": two_q, "z_markov": z_val,
    })
    w.add_data("per_chain", {
        "e": {"V0": Ve, "dV0": dVe},
        "p_g0": {"V0": Vp0, "dV0": dVp0},
        "p_g1": {"V0": Vp1, "dV0": dVp1},
        "n_g0": {"V0": Vn0, "dV0": dVn0},
        "n_g1": {"V0": Vn1, "dV0": dVn1},
    })
    w.add_data("level_1_brane_shift", {
        "m_p_L0_MeV": m_p_0, "m_p_L0_1_MeV": m_p_1,
        "m_n_L0_MeV": m_n_0, "m_n_L0_1_MeV": m_n_1,
        "m_p_err_L0": (m_p_0-M_P_MEV)/M_P_MEV*100,
        "m_p_err_L0_1": (m_p_1-M_P_MEV)/M_P_MEV*100,
        "m_n_err_L0": (m_n_0-M_N_MEV)/M_N_MEV*100,
        "m_n_err_L0_1": (m_n_1-M_N_MEV)/M_N_MEV*100,
    })
    w.add_data("multiplicative_alpha_fit", {
        "alpha_from_proton": alpha_fit,
        "two_q": two_q,
        "ratio_alpha_to_two_q": alpha_fit / two_q,
        "m_p_MeV": m_p_mult, "m_n_MeV": m_n_mult,
        "m_n_err_with_proton_alpha": (m_n_mult-M_N_MEV)/M_N_MEV*100,
        "required_alpha_for_neutron": -target_n_correction,
    })
    w.add_data("log_form_alternative", {
        "m_p_MeV": m_p_log_MeV, "m_n_MeV": m_n_log_MeV,
        "m_p_err": (m_p_log_MeV-M_P_MEV)/M_P_MEV*100,
        "m_n_err": (m_n_log_MeV-M_N_MEV)/M_N_MEV*100,
    })
    w.save()


if __name__ == "__main__":
    main()

def hecke_mul(t1, t2):
    r = {}
    for w1, c1 in t1.items():
        for w2, c2 in t2.items():
            w = w1 + w2
            r[w] = r.get(w, 0.0) + c1 * c2
    return {w: c for w, c in r.items() if abs(c) > 1e-14}


def reduce_nf(terms):
    changed = True
    iters = 0
    while changed:
        changed = False
        iters += 1
        if iters > 10000:
            break
        new = {}
        for word, coeff in terms.items():
            if abs(coeff) < 1e-14:
                continue
            done = False
            for p in range(len(word) - 1):
                if word[p] == word[p + 1]:
                    pre, suf = word[:p], word[p + 2:]
                    new[pre + (word[p],) + suf] = new.get(pre + (word[p],) + suf, 0) + coeff * h
                    new[pre + suf] = new.get(pre + suf, 0) + coeff
                    done = changed = True
                    break
            if done:
                continue
            for p in range(len(word) - 2):
                a, b, c = word[p], word[p + 1], word[p + 2]
                if a == c and abs(a - b) == 1:
                    nt = (b, a, b)
                    if nt < (a, b, c):
                        nw = word[:p] + nt + word[p + 3:]
                        new[nw] = new.get(nw, 0) + coeff
                        done = changed = True
                        break
            if done:
                continue
            # Far commutativity
            for p in range(len(word) - 1):
                if word[p] > word[p + 1] and abs(word[p] - word[p + 1]) > 1:
                    nw = word[:p] + (word[p + 1], word[p]) + word[p + 2:]
                    new[nw] = new.get(nw, 0) + coeff
                    done = changed = True
                    break
            if not done:
                new[word] = new.get(word, 0) + coeff
        terms = {w: c for w, c in new.items() if abs(c) > 1e-14}
    return terms


def markov_trace_word(word, n):
    if not word:
        return 1.0
    if n <= 1:
        return 1.0
    top = n - 1
    if max(word) < top:
        return markov_trace_word(word, n - 1)
    pos = len(word) - 1
    while pos >= 0 and word[pos] != top:
        pos -= 1
    if pos == len(word) - 1:
        return z * markov_trace_word(word[:pos], n)
    A = word[:pos]
    B = word[pos + 1:]
    new_terms = hecke_mul({B: 1.0}, {A: 1.0})
    new_terms = reduce_nf(new_terms)
    return z * sum(c * markov_trace_word(w, n) for w, c in new_terms.items())


def markov_trace(terms, n):
    return sum(c * markov_trace_word(w, n) for w, c in terms.items())


def word_str(w):
    if not w:
        return "1"
    return ''.join(f'σ{g}' for g in w)



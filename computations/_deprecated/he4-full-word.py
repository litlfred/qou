def nuclear_element(ordering):
    """Build N(ordering) = prod_i (c_i σ_i + d_i) in H_A(q)."""
    A = len(ordering)
    result = {(): 1.0}
    for i in range(A - 1):
        ti, tj = ordering[i], ordering[i + 1]
        if ti == 1 and tj == 1:    # pp
            factor = {(i,): 1.0}
        elif ti == 0 and tj == 0:  # nn
            factor = {(i,): 1.0, (): -h}
        else:                       # mixed
            factor = {(i,): 1.0, (): -h / 2}
        result = hecke_mul(result, factor)
        result = reduce_nf(result)
    return result



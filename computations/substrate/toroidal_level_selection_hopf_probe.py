from _precision import set_compute_dps  # noqa: E402
set_compute_dps()
half = mp.mpf(1) / 2

# ------------------------------------------------- (1) elementary toroidal
def p_half(nu, eta):
    return mp.legenp(nu - half, half, mp.cosh(eta), type=3)


def p_mhalf(nu, eta):
    return mp.legenp(nu - half, -half, mp.cosh(eta), type=3)


POINTS = [(mp.mpf("1"), mp.mpf("0.7")), (mp.mpf("2.4"), mp.mpf("0.21")),
          (mp.mpf("3"), mp.mpf("1.3"))]
tol = mp.mpf("1e-40")
elem_plus_ok = all(
    abs(p_half(nu, e) - mp.sqrt(2 / (mp.pi * mp.sinh(e))) * mp.cosh(nu * e)) < tol
    for nu, e in POINTS)
elem_minus_ok = all(
    abs(p_mhalf(nu, e) - mp.sqrt(2 / (mp.pi * mp.sinh(e))) * mp.sinh(nu * e) / nu) < tol
    for nu, e in POINTS)

# ------------------------------------------------ (2) recurrence, exact
q, Wp, Wm = sp.symbols("q W_p W_m", positive=True)
k = sp.symbols("k", integer=True, positive=True)
x = lambda j: Wp * q**(2 * j) + Wm * q**(-2 * j)
recurrence_ok = sp.simplify(x(k + 1) - (q**2 + q**(-2)) * x(k) + x(k - 1)) == 0
# eta = 2 ln q: q^2 + q^-2 = 2 cosh(eta)
cosh_id_ok = sp.simplify(
    ((q**2 + q**(-2)) - 2 * sp.cosh(2 * sp.log(q))).rewrite(sp.exp)) == 0


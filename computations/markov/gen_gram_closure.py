#!/usr/bin/env python3
"""RETIRED GENERATOR -- do not run to "restore" anything (bean qou-x64l).

This wrote `QOU/Machinery/MarkovTraceH4Gram0..7` + `MarkovTraceH4Gram`: the 576
`gramval_i_j` entries discharging `gram_symm`, hence the ASCII `trM_cyclic`, and
through `H4BasisBridge` the subscript `trM4_cyclic`.

**Those nine modules were deleted** -- 6604 generated lines, ~700 KB, ~4.3 GB
peak, and the reason a full build took ~55 min rather than ~5.
`QOU.Machinery.H4.trM4_cyclic` (`H4Cyclicity`) now proves cyclicity directly
from the three generators and the subalgebra argument, and `H4.trM_cyclic` is a
three-rewrite corollary of it across the basis relabelling. Nothing imports the
Gram chain, and `gram_symm` has no remaining use anywhere in the tree.

Running this script regenerates nine modules that nothing imports. It is kept,
rather than deleted, for two narrow reasons:

  * it records how the 576 entries were derived (an independent check on the
    `TRM` trace table, still meaningful even though the Lean is gone);
  * it is the working template if a Gram closure is ever wanted at another `n`
    -- but note that the generator route is the cheap one at `n = 4`, so prefer
    porting `H4Cyclicity`'s argument before generating O(n!^2) entries.

Do not re-add its output to the build.
"""
import sys; sys.path.insert(0,'computations/markov')
import sympy as sp
from hecke_regular_nf_table import Hecke, markov_trace, reduced_word
H4=Hecke(4); tr4=markov_trace(H4)
words=[reduced_word(p) for p in H4.S]
def Lx(e): return str(sp.expand(e)).replace('**','^')
def flat(d): return [d.get(k, sp.Integer(0)) for k in range(24)]
def vec(d): return '![' + ', '.join(Lx(x) for x in flat(d)) + ']'
def wj(i,j):
    cur={i: sp.Integer(1)}
    for g in words[j]: cur=H4.right_gen(cur,g)
    return cur
def poly(i,j):
    return sp.expand(sum(flat(wj(i,j))[m]*tr4[m] for m in range(24)))
def entry(i,j):
    w=words[j]; ex=f'e ({i} : Fin 24)'
    for g in w: ex=f'mulσ{g} h ({ex})'
    lines=[f'theorem gramval_{i}_{j} (z h : R) : trM z h (mulNF h (e ({i}:Fin 24)) (e ({j}:Fin 24))) = {Lx(poly(i,j))} := by']
    lines.append(f'  have hmul : mulNF h (e ({i}:Fin 24)) (e ({j}:Fin 24)) = {ex} := by')
    lines.append(f'    funext m; simp [mulNF, e, Pi.single_apply]')
    lines.append(f'  rw [hmul]')
    cur={i: sp.Integer(1)}
    lines.append(f'  have hh0 : (e ({i} : Fin 24) : Fin 24 → R) = {vec(cur)} := by funext m; fin_cases m <;> simp [e, Pi.single_apply]')
    for k,g in enumerate(w):
        cur=H4.right_gen(cur,g); ee=f'e ({i} : Fin 24)'
        for gg in w[:k+1]: ee=f'mulσ{gg} h ({ee})'
        lines.append(f'  have hh{k+1} : {ee} = {vec(cur)} := by rw [hh{k}]; funext m; fin_cases m <;> simp [mulσ{g}] <;> try ring')
    lines.append(f'  rw [hh{len(w)}]')
    lines.append(f'  simp only [trM, TRM, Fin.sum_univ_succ, Fin.sum_univ_zero, Matrix.cons_val_zero, Matrix.cons_val_succ]; ring')
    return '\n'.join(lines)

# ── Emission: ONE MODULE PER CHUNK, CHAINED ──────────────────────────────
#
# The 576 entries must NOT go in a single module. Peak elaboration memory
# grows linearly in the number of entries (~28 MB each, measured), so the
# whole closure in one file needs ~15 GB and over an hour — it cannot
# compile in a 15 GB container at all (bean qou-8hjy).
#
# Split into NCHUNK modules of 576/NCHUNK entries, **each importing the
# previous**. The chain matters: were the chunks independent, Lake would
# elaborate them in parallel and peak memory would be (cores x chunk),
# which is exactly the wall again on a many-core machine. Chained, Lake
# must build them in order and the peak is one chunk — measured flat at
# ~4.3 GB across the chain, not growing with depth.
#
# The final module closes `gram_symm` from all the entries and derives
# `trM_cyclic`.
NCHUNK = 8
LEAN_DIR = 'folio/quantum-observable-universe/lean/QOU/Machinery'
per = (576 + NCHUNK - 1) // NCHUNK

def header(prev, title, blurb):
    return [f'import {prev}', '', '/-!', f'# {title}', ''] + blurb + [
        '-/', '', 'namespace QOU.Machinery.H4', '',
        'variable {R : Type*} [CommRing R]', '']

pairs = [(i, j) for i in range(24) for j in range(24)]
for k in range(NCHUNK):
    prev = 'QOU.Machinery.MarkovTraceH4' if k == 0 else f'QOU.Machinery.MarkovTraceH4Gram{k-1}'
    out = header(prev, f'QOU.Machinery.H4 Gram closure — part {k} of {NCHUNK}', [
        'Auto-generated by `computations/markov/gen_gram_closure.py`: Gram entries',
        '`G_{i,j} = tr_M(b_i*b_j)` computed sorry-free via the sparse-basis have-chain',
        '(each `mulsigma` step on a basis vector is depth-1 + sparse, so the depth-6',
        'whnf wall is never hit).',
        '',
        f'Part {k} of {NCHUNK}, each importing the previous so the chain builds serially',
        'and peak elaboration memory stays bounded. See the generator for why.'])
    for (i, j) in pairs[k*per:(k+1)*per]:
        out.append(entry(i, j)); out.append('')
    out.append('end QOU.Machinery.H4')
    open(f'{LEAN_DIR}/MarkovTraceH4Gram{k}.lean', 'w').write('\n'.join(out) + '\n')

allnames = ', '.join(f'gramval_{i}_{j}' for (i, j) in pairs)
out = header(f'QOU.Machinery.MarkovTraceH4Gram{NCHUNK-1}',
             'QOU.Machinery.H4 — Gram symmetry and trace cyclicity',
             ['Closes `gram_symm` from the 576 computed Gram entries, hence `trM_cyclic`.'])
# `fin_cases` yields indices in `Fin.mk` form (`⟨3, _⟩`) while the entries above
# are stated with `OfNat` numerals (`(3 : Fin 24)`). They are definitionally
# equal — each bridge is `rfl` — but `simp` matches on syntax, so without these
# the dispatch below rewrites nothing and leaves 552 goals open.
out.append('/-! `fin_cases` produces `Fin` indices in `Fin.mk` form while the generated')
out.append('`gramval_i_j` are stated with `OfNat` numerals. Each bridge is `rfl`; they')
out.append('differ only syntactically, and `simp` matches on syntax. -/')
out.append('')
for k in range(24):
    out.append(f'@[simp] theorem finMk{k} (hh : {k} < 24) : (⟨{k}, hh⟩ : Fin 24) = {k} := rfl')
out.append('')
out.append('set_option maxHeartbeats 4000000 in')
out.append('/-- **Gram symmetry** — discharged by the 576 computed entries.')
out.append('')
out.append('`fin_cases i <;> fin_cases j` opens 24² = 576 goals and each is matched against')
out.append('the full 576-lemma `simp only` set, so this one dispatch costs far more than the')
out.append('default 200 000 heartbeats. It is a finite, terminating computation — the budget')
out.append('is raised, not removed. -/')
out.append('theorem gram_symm (z h : R) :')
out.append('    ∀ i j, trM z h (mulNF h (e i) (e j)) = trM z h (mulNF h (e j) (e i)) := by')
out.append('  intro i j')
out.append('  fin_cases i <;> fin_cases j <;>')
finmk = ', '.join(f'finMk{k}' for k in range(24))
out.append(f'    simp only [{finmk}, {allnames}]')
out.append('')
out.append('/-- **(M2) Trace cyclicity for H₄ — fully sorry-free.** -/')
out.append('theorem trM_cyclic (z h : R) (u v : Fin 24 → R) :')
out.append('    trM z h (mulNF h u v) = trM z h (mulNF h v u) :=')
out.append('  trM_cyclic_of_gram_symm z h (gram_symm z h) u v')
out.append('')
out.append('end QOU.Machinery.H4')
open(f'{LEAN_DIR}/MarkovTraceH4Gram.lean', 'w').write('\n'.join(out) + '\n')
print(f"wrote {NCHUNK} chunk modules ({per} entries each) + the closure module")

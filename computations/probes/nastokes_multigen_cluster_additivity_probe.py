def mp_verdict(shape, q, word, subset, gp):
    """Repeat the R_3 measurement entirely in mpmath at 40 dps."""
    sig, germs, dim, h = rep_and_germs(shape, q, mpmath_mode=True)
    i, j = gp
    F = germs[i] * germs[j] - germs[j] * germs[i]
    I = mp.eye(dim)

    def om(T):
        w = restrict_word(word, T)
        U, Ui = I, I
        P, Om = mp.zeros(dim, dim), mp.zeros(dim, dim)
        for (c, d, g) in w:
            Fk = Ui * F * U
            Om += Fk * P - P * Fk
            P = P + Fk
            e = d / c
            A = 1 / (1 - e * h - e * e)
            U = U * (c * sig[g] + d * I)
            Ui = ((A / c) * sig[g] + (-A * (h + e) / c) * I) * Ui
        return Om

    S = list(subset)
    R = mp.zeros(dim, dim)
    for r in range(len(S) + 1):
        for T in itertools.combinations(S, r):
            R = R + ((-1) ** (len(S) - r)) * om(T)
    return float(mp.norm(om(tuple(S)))), float(mp.norm(R))



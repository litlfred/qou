def _letter_inv_coeffs(c, d, h):
    """(alpha, beta) with (c*sigma + d)^{-1} = (alpha*sigma + beta).
    From sigma^2 = h sigma + 1:  (sigma+e)^{-1} = A sigma + B,
    A = 1/(1 - e h - e^2), B = -A (h + e), e = d/c; then divide by c."""
    e = d / c
    A = 1.0 / (1.0 - e * h - e * e)
    return A / c, (-A * (h + e)) / c


def transports(word, sig, h, dim):
    """Yekutieli ordered partial products U_k, U_k^{-1} BEFORE each band."""
    I = np.eye(dim)
    U, Ui = np.eye(dim), np.eye(dim)
    Us, Uis = [], []
    for (c, d, g) in word:
        Us.append(U)
        Uis.append(Ui)
        al, be = _letter_inv_coeffs(c, d, h)
        U = U @ (c * sig[g] + d * I)
        Ui = (al * sig[g] + be * I) @ Ui
    return Us, Uis


def ordered_pairing(Us, Uis, F, dim, Fs=None):
    """Omega_2^perp = listPairing([Fc_0, ...]) = sum_{i<j} [Fc_j, Fc_i], with
    Fc_k = U_k^{-1} F_k U_k.  Computed as sum_j [Fc_j, P_{j-1}] (bilinearity;
    O(L) commutators).  `Fs` supplies a per-band curvature (band-local reading);
    `F` is the constant reading."""
    P = np.zeros((dim, dim))
    Om = np.zeros((dim, dim))
    for t, (U, Ui) in enumerate(zip(Us, Uis)):
        Fk = Ui @ (F if Fs is None else Fs[t]) @ U
        Om += Fk @ P - P @ Fk
        P = P + Fk
    return Om


def omega_for_subset(word, subset, sig, h, dim, F, curvature_of=None, cache=None):
    key = tuple(sorted(subset))
    if cache is not None and key in cache:
        w, Us, Uis = cache[key]
    else:
        w = restrict_word(word, subset)
        Us, Uis = transports(w, sig, h, dim)
        if cache is not None:
            cache[key] = (w, Us, Uis)
    Fs = None if curvature_of is None else [curvature_of(g) for (_, _, g) in w]
    return ordered_pairing(Us, Uis, F, dim, Fs=Fs)


def moebius_residual(word, subset, sig, h, dim, F, curvature_of=None, cache=None):
    """R_S = sum_{T subset S} (-1)^{|S|-|T|} Omega(T)."""
    S = list(subset)
    R = np.zeros((dim, dim))
    for r in range(len(S) + 1):
        for T in itertools.combinations(S, r):
            R = R + ((-1) ** (len(S) - r)) * omega_for_subset(
                word, T, sig, h, dim, F, curvature_of=curvature_of, cache=cache)
    return R


def fro(M):
    return float(np.linalg.norm(M, "fro"))


def f64_json(o):
    """Serialize an f64 result tree for a witness: every float becomes its own
    repr string, ints/bools/None/strings pass through.

    The sweep in this probe is float64 BY DESIGN and says so in its own caveat
    (numpy at dim up to 77, with an independent mpmath 40-dps re-run of R_3 as
    the control). So there is nothing to recover by widening these numbers, and
    nothing honest to gain by padding them: repr(float) is exactly the ~17
    digits the kernel produced, round-trips exactly, and keeps raw float64 JSON
    out of the witness. Applied once at the sink rather than at ~30 call sites,
    so no result can be added later and quietly miss it.
    """
    if isinstance(o, bool) or o is None:
        return o
    if isinstance(o, float):
        return repr(o)
    if isinstance(o, dict):
        return {k: f64_json(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [f64_json(v) for v in o]
    return o



def _templates():
    """Species intra-chains and interface crossings, EXTRACTED from the corpus
    function `atom_braid_word_3A` (never re-derived here).

    A = 1 calls give the bare intra chains; A = 2 calls expose the pp / nn / pn
    interface letter as the single letter on generator 2.
    """
    p_intra = [(c, d, g) for (c, d, g) in atom_braid_word_3A(1, 0)]
    n_intra = [(c, d, g) for (c, d, g) in atom_braid_word_3A(0, 1)]
    inter = {}
    for key, (Z, N) in (("pp", (2, 0)), ("nn", (0, 2)), ("pn", (1, 1))):
        lets = [(c, d) for (c, d, g) in atom_braid_word_3A(Z, N) if g == 2]
        assert len(lets) == 1, (key, lets)
        inter[key] = lets[0]
    return p_intra, n_intra, inter


_P_INTRA, _N_INTRA, _INTER = _templates()


def word_for_ordering(ordering):
    """The 3A-strand word for an explicit species ordering over {'p','n'}.

    Reproduces `atom_braid_word_3A(Z, N)` EXACTLY on the canonical ordering
    'p'*Z + 'n'*N (asserted in `main`); permuted orderings are the control for
    whether the cluster residual is a well-defined many-body observable.
    """
    A = len(ordering)
    out = []
    for k, nuc in enumerate(ordering):
        intra = _P_INTRA if nuc == "p" else _N_INTRA
        for (c, d, g) in intra:
            out.append((c, d, g + 3 * k))
        if k < A - 1:
            pair = nuc + ordering[k + 1]
            key = "pp" if pair == "pp" else ("nn" if pair == "nn" else "pn")
            c, d = _INTER[key]
            out.append((c, d, 3 * k + 2))
    return out


def block_label(gen_idx: int):
    """(kind, index) of the word position carrying `gen_idx`: nucleon k owns
    gens 3k, 3k+1; link k (joining nucleons k, k+1) owns gen 3k+2."""
    k, r = divmod(gen_idx, 3)
    return ("nucleon", k) if r in (0, 1) else ("link", k)


def restrict_word(word, keep_nucleons):
    """Sub-configuration: nucleon k's intra letters iff k in S; link k iff BOTH
    endpoints in S.  Order preserved, generator indices untouched -- every
    sub-configuration lives in the SAME algebra H_n(q), so the operators are
    directly comparable."""
    S = set(keep_nucleons)
    out = []
    for (c, d, g) in word:
        kind, k = block_label(g)
        if (kind == "nucleon" and k in S) or (kind == "link" and k in S and (k + 1) in S):
            out.append((c, d, g))
    return out



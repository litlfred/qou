def _blocks(shape):
    """Per-generator block data: for each generator k (1-based) a list of
    (i, j, rho) with j = None for a 1x1 block.  Depends only on the shape."""
    n = sum(shape)
    syts, _cells, contents = standard_young_tableaux(shape)
    dim = len(syts)
    idx = {tuple(sorted(t.items())): i for i, t in enumerate(syts)}
    per_gen = []
    for k in range(1, n):
        out, done = [], set()
        for i in range(dim):
            if i in done:
                continue
            ck, ck1 = syts[i][k], syts[i][k + 1]
            r = contents[ck1] - contents[ck]
            sm = dict(syts[i])
            sm[k], sm[k + 1] = ck1, ck
            j = idx.get(tuple(sorted(sm.items())))
            if j == i:
                j = None
            out.append((i, j, r))
            done.add(i)
            if j is not None:
                done.add(j)
        per_gen.append(out)
    return per_gen, dim


def _entry_and_deriv(r, q, one):
    """(a, a', b, da, da', db) for axial distance r, in the caller's number type.

    a  = h/(1-q^{-2r}),  a' = h/(1-q^{2r}),  b = sqrt(a a' + 1),  h = q - 1/q.
    Derivatives are CLOSED FORM (no finite differences).
    """
    h = q - one / q
    dh = one + one / q ** 2
    u = q ** (-2 * r)
    du = (-2 * r) * q ** (-2 * r - 1)
    v = q ** (2 * r)
    dv = (2 * r) * q ** (2 * r - 1)
    a = h / (one - u)
    da = dh / (one - u) + h * du / (one - u) ** 2
    ap = h / (one - v)
    dap = dh / (one - v) + h * dv / (one - v) ** 2
    bsq = a * ap + one
    if bsq <= 0:
        return a, ap, 0 * one, da, dap, 0 * one
    b = bsq ** 0.5 if not isinstance(q, mp.mpf) else mp.sqrt(bsq)
    db = (ap * da + a * dap) / (2 * b) if b != 0 else 0 * one
    return a, ap, b, da, dap, db


def rep_and_germs(shape, q, *, mpmath_mode=False):
    """rho(sigma_i) and the germs dq_i = q (d_q rho) rho^{-1}, i = 0..n-2.

    rho(sigma)^{-1} = rho(sigma) - h comes from the Hecke relation
    sigma^2 = h sigma + 1, so NO matrix inversion is used anywhere.
    """
    per_gen, dim = _blocks(shape)
    if mpmath_mode:
        one = mp.mpf(1)
        zeros = lambda: mp.zeros(dim, dim)          # noqa: E731
        eye = mp.eye(dim)
        matmul = lambda X, Y: X * Y                 # noqa: E731
    else:
        q = float(q)
        one = 1.0
        zeros = lambda: np.zeros((dim, dim))        # noqa: E731
        eye = np.eye(dim)
        matmul = lambda X, Y: X @ Y                 # noqa: E731
    h = q - one / q
    sigmas, germs = [], []
    for blocks in per_gen:
        M, dM = zeros(), zeros()
        for (i, j, r) in blocks:
            a, ap, b, da, dap, db = _entry_and_deriv(r, q, one)
            if j is None:
                M[i, i] = a
                dM[i, i] = da
            else:
                M[i, i], M[j, j] = a, ap
                M[i, j], M[j, i] = b, b
                dM[i, i], dM[j, j] = da, dap
                dM[i, j], dM[j, i] = db, db
        sigmas.append(M)
        germs.append(q * matmul(dM, M - h * eye))
    return sigmas, germs, dim, h


def certify_rep(sigmas, dim, h, *, mpmath_mode=False):
    """Braid + Hecke + far-commutation certification."""
    if mpmath_mode:
        eye, nrm = mp.eye(dim), (lambda X: float(mp.norm(X)))
        mul = lambda X, Y: X * Y                     # noqa: E731
    else:
        eye, nrm = np.eye(dim), (lambda X: float(np.linalg.norm(X)))
        mul = lambda X, Y: X @ Y                     # noqa: E731
    worst = 0.0
    for M in sigmas:
        worst = max(worst, nrm(mul(M, M) - h * M - eye))
    for i in range(len(sigmas) - 1):
        worst = max(worst, nrm(mul(mul(sigmas[i], sigmas[i + 1]), sigmas[i])
                               - mul(mul(sigmas[i + 1], sigmas[i]), sigmas[i + 1])))
    for i in range(len(sigmas)):
        for j in range(i + 2, len(sigmas)):
            worst = max(worst, nrm(mul(sigmas[i], sigmas[j]) - mul(sigmas[j], sigmas[i])))
    return worst



def block_entropy(per_block: dict, q0: float):
    """Born–Plancherel block (von Neumann) entropy − Σ p_λ ln p_λ,
    p_λ ∝ W_λ · ‖ρ_λ(β)‖²_F."""
    weights = []
    for lam, d in per_block.items():
        M = np.array(d["matrix"], dtype=float)
        fro2 = float(np.sum(M * M))
        lam_t = tuple(lam) if not isinstance(lam, tuple) else lam
        W = mbd.W_lambda_float(q0, lam_t)
        weights.append(W * fro2)
    tot = sum(weights)
    if tot <= 0:
        return None
    S = 0.0
    for w in weights:
        p = w / tot
        if p > 0:
            S -= p * math.log(p)
    return S


def run():
    q0 = float(bks.Q0)
    me = float(mbd._constants()[0])
    E0 = me / (q0 * (q0 - 1.0))
    rows = []
    for atom in bks.REGISTRY:
        n0 = atom["n_0"]
        aw = atom["atom_braid_word"]
        cp = bks.constituent_product_word(atom["constituent_offsets"])
        pb_bound = bks.per_block_evaluation(aw, n0, q=q0)["per_block"]
        pb_free = bks.per_block_evaluation(cp, n0, q=q0)["per_block"]
        S_bound = block_entropy(pb_bound, q0)
        S_free = block_entropy(pb_free, q0)
        dS = S_bound - S_free
        bame = atom["B_AME_MeV"]
        rows.append({
            "name": atom["name"], "A": atom["A"], "n0": n0, "B_AME": bame,
            "S_bound": S_bound, "S_free": S_free, "dS": dS,
            "E0_S_bound": E0 * S_bound, "E0_dS": E0 * dS, "E0_absdS": E0 * abs(dS),
            "err_S_bound": bame / (E0 * S_bound) if S_bound else None,
            "err_dS": bame / (E0 * dS) if dS else None,
            "err_absdS": bame / (E0 * abs(dS)) if dS else None,
        })
    return {"q0": q0, "E0": E0, "rows": rows}


def report(res):
    print("# Von Neumann (Wedderburn-block) entanglement entropy vs B_AME — the real test")
    print(f"E₀ = {res['E0']:.4f} MeV   q₀ = {res['q0']:.6f}\n")
    print("S = −Σ p_λ ln p_λ,  p_λ ∝ W_λ·‖ρ_λ(β)‖²_F   (state-dependent, from the Hecke rep)\n")
    print("| iso | A | n₀ | B_AME | S_bound | S_free | ΔS | E₀·S_bound | E₀·ΔS | err(S_bound) | err(ΔS) |")
    print("|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    for r in res["rows"]:
        err_dS_str = f"{r['err_dS']:.2f}" if r["err_dS"] else "—"
        print(f"| {r['name']} | {r['A']} | {r['n0']} | {r['B_AME']:.2f} "
              f"| {r['S_bound']:.3f} | {r['S_free']:.3f} | {r['dS']:+.3f} "
              f"| {r['E0_S_bound']:.2f} | {r['E0_dS']:+.2f} "
              f"| {r['err_S_bound']:.2f} | {err_dS_str} |")
    print("\n## Reading")
    # Are the errors near 1 (conjecture holds) for either S_bound or ΔS?
    eb = [r["err_S_bound"] for r in res["rows"] if r["err_S_bound"]]
    ed = [r["err_dS"] for r in res["rows"] if r["err_dS"]]
    def spread(xs):
        return (min(xs), max(xs)) if xs else (None, None)
    print(f"- err(E₀·S_bound) range: {spread(eb)} ; err(E₀·ΔS) range: {spread(ed)}")
    print("- Conjecture B = E₀·S holds for a column iff its err ≈ 1 across all three isotopes.")
    print("- ΔS (entanglement GENERATED by binding) is the binding-relevant quantity (free")
    print("  nucleons are a product state); S_bound includes the constituents' own entropy.")


def main(argv=None):
    res = run()
    report(res)
    rows = res["rows"]
    w = WitnessBuilder("binding-von-neumann-entropy-test", engine="python")
    w.set_description(
        "Test of the owner conjecture B = E0*S_vN: the state-dependent Wedderburn-block "
        "(von Neumann) entanglement entropy S = -sum p_lambda ln p_lambda, p_lambda ~ "
        "W_lambda*||rho_lambda(beta)||_F^2, of the actual bound nuclear braid word (Hecke "
        "seminormal rep, per_block_evaluation), vs B_AME, for 2H/3H/3He (n0<=9, the feasible "
        "registry). Reports S_bound, S_free (constituent product), Delta S (entanglement "
        "generated by binding), and E0*S vs B_AME. Parameter-free (Hecke rep + E0 + W_lambda)."
    )
    w.add_data("q0", res["q0"])
    w.add_data("E0_MeV", res["E0"])
    w.add_data("prescription", "p_lambda ~ W_lambda * ||rho_lambda(beta)||_F^2 (Born-Plancherel)")
    w.add_data("rows", rows)
    # Record (not assert pass/fail — the verdict is which column tracks): assert the
    # computation produced finite entropies for all three isotopes.
    n_finite = sum(1 for r in rows if r["S_bound"] is not None and math.isfinite(r["S_bound"]))
    w.add_assertion(
        "all_three_isotopes_have_finite_block_entropy",
        computed=n_finite, expected=len(rows), tolerance=0,
        source="State-dependent Wedderburn-block entropy computed from the Hecke rep "
               "for every registry isotope (2H, 3H, 3He).",
    )
    out = w.save()
    print(f"\nwitness → {out.name}")
    return 0



"""Von Neumann entanglement entropy of the bound nuclear state vs B_AME/E₀ — the real test.

Owner conjecture (2026-06-30): B = E₀·S_vN, with S_vN the von Neumann entropy of the bound-state
reduced density matrix — "the bound-state energy equals the total occupancy surprisal". This is the
ONLY reading not already refuted: the single-partition surprisal E₀·ln(1/W_λ) is ⁴He-local, and the
state-INDEPENDENT Plancherel Shannon entropy is 2–3× off. Here we compute the STATE-DEPENDENT block
(Wedderburn) entanglement entropy of the ACTUAL bound braid word from the Hecke seminormal
representation (via `binding_k_solver.per_block_evaluation`), and test E₀·S against B_AME.

Prescription (Born–Plancherel block weight). For the bound braid word β, the probability of
Wedderburn block λ ⊢ n₀ (n₀ = 3A) is the Plancherel-weighted block intensity
    p_λ  ∝  W_λ · ‖ρ_λ(β)‖²_F ,      ‖M‖²_F = Tr(M Mᵀ),
with W_λ the Hecke q-Plancherel weight. Then the block (von Neumann) entanglement entropy is
    S_block(β) = − Σ_λ p_λ ln p_λ .
This is state-dependent (it uses the actual rep matrices ρ_λ(β)), unlike the refuted Plancherel
Shannon entropy (which is β-independent). We report:
  • S_bound = S_block(atom word)         — the bound state;
  • S_free  = S_block(constituent product) — the unbound product of free nucleons;
  • ΔS = S_bound − S_free                  — the entanglement GENERATED by binding.
and test E₀·S_bound and E₀·ΔS against B_AME.

Feasible only for small n₀ = 3A (block matrix dims explode with n): the registry covers
²H (n=6), ³H (n=9), ³He (n=9). ⁴He+ need their bound braid words (not registered) and n≥12 blocks.

This is the honest test the earlier coincidence demanded: if E₀·S (independently computed, not
back-solved) tracks B_AME, the conjecture has teeth; if not, it is refuted at the light end.
NOT a fit — every quantity is the Hecke rep + E₀ (CAL-derived) + W_λ.
"""

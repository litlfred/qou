def closed_form_c_k(k: int, b: mp.mpf) -> mp.mpf:
    """Closed-form c_k for k=2..N.

    For k ≤ 7 the values are the documented direct closed forms
    (c_2 = -1, c_3 = -2, c_4 = -2·b⁴, c_5 = -(b² + 1/2), c_6 = 4·b²,
    c_7 = -8). For k ≥ 8 the values are GENERATED by applying the
    recursion c_{k+2} = b²·c_k, which is valid for k ≥ 6 with c_6
    and c_7 as seeds (so k ≥ 8 is the range over which the recursion
    is actually used to extend the table; the relation itself first
    becomes valid at k = 6 — c_8 = b²·c_6 holds — but c_6 and c_7
    themselves are seeds, not generated). The recursion instantiates
    `QOU.QBeta.CKRecursion` (Lean, on `main` per
    q-beta-c-k-recursion-from-habiro-q-difference.lean) at depth = 2,
    kernel = (0, b²) — a CONSTANT-kernel case. The constant-kernel
    hypothesis is REFUTED through d = 4 at q₀ (extracted c_k diverge
    from the closed form by O(10³)+ at k ≥ 8); the closed form is
    therefore the STRUCTURAL silver-ratio signal rather than a
    precision claim at q₀.
    """
    b2 = b * b
    if k == 2:
        return mp.mpf(-1)
    if k == 3:
        return mp.mpf(-2)
    if k == 4:
        return mp.mpf(-2) * b ** 4
    if k == 5:
        return -(b2 + mp.mpf(1) / 2)
    if k == 6:
        return mp.mpf(4) * b2
    if k == 7:
        return mp.mpf(-8)
    # k ≥ 8: apply recursion c_k = b² · c_{k-2}
    return b2 * closed_form_c_k(k - 2, b)


def qbeta_at_depth(N: int, Q_A_cos: mp.mpf, b: mp.mpf, hbar_q_sq: mp.mpf
                   ) -> mp.mpf:
    """Q_β_N = Q_A·cos · ∏_{k=2}^{N} (1 + c_k · b^k · ℏ_q^{2k})."""
    factor = mp.mpf(1)
    for k in range(2, N + 1):
        c_k = closed_form_c_k(k, b)
        rung = 1 + c_k * b ** k * hbar_q_sq ** k
        factor *= rung
    return Q_A_cos * factor


def main() -> int:
    mp.mp.dps = 60

    # Load provenance witness — same as qbeta_decay_sdp_extended_ck.py,
    # but the witness lives at the COMPUTATIONS_ROOT level, not in qbeta/.
    provenance = COMPUTATIONS_ROOT / "q-beta-operator-valued-N3.witness.json"
    with open(provenance) as f:
        d = json.load(f)
    data = d["data"]
    Q_N2 = mp.mpf(str(data["Q_N2"]))
    Q_AME = mp.mpf(str(data["Q_AME"]))
    b = mp.mpf(str(data["hoefsmit_b"]))
    hbar_q_sq = mp.mpf(str(data["hbar_q_sq"]))

    # Form A · cos correction (matches qbeta_decay_sdp_extended_ck.py logic)
    N2_factor = 1 + mp.mpf(-1) * b ** 2 * hbar_q_sq ** 2
    Q_A_cos = Q_N2 / N2_factor

    print("=" * 78)
    print(" Q_β closed-form wiring — depths N=4..10 (production extension)")
    print("=" * 78)
    print(f"  Q_β AME   = {mp.nstr(Q_AME, 16)}")
    print(f"  Q_A · cos = {mp.nstr(Q_A_cos, 16)}")
    print(f"  b         = {mp.nstr(b, 16)}")
    print(f"  ℏ_q²      = {mp.nstr(hbar_q_sq, 16)}")
    print()

    # Show the c_k closed-form values at q₀
    print("  Closed-form c_k values at q₀:")
    print(f"  {'k':>3} {'c_k closed-form (15dps)':>26}")
    print("  " + "-" * 31)
    for k in range(2, 11):
        c_k = closed_form_c_k(k, b)
        print(f"  {k:>3} {mp.nstr(c_k, 15):>26}")
    print()

    # Compute Q_β at each depth N=2..20 (extended via recursion)
    print("  Q_β_N at each depth (closed-form wiring, recursion-extended):")
    print(f"  {'N':>3} {'Q_β_N':>30} {'(Q_β_N − AME)/AME (ppQ)':>30}")
    print("  " + "-" * 65)
    results = {}
    for N in (2, 3, 4, 5, 6, 7, 8, 9, 10, 12, 14, 16, 18, 20):
        Q_N = qbeta_at_depth(N, Q_A_cos, b, hbar_q_sq)
        rel_err = (Q_N - Q_AME) / Q_AME
        rel_err_ppQ = rel_err * mp.mpf("1e15")  # ppQ = parts per quadrillion = 10⁻¹⁵
        results[N] = {
            "Q_beta_N": mp.nstr(Q_N, 30),
            "delta_vs_AME": mp.nstr(rel_err, 12),
            "delta_vs_AME_ppQ": mp.nstr(rel_err_ppQ, 8),
        }
        print(f"  {N:>3} {mp.nstr(Q_N, 22):>30} {mp.nstr(rel_err_ppQ, 8):>30}")
    print()
    print("  Scoreboard read: at q₀, the closed-form wiring at N=4 reproduces")
    print(f"  the production 1ppQ achievement (≈ 1.79e-11 ppQ per qbeta-1ppq-achieved)")
    print(f"  per the baseline. Extending N=4 → N=10 measures whether the")
    print(f"  closed-form c_5..c_10 IMPROVE or DEGRADE Q_β at q₀.")
    print()

    # Compare against baseline (qbeta-1ppq-achieved at N=4)
    BASELINE_N4_ppQ = mp.mpf("1.7916878279761012e-11")  # from qbeta-1ppq-achieved.witness.json
    diff_n4 = mp.mpf(results[4]["delta_vs_AME_ppQ"]) - BASELINE_N4_ppQ
    print(f"  Cross-check vs qbeta-1ppq-achieved (N=4 baseline = {mp.nstr(BASELINE_N4_ppQ, 6)} ppQ):")
    print(f"    this probe's N=4 = {results[4]['delta_vs_AME_ppQ']} ppQ")
    print(f"    diff             = {mp.nstr(diff_n4, 4)}")
    print()
    final_N = 10
    final_ppQ = mp.mpf(results[final_N]["delta_vs_AME_ppQ"])
    if abs(final_ppQ) < abs(BASELINE_N4_ppQ):
        verdict = (
            f"WIRING IMPROVES PRECISION: N={final_N} gives |Δ| < N=4 baseline. "
            f"Closed-form c_5..c_10 wiring is GOOD at q₀.")
    else:
        verdict = (
            f"WIRING DOES NOT IMPROVE: N={final_N} has |Δ| ≥ N=4 baseline. "
            f"At q₀ the SDP-extracted noise-floor values (per upstream caveat) "
            f"add no precision; closed forms maintain ~baseline.")
    print(f"  VERDICT: {verdict}")

    # Emit witness
    out = {
        "computation": "qbeta-closed-form-wiring-n4-to-n10",
        "description": (
            "Closed-form wiring probe extending Q_β production from "
            "N=4 (current 1ppQ achievement) to N=10 using documented + "
            "this-session-derived closed forms for c_5..c_10. "
            "Measures the precision delta at each depth. "
            "EXPLORATORY. No production-script edit made."),
        "inputs_provenance": "q-beta-operator-valued-N3.witness.json",
        "Q_AME_from_provenance": mp.nstr(Q_AME, 50),
        "Q_A_cos_at_q0": mp.nstr(Q_A_cos, 30),
        "b_at_q0": mp.nstr(b, 30),
        "hbar_q_squared_at_q0": mp.nstr(hbar_q_sq, 30),
        "closed_form_c_k_at_q0": {
            f"c_{k}": mp.nstr(closed_form_c_k(k, b), 30)
            for k in range(2, 11)
        },
        "Q_beta_at_depth": results,
        "N4_baseline_ppQ_from_production": mp.nstr(BASELINE_N4_ppQ, 12),
        "verdict": verdict,
    }
    out_path = COMPUTATIONS_ROOT / "qbeta-closed-form-wiring-n4-to-n10.witness.json"
    out_path.write_text(json.dumps(out, indent=2))
    print(f"\n  Witness: {out_path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

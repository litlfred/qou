"""Wire closed-form c_k (k=2..10) into Q_β production at depths N=4..10.

Per user prompt 2026-06-04 ("do closed form wiring"). Extends the
N=4 production baseline (1.79e-11 ppQ achieved per
`qbeta-1ppq-achieved.witness.json`) to N=10 using the closed-form
c_k from the documented + this-session-derived pattern:

  c_2 = -1                  (factor convention)
  c_3 = -2                  (J_Hopf at q=1)
  c_4 = c_3 · b⁴       =  -2·b⁴       (documented)
  c_5 = -(b² + 1/2)         (averaging-resonance outlier, +1/2 fingerprint)
  c_6 = c_3² · b²      =   4·b²       (documented)
  c_7 = c_3³           =  -8           (documented)
  c_8 = c_3² · b⁴      =   4·b⁴       (derived this session)
  c_9 = c_3³ · b²      =  -8·b²       (derived this session)
  c_10 = c_3² · b⁶     =   4·b⁶       (derived this session)

Precision-ladder formula (per `qbeta_decay_sdp_extended_ck.py:9`):

  Q_β_N = Q_A · cos(α - b·ℏ_q²/2) · ∏_{k=2}^{N} (1 + c_k · b^k · ℏ_q^{2k})

Inputs sourced from the canonical `q-beta-operator-valued-N3.witness.json`
(same provenance as the extraction script).

This probe measures:
  - Q_β at each depth N ∈ {4, 5, 6, 7, 8, 9, 10}
  - Δ vs Q_β^AME at each depth (ppQ)
  - Whether extending production beyond N=4 *improves* or *degrades*
    the precision (the empirical question PR #1793 closed-form
    wiring was meant to answer).

q-usage discipline: all evaluations at real q₀; b, ℏ_q taken from the
provenance witness (Hoefsmit-derived at q₀); closed-form c_k are
fibre-level Laurent forms realised at q₀. CLAUDE.md §7c compliant.

EXPLORATORY. Documents the wiring outcome; no production-script edit
made (the existing `qbeta_decay_sdp_full_ck.py` is the canonical N=4
production path; extending it requires a separate workplan).
"""

#!/usr/bin/env python3
"""The two-row reduction behind `corank(n) = n! - Catalan(n)`, checked to n = 14.

WHY THIS PROBE EXISTS

`computations/probes/tl_n6_discriminator.py` measured the convention-D
Markov-Gram corank at n = 3, 4, 5, 6 -- `1, 10, 78, 588` -- and identified the
radical with the two-sided ideal generated by the 3-strand q-antisymmetriser
(= ker(H_n(q) ->> TL_n(q))). Four measurements are not a theorem. Turning them
into one needs the arithmetic identity that sits underneath:

    dim radical = n! - sum_{l(lambda) <= 2} (dim V_lambda)^2       (Wedderburn,
                                                                   plus y_lambda = 0
                                                                   iff l(lambda) > 2)

    sum_{l(lambda) <= 2} (dim V_lambda)^2 = Catalan(n)             <-- THE GAP

This probe verifies the second line and the reduction it rests on, so that the
Lean proof in `QOU/Mathlib/BallotNumbers.lean` is checked against independently
computed numbers rather than against its own algebra.

WHAT IS CHECKED, and why each check is independent of the next

  (1) TWO-ROW DIMENSION == BALLOT NUMBER.
      `f^{(n-k,k)}` computed by the HOOK LENGTH FORMULA (products of hooks over
      the actual Young diagram) equals `C(n,k) - C(n,k-1)`. This is the step the
      task framing depends on: it is what lets a statement about Specht
      dimensions become a statement about binomial coefficients, with no
      symmetric-function theory and no RSK.

  (2) FULL PARTITION ENUMERATION, as a control.
      Every partition of n is enumerated and its dimension computed by the same
      hook length formula. Two things are then checked:
        - `sum_{all lambda} (dim)^2 == n!`   (Burnside -- validates the HLF code
          itself, independently of anything two-row)
        - `sum_{l(lambda) <= 2} (dim)^2 == Catalan(n)`
      The second is the target identity, reached WITHOUT going through the
      ballot formula at all. So (1) and (2) can disagree, and would if the
      ballot indexing were off by one -- which is the classic failure mode here
      (`C(n,-1)` truncating to `C(n,0)` in an unsigned type).

  (3) THE CORANK SERIES.
      `n! - Catalan(n)` is printed against the corpus-measured `1, 10, 78, 588`
      at n = 3..6 and extended to n = 14. This is the arithmetic side of the
      extension only: it does NOT re-measure a Gram rank at n >= 7, and must not
      be read as one. What it does is fix the number a future rank measurement
      has to produce.

  (4) THE REFLECTION-ROUTE INTERMEDIATE.
      The Lean proof does not induct. It runs the sum over the FULL range
      k = 0..n+1, where the summand is antisymmetric under k -> n+1-k, and then
      folds:

          sum_{k=0}^{n+1} d_k^2  =  2*(C(2n,n) - C(2n,n-1))  =  2*Catalan(n)

      the first equality by Vandermonde twice, the second because
      `(n+1)*C(2n,n-1) = n*C(2n,n)`. This check pins the intermediate quantity
      the Lean lemma `ballot_sq_sum_full_range` asserts, so a failure here would
      localise to that lemma rather than to the end-to-end statement.

EXACTNESS. Integer arithmetic throughout (`math.comb`, `math.factorial`,
floor division only where the quotient is known to be exact). No floats, no
mpmath, no tolerance -- so this probe is outside the NO-FLOAT64 precision-gate
family by construction, and emits no witness: there is no anchor, no `q_0`, and
nothing that could drift. It is a self-contained arithmetic check.

Exit status is 0 iff every check passes.
"""

from __future__ import annotations

import sys
from math import comb, factorial

MAX_N = 14


def catalan(n: int) -> int:
    """C_n = C(2n,n)/(n+1). Exact: (n+1) divides C(2n,n)."""
    return comb(2 * n, n) // (n + 1)


def partitions(n: int, cap: int | None = None) -> list[tuple[int, ...]]:
    """Every partition of `n` with parts <= `cap`, as weakly decreasing tuples."""
    if cap is None:
        cap = n
    if n == 0:
        return [()]
    out: list[tuple[int, ...]] = []
    for first in range(min(n, cap), 0, -1):
        for rest in partitions(n - first, first):
            out.append((first,) + rest)
    return out


def hook_dim(shape: tuple[int, ...]) -> int:
    """dim of the Specht module S^shape by the hook length formula.

    hook(i,j) = (arm) + (leg) + 1 = (row_i - j) + (col_j - i) - 1 with the
    0-indexed conventions used below.
    """
    n = sum(shape)
    if n == 0:
        return 1
    cols = [sum(1 for r in shape if r > c) for c in range(shape[0])]
    prod = 1
    for i, row in enumerate(shape):
        for j in range(row):
            prod *= (row - j) + (cols[j] - i) - 1
    quotient, remainder = divmod(factorial(n), prod)
    assert remainder == 0, f"hook product does not divide n! for {shape}"
    return quotient


def ballot(n: int, k: int) -> int:
    """m_k(n) = C(n,k) - C(n,k-1), with m_0(n) = 1 pinned rather than computed."""
    return comb(n, k) - (comb(n, k - 1) if k >= 1 else 0)


def check_one_hlf_equals_ballot() -> bool:
    print("(1) two-row hook-length dimension  vs  ballot number C(n,k) - C(n,k-1)")
    print("    %3s %3s %10s %10s %s" % ("n", "k", "hook", "ballot", "ok"))
    ok = True
    for n in range(1, MAX_N + 1):
        for k in range(0, n // 2 + 1):
            shape = (n - k, k) if k > 0 else (n,)
            h, b = hook_dim(shape), ballot(n, k)
            good = h == b
            ok &= good
            if n <= 8 or not good:
                print("    %3d %3d %10d %10d %s" % (n, k, h, b, "OK" if good else "MISMATCH"))
    print("    ... (n = 9..%d checked silently)" % MAX_N)
    print("    (1) VERDICT: %s\n" % ("PASS" if ok else "FAIL"))
    return ok


def check_two_full_enumeration() -> bool:
    print("(2) full partition enumeration -- Burnside control + two-row sum")
    print("    %3s %8s %14s %14s %12s %12s %s"
          % ("n", "#parts", "sum dim^2", "n!", "two-row sum", "catalan", "ok"))
    ok = True
    for n in range(1, MAX_N + 1):
        parts = partitions(n)
        dims = {lam: hook_dim(lam) for lam in parts}
        total = sum(d * d for d in dims.values())
        two_row = sum(d * d for lam, d in dims.items() if len(lam) <= 2)
        burnside_ok = total == factorial(n)
        catalan_ok = two_row == catalan(n)
        good = burnside_ok and catalan_ok
        ok &= good
        print("    %3d %8d %14d %14d %12d %12d %s"
              % (n, len(parts), total, factorial(n), two_row, catalan(n),
                 "OK" if good else ("BURNSIDE-FAIL" if not burnside_ok else "CATALAN-FAIL")))
    print("    (2) VERDICT: %s\n" % ("PASS" if ok else "FAIL"))
    return ok


def check_three_corank_series() -> bool:
    print("(3) corank series  n! - Catalan(n)")
    measured = {3: 1, 4: 10, 5: 78, 6: 588}
    print("    corpus-measured (tl_n6_discriminator.py, Gram rank): "
          + ", ".join("n=%d -> %d" % (k, v) for k, v in sorted(measured.items())))
    ok = True
    for n in range(1, MAX_N + 1):
        value = factorial(n) - catalan(n)
        tag = ""
        if n in measured:
            good = value == measured[n]
            ok &= good
            tag = "  <- measured %d  %s" % (measured[n], "OK" if good else "MISMATCH")
        elif n >= 7:
            tag = "  (arithmetic only -- NOT a rank measurement)"
        print("    n=%2d: %14d - %8d = %14d%s" % (n, factorial(n), catalan(n), value, tag))
    print("    (3) VERDICT: %s\n" % ("PASS" if ok else "FAIL"))
    return ok


def check_four_reflection_intermediate() -> bool:
    print("(4) reflection-route intermediate: sum_{k=0}^{n+1} d_k^2 = 2*Catalan(n)")
    print("    %3s %12s %28s %12s %s"
          % ("n", "full sum", "2*(C(2n,n) - C(2n,n-1))", "2*catalan", "ok"))
    ok = True
    for n in range(1, MAX_N + 1):
        full = sum(ballot(n, k) ** 2 for k in range(0, n + 2))
        vandermonde = 2 * (comb(2 * n, n) - comb(2 * n, n - 1))
        twice = 2 * catalan(n)
        good = full == vandermonde == twice
        ok &= good
        print("    %3d %12d %28d %12d %s" % (n, full, vandermonde, twice, "OK" if good else "BAD"))
    print("    (4) VERDICT: %s\n" % ("PASS" if ok else "FAIL"))
    return ok


def check_five_half_sum() -> bool:
    """The end-to-end statement the Lean file proves, in the Lean file's own indexing."""
    print("(5) the Lean statement itself: sum_{k in range(n/2 + 1)} ballot(n,k)^2 = catalan(n)")
    ok = True
    rows = []
    for n in range(0, MAX_N + 1):
        half = sum(ballot(n, k) ** 2 for k in range(0, n // 2 + 1))
        good = half == catalan(n)
        ok &= good
        rows.append("n=%d:%d%s" % (n, half, "" if good else "!=%d" % catalan(n)))
    print("    " + "  ".join(rows))
    print("    (5) VERDICT: %s\n" % ("PASS" if ok else "FAIL"))
    return ok


def main() -> int:
    print(__doc__.split("\n")[0])
    print("=" * 78)
    print()
    results = [
        check_one_hlf_equals_ballot(),
        check_two_full_enumeration(),
        check_three_corank_series(),
        check_four_reflection_intermediate(),
        check_five_half_sum(),
    ]
    print("=" * 78)
    if all(results):
        print("ALL CHECKS PASS (n = 1..%d)." % MAX_N)
        print()
        print("Reading: the two-row Specht dimension IS the ballot number in this")
        print("repo's conventions, and the two-row square-sum IS Catalan(n). So")
        print("corank(n) = n! - Catalan(n) reduces to a finite binomial identity")
        print("with no RSK and no symmetric-function input. That identity is proved")
        print("for general n in QOU/Mathlib/BallotNumbers.lean.")
        return 0
    print("FAILURES: %s" % [i + 1 for i, r in enumerate(results) if not r])
    return 1


if __name__ == "__main__":
    sys.exit(main())

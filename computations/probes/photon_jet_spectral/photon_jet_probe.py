#!/usr/bin/env python3
"""Exact symbolic probe for docs/audits/2026-11-25-photon-jet-and-hearing-the-shape.md.

Tests pre-registered predictions P1-P7 in H_3(q) over Q(q), exact sympy arithmetic
(no floats). Photon = def:photon, gamma = 1 + f0*s0 + f1*s1 + f01*s0*s1^{-1}.
Markov trace: Ocneanu, convention D z = q^3/(q^2+1). Writes a witness JSON.
"""
import json, itertools, sys
from pathlib import Path
import sympy as sp

q = sp.symbols('q', nonzero=True)
h = q - 1/q
zD = q**3/(q**2 + 1)
z = sp.symbols('z')  # generic Markov parameter where stated

# --- H_3 regular rep in the basis T_w, w in S_3 as reduced words over {0,1}
B = ['e', '0', '1', '01', '10', '010']          # 010 = 101 = e^- (electron word)
idx = {b: i for i, b in enumerate(B)}
# left multiplication by s on basis words: (length up? -> concat) else Hecke
left = {
    '0': {'e': '0', '1': '01', '10': '010'},
    '1': {'e': '1', '0': '10', '01': '010'},
}
down = {'0': {'0': 'e', '01': '1', '010': '10'}, '1': {'1': 'e', '10': '0', '010': '01'}}

def Lmat(s):
    M = sp.zeros(6, 6)
    for b in B:
        j = idx[b]
        if b in left[s]:
            M[idx[left[s][b]], j] += 1
        else:  # T_s T_w with l(sw)<l(w): h*T_w + T_{sw}
            M[j, j] += h
            M[idx[down[s][b]], j] += 1
    return M

S0, S1 = Lmat('0'), Lmat('1')
I6 = sp.eye(6)
assert sp.simplify(S0*S1*S0 - S1*S0*S1) == sp.zeros(6, 6)
assert sp.simplify(S0*S0 - h*S0 - I6) == sp.zeros(6, 6)
S1inv = S1 - h*I6
assert sp.simplify(S1*S1inv - I6) == sp.zeros(6, 6)
V = S0*S1inv

def vec(M):  # element as vector = M applied to T_e
    return sp.simplify(M[:, 0])

def trM(M, zz=zD):
    t = {'e': 1, '0': zz, '1': zz, '01': zz**2, '10': zz**2, '010': (h*zz + 1)*zz}
    v = vec(M)
    return sp.simplify(sum(v[idx[b]]*t[b] for b in B))

res = {}
f0, f1, f01 = sp.symbols('phi0 phi1 phi01')
G = I6 + f0*S0 + f1*S1 + f01*V

# P2 augmentations: trivial eps(s)=q, sign eps(s)=-1/q ; eps(T_w)=eps^len
def eps(M, a):
    v = vec(M); ln = {b: (0 if b == 'e' else len(b)) for b in B}
    return sp.simplify(sum(v[idx[b]]*a**ln[b] for b in B))
res['P2_eps_trivial_gamma'] = str(sp.expand(eps(G, q)))
res['P2_eps_sign_gamma'] = str(sp.expand(eps(G, -1/q)))

# P1: (s-q)^2 = -[2]_q (s-q) ; and s0-q == s1-q mod I^2 via braid relation
P1a = sp.simplify((S0 - q*I6)**2 + (q + 1/q)*(S0 - q*I6))
res['P1_hecke_torsion_identity_holds'] = bool(P1a == sp.zeros(6, 6))
# I/I^2 over Q(q): rank of I^2 vs I (I = ker eps_trivial as subspace of H as vectors)
def ideal_span(gens):
    vs = []
    for g in gens:
        for a in B:
            for b in B:
                pass
    return vs
# I spanned by T_w - q^{l(w)} ; compute I^2 = span{x*y}
Ibasis = []
for b in B[1:]:
    M = sp.eye(6)
    for ch in b: M = M * (S0 if ch == '0' else S1)
    Ibasis.append(M - q**len(b)*I6)
prods = [vec(x*y) for x in Ibasis for y in Ibasis]
rI2 = sp.Matrix.hstack(*prods).rank(simplify=True)
res['P1_rank_I'] = 5; res['P1_rank_I2_over_Qq'] = int(rI2)

# P3: single-photon trace (generic z, then D)
res['P3_trM_gamma_generic_z'] = str(sp.factor(sp.expand(trM(G, z))))
res['P3_trM_gamma_D'] = str(sp.factor(sp.expand(trM(G))))

# P4: Frobenius Gram on W = {s0, s1, V}
W = {'s0': S0, 's1': S1, 'V': V}
Gram = {}
for a, b in itertools.product(W, W):
    Gram[f'{a},{b}'] = str(sp.factor(trM(W[a]*W[b], z)))
res['P4_gram_generic_z'] = Gram
diff = sp.factor(trM(S0*V, z) - trM(S1*V, z))
res['P4_G(s0,V)-G(s1,V)_generic_z'] = str(diff)
res['P4_G(s0,V)-G(s1,V)_D'] = str(sp.factor(diff.subs(z, zD)))
# two-photon trace
g0, g1, g01 = sp.symbols('psi0 psi1 psi01')
G2 = I6 + g0*S0 + g1*S1 + g01*V
res['P4_trM_gamma_gamma_D_minus_flip'] = str(sp.factor(sp.expand(
    trM(G*G2) - trM(G*G2).subs({f0: f1, f1: f0, g0: g1, g1: g0}, simultaneous=True))))

# P5: photon filtration ranks
def span_rank(mats):
    return sp.Matrix.hstack(*[vec(m) for m in mats]).rank(simplify=True)
F = {0: [I6], 1: [I6, S0, S1, V]}
F[2] = F[1] + [x*y for x in [S0, S1, V] for y in [S0, S1, V]]
res['P5_rank_F'] = [span_rank(F[k]) for k in (0, 1, 2)]
# gr_2 basis check: F1 + {L-, e-} spans H3?
Lm, Ee = S1*S0, S0*S1*S0
res['P5_F1_plus_Lminus_eminus_rank'] = span_rank(F[1] + [Lm, Ee])
res['P5_L+_in_F1'] = span_rank(F[1] + [S0*S1]) == 4
res['P5_commutator_s0s1_notin_F1'] = span_rank(F[1] + [S0*S1 - S1*S0]) == 5
# symmetric part of W.W (anticommutators) mod F1
sym = [x*y + y*x for x in [S0, S1, V] for y in [S0, S1, V]]
res['P5_rank_F1_plus_sym'] = span_rank(F[1] + sym)
# filtration of W-subalgebra closure under commutator: is R+W a Lie subalgebra? and Lie alg generated by W
def comm(a, b): return a*b - b*a
LieW = [S0, S1, V]
res['P5_W_closed_under_commutator'] = span_rank([I6, S0, S1, V] + [comm(a, b) for a in LieW for b in LieW]) == 4

# P6: (2,1) block. Build 2x2 rep and test traceless parts
a = sp.Matrix([[q, 1], [0, -1/q]]); b = sp.Matrix([[-1/q, 0], [1, q]])
assert sp.simplify(a*b*a - b*a*b) == sp.zeros(2, 2)
assert sp.simplify(a*a - h*a - sp.eye(2)) == sp.zeros(2, 2)
binv = b - h*sp.eye(2); v = a*binv
def tl(M): return sp.simplify(M - M.trace()/2*sp.eye(2))
res['P6_tl_s0_squared_scalar'] = str(sp.factor(sp.simplify((tl(a)**2)[0, 0])))
res['P6_tl_s0_nilpotent'] = bool(sp.simplify(tl(a)**2) == sp.zeros(2, 2))
res['P6_tl_V_squared_scalar'] = str(sp.factor(sp.simplify((tl(v)**2)[0, 0])))
# Killing (trace form on sl2 = tr(XY)) Gram of traceless parts
T = {'s0': tl(a), 's1': tl(b), 'V': tl(v)}
res['P6_sl2_trace_gram'] = {f'{x},{y}': str(sp.factor(sp.simplify((T[x]*T[y]).trace()))) for x in T for y in T}
res['P6_sl2_gram_det'] = str(sp.factor(sp.Matrix(3, 3, lambda i, j: (list(T.values())[i]*list(T.values())[j]).trace()).det()))
res['P6_V_trace_det'] = [str(sp.factor(v.trace())), str(sp.factor(v.det()))]

# P7: audibility of q from single-photon response under D
q2 = sp.symbols('q2', nonzero=True)
sol = sp.solve([sp.Eq(q - 1/q, q2 - 1/q2)], q2)
res['P7_h_preimages'] = [str(s) for s in sol]
res['P7_zD_at_minus_qinv_minus_zD'] = str(sp.factor(zD.subs(q, -1/q) - zD))

out = Path(__file__).with_name('photon-jet-probe.witness.json')
out.write_text(json.dumps({'description': 'photon jet / hearing-the-shape exact probe, H_3(q), convention D', 'q0Value': None, 'exact': True, 'results': res}, indent=1, ensure_ascii=False))
for k, val in res.items(): print(k, ':', val)

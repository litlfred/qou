import json,sys
S=sys.argv[1]; lim=int(sys.argv[2]) if len(sys.argv)>2 else 10**9
D=json.load(open(S+"/lean_gen.json"))
H='''import QOU.MassTheory.PhotonPairReachability

/-!
# No six-strand γγ word in the pair test is a product of two photons (1370 cells)

Instances of `QOU.MassTheory.PhotonPairReachability.not_photonPair_eq_smul` for the γγ words of
the six-strand pair test (`computations/probes/six_strand_photon_pair/`, PR #9050). Each word is a
product of vertices `Vₖ = σₖσₖ₊₁⁻¹` (3 or 5 vertices, the 88 words matching a lepton pair's link).
For each word and each pair of photon positions `(i, j)` (`γᵢ` on strands `i, i+1, i+2`), the
statement is: there are no weights `a, b, c, a', b', c'` and no `μ ≠ 0` with
`γᵢ(a,b,c) γⱼ(a',b',c') = μ · w` on the one-marked-strand sector.

Each theorem names a matrix entry `(s → r)` of the word outside the reach of `γᵢγⱼ`. The entry is
a monomial `±q^A`, `±qi^B`, or that times `h = q − qi`, so it is nonzero for **every** `q` with
`q·qi = 1` and `q − qi ≠ 0`, i.e. every `q ≠ 0, ±1` — not only generic `q`.

Coverage: 1370 of the 1395 non-factorising (word, i, j) cells. Not covered here:
* the 13 cells that DO factorise (`PhotonCrossingMonomials`, probe check
  `P2_two_photon_factorisations_reported`);
* 25 cells where the one-marked-strand sector does not obstruct; the probe excludes them by a
  Gröbner computation over `ℚ(q)` in the full representation (`P2_generic_q_two_photon`), which is
  computer algebra, not Lean.

The sector maps are a representation of the Hecke algebra (`PhotonPairReachability`'s
`sig_sigInv`, `sigInv_sig`, `sig_quadratic`, `sig_braid`, `sig_comm`), so an equation
`γᵢγⱼ = μ·w` in `H₆(q)` would hold on the sector; that lift from the abstract Hecke algebra is
stated in prose, not formalised.

Generated by `computations/probes/six_strand_photon_pair/lean_gen/` from the probe's own words; every entry was checked
against the probe's representation before emission.

-- Ref: [leitner2026] computations/probes/six_strand_photon_pair/six_strand_pair_probe.py
-/

namespace QOU.MassTheory.PhotonPairNoFactor

open QOU.MassTheory.PhotonPairReachability

set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false

variable {K : Type*} [Field K]

'''
body=[]
used=set()
for k,name,lw in D["words"]:
    body.append(f"/-- The γγ word `{name}`. -/\ndef w{k} : List (ℕ × Bool) := {lw}\n")
cnt=0
for g in D["groups"][:lim]:
    k=g["k"]; t=f"{k}_{g['g']}"
    body.append(f'''/-- `{g['word']}`: entry `{g['s']} → {g['r']}` blocks {g['n']} placements. -/
theorem noPair_{t} (q qi : K) (hqi : q * qi = 1) (hh : q - qi ≠ 0) (i j : ℕ)
    (hij : (i, j) ∈ ({g['cells']} : List (ℕ × ℕ))) (a b c a' b' c' μ : K) (hμ : μ ≠ 0) :
    ¬ ∀ v, photon q qi a b c i (photon q qi a' b' c' j v) = fun p => μ * wordAct q qi w{k} v p := by
  have key : ∀ p ∈ ({g['cells']} : List (ℕ × ℕ)), ¬ Reach2 p.1 p.2 {g['s']} {g['r']} := by decide
  refine not_photonPair_eq_smul q qi a b c a' b' c' μ i j {g['s']} {g['r']} _ (key (i, j) hij) ?_ hμ
  have hq : q ≠ 0 := left_ne_zero_of_mul_eq_one hqi
  have hq' : qi ≠ 0 := right_ne_zero_of_mul_eq_one hqi
  have e : wordAct q qi w{k} (basisVec {g['s']}) {g['r']} = {g['T']} := by
    have : wordAct q qi w{k} (basisVec {g['s']}) {g['r']} = {g['E']} := by
      simp only [wordAct, w{k}, sig, sigInv, basisVec, Nat.reduceAdd, Nat.reduceEqDiff, ↓reduceIte]
      try ring
    rw [this]
    try linear_combination ({g['cof']}) * hqi
  rw [e]; simp [hq, hq', hh]
''')
    cnt+=g["n"]
open(sys.argv[3],"w").write(H+"\n".join(body)+"\nend QOU.MassTheory.PhotonPairNoFactor\n")
print("cells",cnt)

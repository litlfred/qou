x2 = B.scal(pow(z2v, inv3, MOD))
checks["cube_roots_exact"] = (
    B.pw(x1, 3) == B.scal(z1v) and B.pw(x2, 3) == B.scal(z2v))


def Dz(x):
    r = B.one()
    for k in (1, 2):
        r = B.mul(r, B.pw(B.sub(B.one(), B.mul(B.pw(Z3, k), x)), k))
    return r


D1inv = B.inv(Dz(B.one()))


def Pz(x):
    return B.mul(Dz(x), D1inv)


def cls(u):
    v = B.pw(B.teich(u), 8)
    cur = B.one()
    for j in range(3):
        if cur == v:
            return j
        cur = B.mul(cur, Z3)
    return None


c1, c2 = cls(Pz(x1)), cls(Pz(x2))
detail["per_symbol_class_c1_of_z1"] = c1
detail["per_symbol_class_c2_of_z2"] = c2

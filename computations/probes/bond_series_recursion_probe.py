"""A universal 3-term recursion on the bond series — and exactly where it breaks.

WHAT THIS TESTS
---------------
The atom word's trace factorises over nucleon BLOCKS and interface BONDS
(bean `qou-qqm4`), and the bond factors are measured to order 4 (`qou-yaig`,
#7002 and the c4 run). Writing each bond as `(1/2)(1, rho, tau, ups, chi)`:

    pp   (1,  2, 1/2, -1/2,  1/4)
    pn   (1,  0, 3/2, -3/2, 31/12)
    nn   (1, -2, 5/2, -5/2,  9/4)

Ask whether one recursion `c_{k+1} = A_k c_k + B_k c_{k-1}`, with coefficients
depending on `k` but NOT on which bond, generates every one of them.

WHY IT IS A TEST AND NOT A FIT
------------------------------
Two unknowns per rung, three bonds -> THREE equations. The system is
OVERDETERMINED by one, so a solution existing at all is a real constraint.
`A_k, B_k` are solved on two bonds and CHECKED on the third, then re-verified on
all three.

RESULT
------
    k = 1   A = -1/2   B = 3/2    HOLDS
    k = 2   A = -1     B = 0      HOLDS   (this IS the ups = -tau relation)
    k = 3   rank-deficient; its forced consequence is FALSE -> BREAKS

**The k = 3 case is not a failure to solve — it is informative, and reporting it
as "singular, skipped" would understate it.** After k = 2 every bond has
`(c3, c2) = (-tau, tau)`, all proportional to `(-1, 1)`, so the 3-term ansatz has
rank 1 at k = 3 and cannot be inverted. What it still FORCES is

    c4 = A*(-tau) + B*(tau) = (B - A)*tau      i.e.  c4 proportional to tau

and the measured ratios `c4/tau` are `1/2`, `31/18`, `9/10` — not constant. So
the universal 3-term recursion is REFUTED at k = 3 rather than merely unsolvable.

WHAT THIS DOES AND DOES NOT SAY
-------------------------------
- It says the first two rungs of every bond series are generated by one
  bond-independent rule, which is more than the `rho = p_b - n_b`,
  `tau = 1/2 + n_b` description supplies (that is three values with one spare
  dof; this is a relation with none).
- It does NOT say the whole series is recursive. It stops at k = 3, measured.
- It does NOT identify the rule with anything. In particular it is NOT the
  registry's `a_n` recursion (checked below): that gives `(-3/4, -1/8)` at n = 1
  and `(-1, -1/4)` at n = 2, so only the single coefficient `A = -1` coincides
  and both `B` disagree. One coincidence is not an identification, and it is
  cross-checked here so nobody reads it as one.
- Three bonds is three data points. A rule fitted to two and checked on one is a
  real but thin test, and the honest weight to give it is "worth deriving", not
  "derived".

NUCLEON SERIES ARE DELIBERATELY NOT CLAIMED. There are only two of them, so two
equations for two unknowns at every rung: always solvable, never a test. The
solve is printed and explicitly labelled a fit.

NO FLOAT: exact `fractions.Fraction` throughout.
"""
from __future__ import annotations

from fractions import Fraction as F

BOND = {
    "pp": [F(1), F(2), F(1, 2), F(-1, 2), F(1, 4)],
    "pn": [F(1), F(0), F(3, 2), F(-3, 2), F(31, 12)],
    "nn": [F(1), F(-2), F(5, 2), F(-5, 2), F(9, 4)],
}
NUC = {"p": [F(1), F(3, 2), F(23, 4), F(75, 4), F(-37, 2)],
       "n": [F(1), F(-1), F(3), F(19), F(-57, 2)]}


def solve_pair(s1, s2, k):
    """A, B from c_{k+1} = A c_k + B c_{k-1} on two series; None if singular."""
    x1, y1, z1 = s1[k], s1[k - 1], s1[k + 1]
    x2, y2, z2 = s2[k], s2[k - 1], s2[k + 1]
    det = x1 * y2 - x2 * y1
    if det == 0:
        return None
    return ((z1 * y2 - z2 * y1) / det, (x1 * z2 - x2 * z1) / det)


def main() -> int:
    names = list(BOND)
    failures, held = [], []
    print("=" * 74)
    print("  universal 3-term recursion on the bond series?")
    print("  c_{k+1} = A_k c_k + B_k c_{k-1}, A_k/B_k independent of the bond")
    print("=" * 74)

    for k in (1, 2, 3):
        sols = {}
        for i in range(len(names)):
            for j in range(i + 1, len(names)):
                r = solve_pair(BOND[names[i]], BOND[names[j]], k)
                if r:
                    sols[(names[i], names[j])] = r
        if not sols:
            # rank-deficient: report the CONSEQUENCE it still forces
            ratios = {n: BOND[n][k + 1] / BOND[n][k - 1] for n in names}
            uniq = set(ratios.values())
            print(f"  k={k}: every pair is SINGULAR — (c{k}, c{k-1}) is "
                  f"proportional to (-1, 1) in all three bonds.")
            print(f"        The ansatz still forces c{k+1} proportional to c{k-1}:")
            for n, v in ratios.items():
                print(f"          {n}: c{k+1}/c{k-1} = {v}")
            if len(uniq) == 1:
                print(f"        constant -> consistent, but NOT determined here")
                held.append((k, "rank-deficient but consistent"))
            else:
                print(f"        NOT constant -> the universal recursion is "
                      f"REFUTED at k={k}")
                failures.append(k)
            continue
        A, B = next(iter(sols.values()))
        allok = all(A * BOND[n][k] + B * BOND[n][k - 1] == BOND[n][k + 1]
                    for n in names)
        agree = all(v == (A, B) for v in sols.values())
        print(f"  k={k}: A={A}  B={B}   verified on all three: {allok}   "
              f"every pair agrees: {agree}")
        if allok and agree:
            held.append((k, f"A={A}, B={B}"))
        else:
            failures.append(k)

    print()
    print("  cross-check — is this the registry's a_n recursion?")
    print("    a_{n+1} = -3n/(2(n+1)) a_n - (2n-1)/(4(n+1)) a_{n-1}")
    for n in (1, 2, 3):
        print(f"      n={n}: ({F(-3*n, 2*(n+1))}, {F(-(2*n-1), 4*(n+1))})")
    print("    measured: k=1 (-1/2, 3/2), k=2 (-1, 0). Only A at n=2 coincides;")
    print("    both B disagree. NOT the same recursion.")

    print()
    print("  nucleon series — solved, and labelled a FIT, not a test")
    print("  (two series, two unknowns per rung: always solvable, never a check)")
    for k in (1, 2, 3):
        r = solve_pair(NUC["p"], NUC["n"], k)
        print(f"      k={k}: {'A=%s B=%s' % r if r else 'singular'}")

    print()
    print("=" * 74)
    for k, what in held:
        print(f"  k={k}: HOLDS  {what}")
    for k in failures:
        print(f"  k={k}: BREAKS")
    print("=" * 74)
    print("  Two rungs generated by one bond-independent rule; the third refuted.")
    print("  Three bonds is three data points — 'worth deriving', not 'derived'.")
    print()
    if held and failures == [3]:
        print("PASS  k=1 and k=2 hold (overdetermined); k=3 refuted, as measured")
        return 0
    print(f"UNEXPECTED  held={held} failures={failures} — re-read before quoting")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())

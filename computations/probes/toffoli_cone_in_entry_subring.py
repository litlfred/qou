import mpmath as mp                                          # noqa: E402
import sympy as sp                                           # noqa: E402
from toffoli_nf_coordinates_and_lp_feasibility import (      # noqa: E402
    chain_element, decode, toffoli_element, NF, q,
)

mp.mp.dps = 60

# ---------------------------------------------------------------- H_3(q)
H = q - 1 / q
Z = q ** 3 / (q ** 2 + 1)                      # convention D
E, A, B, AB, BA, W = (), (0,), (1,), (0, 1), (1, 0), (0, 1, 0)

# right multiplication by a generator, in the Hecke normal-form basis
RMUL = {
    (E, 0): {A: 1},           (E, 1): {B: 1},
    (A, 0): {A: H, E: 1},     (A, 1): {AB: 1},
    (B, 0): {BA: 1},          (B, 1): {B: H, E: 1},
    (AB, 0): {W: 1},          (AB, 1): {AB: H, A: 1},
    (BA, 0): {BA: H, B: 1},   (BA, 1): {W: 1},
    (W, 0): {W: H, AB: 1},    (W, 1): {W: H, BA: 1},
}
TR = {E: sp.Integer(1), A: Z, B: Z, AB: Z ** 2, BA: Z ** 2,
      W: q ** 3 * (q ** 4 + 1) / (q ** 2 + 1) ** 2}

CONE_NUM = q ** 10 + q ** 6 - q ** 4 + q ** 2 - 1
DEN = q ** 6 * (q ** 2 + 1) ** 4              # common denominator
AMBIENT = 21                                   # numerator degree <= 20

CHECKS: list[tuple[str, bool]] = []


def check(name, ok, detail=""):
    CHECKS.append((name, bool(ok)))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    if detail:
        print(f"         {detail}")


def _rmul(vec, g):
    out: dict = {}
    for w, c in vec.items():
        for w2, c2 in RMUL[(w, g)].items():
            out[w2] = out.get(w2, 0) + c * c2
    return out


def _wmul(w1, w2):
    v = {w1: sp.Integer(1)}
    for g in w2:
        v = _rmul(v, g)
    return v


def gram_symbolic():
    def tr(v):
        return sp.cancel(sum(c * TR[w] for w, c in v.items()))
    return [[tr(_wmul(NF[i], NF[j])) for j in range(6)] for i in range(6)]


def entries():
    def V(i, o):
        a, b = chain_element(i, o)
        return sp.cancel(Z * a + b)

    def tout(k):
        b1, b2, b3 = decode(k)
        return (b1 << 2) | (b2 << 1) | (b3 ^ (b1 & b2))

    raw: dict[str, sp.Expr] = {}
    for k in range(8):
        o = decode(k)
        raw[f"M{k}{k}"] = sp.cancel(V(0, o) * V(1, o))
        m = tout(k)
        if m != k:
            om = decode(m)
            Vp = [V(i, o) for i in range(2)]
            Vd = [V(i, om) for i in range(2)]
            raw[f"M{m}{k}"] = sp.cancel(sum(
                sp.prod([Vp[j] for j in range(2) if j != c]) * (Vp[c] - Vd[c])
                for c in range(2)))
    distinct: dict[str, sp.Expr] = {}
    for n, e in sorted(raw.items()):
        if not any(sp.simplify(e - v) == 0 for v in distinct.values()):
            distinct[n] = e
    return distinct


def numvec(expr):
    """Coefficient vector of `expr * DEN`, as a degree-20 polynomial in q."""
    p = sp.Poly(sp.expand(sp.cancel(expr * DEN)), q)
    coeffs = p.all_coeffs()[::-1]
    if len(coeffs) > AMBIENT:
        raise AssertionError(f"degree {len(coeffs) - 1} exceeds ambient")
    return coeffs + [sp.Integer(0)] * (AMBIENT - len(coeffs))


def span(distinct, names, *, cross: bool):
    items = [("1", sp.Integer(1))]
    items += [(n, distinct[n]) for n in names]
    for i, a in enumerate(names):
        for b in names[i:]:
            if cross or a == b:
                items.append((f"{a}*{b}", sp.cancel(distinct[a] * distinct[b])))
    return items


def analyse(distinct, names, target, *, cross: bool):
    items = span(distinct, names, cross=cross)
    M = sp.Matrix([numvec(e) for _, e in items])
    r = M.rank()
    r2 = M.col_join(sp.Matrix([numvec(target)])).rank()
    return items, M, r, r2


def main() -> int:
    print("=" * 74)
    print("  THE CONE CONDITION LIVES IN THE DEGREE-2 SUBRING OF THE ENTRIES")
    print("=" * 74)
    print()

    # ---- 1. the symbolic Gram is the one pyhecke computes -----------------
    G = gram_symbolic()
    from pyhecke.gram import gram_matrix_mp
    from qou_substrate.constants import Q_50_DIGIT_STR

    worst = mp.mpf(0)
    for qstr in ["0.7", Q_50_DIGIT_STR, "1.7"]:
        Gn = gram_matrix_mp(q=mp.mpf(qstr))
        qq = sp.Rational(qstr)
        for i in range(6):
            for j in range(6):
                sym = mp.mpf(sp.nsimplify(G[i][j].subs(q, qq)).evalf(55).__str__())
                worst = max(worst, abs(sym - mp.mpf(str(Gn[i][j]))))
    check("symbolic Gram reproduces pyhecke.gram.gram_matrix_mp",
          worst < mp.mpf("1e-45"),
          f"max |symbolic - mpmath| = {mp.nstr(worst, 5)} over 3 anchors "
          f"(0.7, proton q0, 1.7) at 60 dps")

    # ---- 2. the cone coordinate -------------------------------------------
    T7 = toffoli_element(decode(7))
    t = [sp.cancel(T7.get(w, sp.Integer(0))) for w in NF]
    Gt = [sp.cancel(sum(G[i][j] * t[j] for j in range(6))) for i in range(6)]
    target = Gt[5]
    check("cone coordinate (row 5) = (q^10+q^6-q^4+q^2-1)/(q^2+1)^2",
          sp.simplify(target - CONE_NUM / (q ** 2 + 1) ** 2) == 0,
          f"row 5 = {sp.factor(target)}; denominator > 0 for q > 0, so the "
          f"sign is the numerator's")

    # ---- 3. the entries ----------------------------------------------------
    D8 = entries()
    names = list(D8)
    print()
    print(f"  distinct 8x8 entries ({len(names)}):")
    for n in names:
        print(f"    {n:<5} = {sp.factor(D8[n])}")
    print()

    # ---- 4. degree-2 span of all eight ------------------------------------
    items, M, r, r2 = analyse(D8, names, target, cross=True)
    check("the degree-2 span is a PROPER subspace (membership is informative)",
          r < AMBIENT,
          f"{len(items)} generators -> rank {r} of ambient {AMBIENT} "
          f"(codimension {AMBIENT - r})")
    check("the cone coordinate IS in the degree-2 span of the eight entries",
          r2 == r, f"rank with target appended: {r2} (unchanged)")

    # ---- 5. squares alone are not enough ----------------------------------
    _, _, rs, rs2 = analyse(D8, names, target, cross=False)
    check("squares alone do NOT suffice -- the cross terms are load-bearing",
          rs2 > rs,
          f"{{1}} u entries u squares: rank {rs}; with target {rs2} -> OUTSIDE")

    # ---- 6. four entries suffice, with an explicit witness ----------------
    four = ["M00", "M33", "M44", "M77"]
    items4, M4, r4, r4b = analyse(D8, four, target, cross=True)
    check(f"a smaller span over {{{', '.join(four)}}} still contains it",
          r4b == r4 and r4 < r,
          f"rank {r4} of {AMBIENT} (codimension {AMBIENT - r4}), strictly "
          f"inside the rank-{r} span")

    sol, params = M4.T.gauss_jordan_solve(sp.Matrix(numvec(target)))
    x = sol.subs({p: 0 for p in params})
    terms = [(items4[i][0], x[i]) for i in range(len(items4)) if x[i] != 0]
    print()
    print(f"  WITNESS ({len(terms)} terms):")
    for n, c in terms:
        print(f"      {n:<12} * {c}")
    print()

    lookup = dict(items4)
    recon = sum(c * lookup[n] for n, c in terms)
    check("the witness verifies symbolically to exact zero",
          sp.simplify(sp.cancel(recon - target)) == 0,
          "sympy cancel/simplify of (witness - cone coordinate) = 0 over Q(q)")

    # ---- 7. scope guard ----------------------------------------------------
    div = [n for n, e in D8.items()
           if sp.rem(sp.Poly(sp.expand(sp.numer(sp.cancel(e))), q),
                     sp.Poly(CONE_NUM, q)).is_zero]
    check("no entry's numerator is divisible by the cone numerator "
          "(the monomial exclusion is untouched)",
          not div, f"divisible: {div or 'none'} -> the published reduction, "
          f"which is a monomial times a sign, stays refuted")

    n_ok = sum(1 for _, ok in CHECKS if ok)
    print()
    print("=" * 74)
    print(f"  {n_ok}/{len(CHECKS)} assertions")
    print("=" * 74)
    print()
    print("  VERDICT.  Question (iii) of bean qou-dwf4 is answered POSITIVE with")
    print("  a codimension-6 witness: the cone condition is a degree-2 polynomial")
    print("  in the 8x8 amplitudes, needing cross terms and no division.  It is")
    print("  NOT a monomial, which is why prop:toffoli-lp-stability's reduction")
    print("  fails -- the cone's extra root at q_c ~ 0.8945 is produced by")
    print("  cancellation BETWEEN products, not by any single amplitude vanishing.")
    return 0 if n_ok == len(CHECKS) else 1


if __name__ == "__main__":
    sys.exit(main())

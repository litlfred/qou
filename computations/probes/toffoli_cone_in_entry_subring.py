"""The cone condition IS in the degree-2 subring of the 8x8 entries -- and that
is informative, because the span is codimension 6, not everything.

WHAT WAS ASKED.  Bean qou-ahu3's question (b) -- "is there ANY relation between
the 8x8 strand-type amplitudes and the LP cone condition?" -- was measured
VACUOUS in `toffoli_8x8_to_cone_relation.py`: four of the entries reconstruct q
itself, so the entries generate the whole field Q(q) and every rational function
of q is a rational expression in them.  The successor question (bean qou-dwf4,
item iii) restricted the FORM:

    is the cone condition in the SUBRING generated by the entries -- reachable
    by additions and multiplications alone -- as opposed to the field, which
    needs a division and is therefore everything?

ANSWER: YES, at degree 2, and the measurement that makes it a result rather
than a tautology is the CODIMENSION.

THE MEASUREMENT.  Put every element over the common denominator
D = q^6 (q^2+1)^4; each numerator is then a polynomial of degree <= 20, so the
ambient space is 21-dimensional.

    {1} u {8 distinct entries} u {45 pairwise products}   rank 15 of 21
    the cone coordinate appended                          rank 15  -> IN SPAN

Rank 15 in ambient 21 is a PROPER subspace of codimension 6.  A generic
rational function with this denominator is NOT in it; membership is a
one-in-2^6-of-the-coordinates coincidence, not an identity satisfied by
everything.  That is the whole difference from question (b), where the answer
was forced.

TWO SHARPENINGS, both measured below.

  * Squares alone are NOT enough.  {1} u entries u {squares} spans only rank
    14 and the cone coordinate raises it to 15 -- so it is OUTSIDE.  The CROSS
    terms M_ij M_kl are doing real work; this is not "any quadratic will do".

  * FOUR entries suffice.  {M00, M33, M44, M77} at degree 2 spans rank 14 --
    smaller still -- and the cone coordinate is in THAT.  The 10-term witness
    is printed and verified symbolically to exact zero.

WHAT THIS DOES *NOT* SHOW.  It does not revive prop:toffoli-lp-stability.  That
block's reduction reads the cone condition off "P_77 . W_std with the sign of
P_76" -- a MONOMIAL times a sign -- and the zero-set refutation of that stands
untouched (the cone numerator vanishes at q_c ~ 0.8945, where no entry does).
A degree-2 polynomial expression is a strictly larger class than a monomial:
e1*e2 - e3*e4 can vanish where none of e1..e4 does, which is exactly how the
cone's extra root is produced.  So this result explains WHY the published
reduction had to fail -- the relation exists but needs cancellation between
terms, which a single product cannot supply -- and does not restore it.

Exact symbolic arithmetic throughout (sympy over Q(q)).  The one numeric step
is a cross-validation of the symbolic Gram against `pyhecke.gram.gram_matrix_mp`,
run in mpmath at 60 dps; no float64 anywhere, and no accuracy claim is made from
it -- it is an agreement check between two implementations.
"""


P0 = [-81, 112, -78, -70, 94, -38, 5]
P1 = [138, -254, 127, 44, -89, 38, -5]
P2 = [135, -101, -11, 61, -33, 5]


def _load():
    here = Path(__file__).resolve().parent
    spec = importlib.util.spec_from_file_location(
        "p5", str(here / "qbeta_5two_quantum_volume_probe.py"))
    P = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(P)
    return P


def delta(x, y):
    return y - (1 + x + 1 / x) / y + 2 / y ** 2


def c1(x, y, d):
    s = x + 1 + 1 / x
    p0 = sum(c * s ** k for k, c in enumerate(P0))
    p1 = sum(c * s ** k for k, c in enumerate(P1))
    p2 = sum(c * s ** k for k, c in enumerate(P2))
    return 2j * mp.pi * (p0 + p1 * y + p2 * y * y) / (24 * d ** 3)


def saddles(m):
    m2 = m * m
    A = [m2, -(m2 + 1), mp.mpf(1)]
    B = [-mp.mpf(1), m2]
    C = [mp.mpf(0)] * 4
    for i, a in enumerate(A):
        for j, b in enumerate(B):
            C[i + j] += a * b
    C[2] += -m2
    return [(y / (m2 - y), y) for y in mp.polyroots(C, maxsteps=300, extraprec=150)]



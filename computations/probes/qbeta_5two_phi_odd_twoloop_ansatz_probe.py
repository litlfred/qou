    pair = [i for i in range(3) if any(
        abs(D[i]["ReV"] - D[j]["ReV"]) < mp.mpf("1e-20") and i != j for j in range(3))]
    i, j = pair[0], pair[1]
    print(f"\n conjugate pair indices {i},{j}  ReV={mp.nstr(D[i]['ReV'],6)}", flush=True)
    print(f" c1(σ1)={mp.nstr(D[i]['c1'],7)}  c1(σ2)={mp.nstr(D[j]['c1'],7)}", flush=True)

    # 2-loop amplitude ansatz on the ray; measure arg-sum phase + mag ratio
    print("\n  t       phi_odd_2loop(arg-sum)   mag_ratio-1", flush=True)
    phase_zero_all = True
    mag_at_sub = None
    for tt in ("0.05", "0.1", "0.2087", "0.3", "0.5"):
        t = mp.mpf(tt)
        tau = 1j * t / (2 * mp.pi)
        aa = [D[k]["amp"] * (1 + D[k]["c1"] * tau) for k in (i, j)]
        bb = [Db[k]["amp"] * (1 + Db[k]["c1"] * (-tau)) for k in (i, j)]
        phi = (mp.arg(aa[0]) + mp.arg(aa[1])) - (mp.arg(bb[0]) + mp.arg(bb[1]))
        magr = (abs(aa[0]) * abs(aa[1])) / (abs(bb[0]) * abs(bb[1])) - 1
        if abs(phi) > mp.mpf("1e-30"):
            phase_zero_all = False
        if tt == "0.2087":
            mag_at_sub = magr
        print(f"  {tt:>7}   {mp.nstr(phi,6):>16}   {mp.nstr(magr,7)}", flush=True)


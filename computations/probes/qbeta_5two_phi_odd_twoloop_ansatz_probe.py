        out = []
        for x, y in saddles(m):
            _, cv = P.complex_volume(x, y)
            d = delta(x, y)
            out.append({"ReV": mp.re(cv), "c1": c1(x, y, d), "amp": 1 / mp.sqrt(1j * d)})
        return out


from __future__ import annotations

import itertools
import json
import sys
import time
from fractions import Fraction
from math import comb

import sympy as sp

P_MOD = (1 << 61) - 1  # Mersenne prime, ample for a one-sided rank bound


# ══════════════════════════════════════════════════════════════════════
# Symmetric group
# ══════════════════════════════════════════════════════════════════════

def perms(n):
    return list(itertools.permutations(range(n)))


def mul(w, u):
    return tuple(w[u[i]] for i in range(len(w)))


def length(w):
    n = len(w)
    return sum(1 for i in range(n) for j in range(i + 1, n) if w[i] > w[j])


def s_gen(n, i):
    p = list(range(n))
    p[i], p[i + 1] = p[i + 1], p[i]
    return tuple(p)


def catalan(n):
    return comb(2 * n, n) // (n + 1)


# ══════════════════════════════════════════════════════════════════════
# Scalar backends. Each supplies one/zero and the ring ops we use.
# ══════════════════════════════════════════════════════════════════════

class QQ:
    name = "Q (exact Fraction)"

    def __init__(self, qv):
        self.q = Fraction(qv)
        self.one, self.zero = Fraction(1), Fraction(0)
        self.h = self.q - 1 / self.q
        self.z = self.q ** 3 / (self.q ** 2 + 1)

    add = staticmethod(lambda a, b: a + b)
    mul = staticmethod(lambda a, b: a * b)
    def inv_q_pow(self, k):
        return (-1 / self.q) ** k


class GFp:
    name = f"GF({P_MOD})"

    def __init__(self, qv):
        num, den = Fraction(qv).numerator, Fraction(qv).denominator
        self.q = num * pow(den, P_MOD - 2, P_MOD) % P_MOD
        self.one, self.zero = 1, 0
        qi = pow(self.q, P_MOD - 2, P_MOD)
        self.h = (self.q - qi) % P_MOD
        self.z = self.q ** 3 % P_MOD * pow((self.q ** 2 + 1) % P_MOD,
                                           P_MOD - 2, P_MOD) % P_MOD
        self._qi = qi

    def inv_q_pow(self, k):
        return pow((-self._qi) % P_MOD, k, P_MOD)


class SymQ:
    name = "Q(q) (symbolic)"

    def __init__(self, _=None):
        self.q = sp.Symbol("q", positive=True)
        self.one, self.zero = sp.Integer(1), sp.Integer(0)
        self.h = self.q - 1 / self.q
        self.z = self.q ** 3 / (self.q ** 2 + 1)

    def inv_q_pow(self, k):
        return (-1 / self.q) ** k


def _norm(F, v):
    return v % P_MOD if isinstance(F, GFp) else v


# ══════════════════════════════════════════════════════════════════════
# H_n(q) in the T_w basis.  Elements are dicts {perm: coeff}.
#   len(w s_i) > len(w)  ->  T_w T_{s_i} = T_{w s_i}
#   otherwise            ->  T_w T_{s_i} = h T_w + T_{w s_i}
# ══════════════════════════════════════════════════════════════════════

def rmul_gen(F, elt, i, n):
    out = {}
    s = s_gen(n, i)
    h, zero = F.h, F.zero
    for w, c in elt.items():
        ws = mul(w, s)
        if length(ws) > length(w):
            out[ws] = _norm(F, out.get(ws, zero) + c)
        else:
            out[w] = _norm(F, out.get(w, zero) + h * c)
            out[ws] = _norm(F, out.get(ws, zero) + c)
    return {w: c for w, c in out.items() if c != zero}


def reduced_word(w, n):
    w = list(w)
    word = []
    changed = True
    while changed:
        changed = False
        for i in range(n - 1):
            if w[i] > w[i + 1]:
                w[i], w[i + 1] = w[i + 1], w[i]
                word.append(i)
                changed = True
                break
    return list(reversed(word))


def t_of_perm(F, w, n):
    elt = {tuple(range(n)): F.one}
    for i in reduced_word(w, n):
        elt = rmul_gen(F, elt, i, n)
    return elt


def hmul(F, a, b, n):
    out = {}
    for wb, cb in b.items():
        cur = dict(a)
        for i in reduced_word(wb, n):
            cur = rmul_gen(F, cur, i, n)
        for w, c in cur.items():
            out[w] = _norm(F, out.get(w, F.zero) + cb * c)
    return {w: c for w, c in out.items() if c != F.zero}


# ══════════════════════════════════════════════════════════════════════
# Ocneanu / Markov trace on the T_w basis, by the coset recursion.
#
#   S_n = union_k S_{n-1} d_k,  d_k = s_{n-2} s_{n-3} ... s_k  (0-indexed),
#   w = u d_k uniquely with len(w) = len(u) + len(d_k).
#     d = e          ->  tr_n(T_w) = tr_{n-1}(T_u)
#     d = s_{n-2} d' ->  tr_n(T_w) = z * tr_{n-1}(T_u T_{d'})   [Markov]
# ══════════════════════════════════════════════════════════════════════

def trace_table(F, n):
    """tr_M(T_w) for every w in S_n, as a dict."""
    tables = {1: {(0,): F.one}}
    for m in range(2, n + 1):
        tb = {}
        prev = tables[m - 1]
        for w in perms(m):
            if w[m - 1] == m - 1:
                tb[w] = prev[w[: m - 1]]
            else:
                k = w.index(m - 1)
                dk = tuple(range(m))
                for i in range(m - 2, k - 1, -1):
                    dk = mul(dk, s_gen(m, i))
                dki = tuple(sorted(range(m), key=lambda t: dk[t]))
                u = mul(w, dki)
                assert u[m - 1] == m - 1 and length(u) + length(dk) == length(w)
                dp = tuple(range(m - 1))
                for i in range(m - 3, k - 1, -1):
                    dp = mul(dp, s_gen(m - 1, i))
                prod = hmul(F, t_of_perm(F, u[: m - 1], m - 1),
                            t_of_perm(F, dp, m - 1), m - 1)
                acc = F.zero
                for v, c in prod.items():
                    acc = _norm(F, acc + c * prev[v])
                tb[w] = _norm(F, F.z * acc)
        tables[m] = tb
    return tables[n]


# ══════════════════════════════════════════════════════════════════════
# Gram matrix G[w][v] = tr_M(T_w T_v), built by a BFS in weak order so
# each entry costs one generator multiplication rather than a full product.
# ══════════════════════════════════════════════════════════════════════

def gram(F, n):
    P = sorted(perms(n), key=length)
    idx = {w: i for i, w in enumerate(P)}
    tr = trace_table(F, n)
    N = len(P)
    G = [[F.zero] * N for _ in range(N)]

    # BFS order: for each v, a (predecessor, generator) with v = pred * s_i
    pred = {tuple(range(n)): None}
    order = [tuple(range(n))]
    seen = {tuple(range(n))}
    qd = [tuple(range(n))]
    while qd:
        v = qd.pop(0)
        for i in range(n - 1):
            vs = mul(v, s_gen(n, i))
            if length(vs) > length(v) and vs not in seen:
                seen.add(vs)
                pred[vs] = (v, i)
                order.append(vs)
                qd.append(vs)

    for w in P:
        cur = {tuple(range(n)): F.one}
        prods = {tuple(range(n)): t_of_perm(F, w, n)}
        for v in order:
            if pred[v] is None:
                continue
            pv, i = pred[v]
            prods[v] = rmul_gen(F, prods[pv], i, n)
        iw = idx[w]
        for v in order:
            acc = F.zero
            for u, c in prods[v].items():
                acc = _norm(F, acc + c * tr[u])
            G[iw][idx[v]] = acc
        del cur
    return G, P, idx


def rank_gfp(M):
    A = [row[:] for row in M]
    rows, cols = len(A), len(A[0])
    r = 0
    for c in range(cols):
        piv = next((i for i in range(r, rows) if A[i][c] % P_MOD), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        inv = pow(A[r][c], P_MOD - 2, P_MOD)
        Ar = [x * inv % P_MOD for x in A[r]]
        A[r] = Ar
        for i in range(rows):
            if i != r and A[i][c]:
                f = A[i][c]
                Ai = A[i]
                A[i] = [(Ai[j] - f * Ar[j]) % P_MOD for j in range(cols)]
        r += 1
        if r == rows:
            break
    return r


def rank_exact(M):
    A = [row[:] for row in M]
    rows, cols = len(A), len(A[0])
    r = 0
    for c in range(cols):
        piv = next((i for i in range(r, rows) if A[i][c] != 0), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        pv = A[r][c]
        for i in range(rows):
            if i != r and A[i][c] != 0:
                f = A[i][c] / pv
                A[i] = [A[i][j] - f * A[r][j] for j in range(cols)]
        r += 1
        if r == rows:
            break
    return r


# ══════════════════════════════════════════════════════════════════════
# The three-strand q-antisymmetriser and the two-sided ideal it generates
# ══════════════════════════════════════════════════════════════════════

def antisymmetriser(F, n, base):
    """E on strands (base, base+1, base+2): SUM_{w in S_3} (-1/q)^len(w) T_w."""
    elt = {}
    for w3 in itertools.permutations(range(3)):
        full = list(range(n))
        for t in range(3):
            full[base + t] = base + w3[t]
        wf = tuple(full)
        coef = F.inv_q_pow(length(wf))
        for u, c in t_of_perm(F, wf, n).items():
            elt[u] = _norm(F, elt.get(u, F.zero) + coef * c)
    return {w: c for w, c in elt.items() if c != F.zero}


def tl_ideal_basis(F, n, idx, N, exact):
    """Spanning set of the two-sided ideal <E>, reduced to a basis."""
    rows, basis = [], []
    rk = 0

    def vec(d):
        v = [F.zero] * N
        for w, c in d.items():
            v[idx[w]] = c
        return v

    frontier = [antisymmetriser(F, n, b) for b in range(n - 2)]
    while frontier:
        nxt = []
        for d in frontier:
            cand = rows + [vec(d)]
            newrk = rank_exact(cand) if exact else rank_gfp(cand)
            if newrk > rk:
                rows, rk = cand, newrk
                basis.append(d)
                for i in range(n - 1):
                    nxt.append(rmul_gen(F, d, i, n))
                    nxt.append(hmul(F, {s_gen(n, i): F.one}, d, n))
        frontier = nxt
    return basis, rk



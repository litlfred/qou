        Gm = sp.Matrix([[sp.cancel(sp.together(x)) for x in row] for row in G])
        det = sp.simplify(Gm.det())
        r = Gm.rank()
        N, ck = len(P), len(P) - r
        pred = N - catalan(n)
        ns = Gm.nullspace()
        qsym = F.q
        radical_is_antisym = False
        if len(ns) == 1:
            v = sp.simplify(ns[0] / ns[0][0])
            radical_is_antisym = all(
                sp.simplify(v[k] - (-1 / qsym) ** length(P[k])) == 0
                for k in range(N))
        say(f"  n={n} dim={N} rank_over_Q(q)={r} corank={ck}"
            f"  n!-Catalan={pred}  det={det}   {time.time()-t0:.1f}s")
        say(f"      null vector equals the q-antisymmetriser (-1/q)^len(w)"
            f" identically in q: {radical_is_antisym}")
        out["runs"].append({"part": "symbolic", "n": n, "dim": N, "rank": r,
                            "corank": ck, "predicted_corank": pred,
                            "det": str(det), "det_identically_zero": det == 0,
                            "null_is_q_antisymmetriser": radical_is_antisym,
                            "match": ck == pred})


# polynomial_q_not_applicable: hyperbolic-geometry numeric probe.
"""one_loop_multicusp_derivation_probe.py — deriving the 1-loop invariant for c >= 2.

Bean `qou-fl4t`. Follows PR #4691 (the quantity in `whitehead_c_sigma_torsion.py`
is not a topological invariant), #4697 (its ambiguity group is the trace-field
units), #4707 (the correct one-cusped construction, promoted to
`computations/one_loop_torsion.py`) and #4708 (the multi-cusp formula is NOT in
Dimofte-Garoufalidis, contrary to what an earlier audit of mine claimed).

WHAT WAS BLOCKING IT, AND WHY THAT WAS WRONG

DG state Definition 1.2 for one cusp and say (Section 1.9) only that "the
generalization to multiple cusps is also quite straightforward, but left out
mainly for simplicity of exposition". PR #4708 concluded correctly that the
formula has to be derived — but gave the wrong reason for it being hard. It
quoted DG's

    "For a one-cusped manifold, every edge begins and ends at the cusp, which
     implies sum_I G_Ii = sum_I G'_Ii = sum_I G''_Ii = 2"

and asserted that this identity "fails for c >= 2", making the extension "not a
matter of adding rows". SECTION A BELOW MEASURES THE IDENTITY DIRECTLY AND IT
HOLDS AT EVERY CUSP NUMBER. It is not a cusp statement at all: each tetrahedron
has six edges in three opposite pairs, one pair per shape type, and each is
glued into exactly one edge class. Cusps never enter. That correction is what
unblocks the derivation.

THE DERIVATION, IN THREE MEASURED FACTS

  A. `sum_I G_Ii = sum_I G'_Ii = sum_I G''_Ii = 2` for every c.
  B. Since `zeta + zeta' + zeta'' = 0`, (A) forces the N specialised edge rows
     to sum to ZERO, and their rank is exactly `N - c`. So the matrix wants
     `N - c` edge rows and `c` peripheral rows — the obvious guess, now with a
     reason.
  C. The non-obvious part: WHICH `N - c` rows. Any independent subset spans the
     right complex subspace, but can generate a proper SUBLATTICE of the edge
     lattice, and the determinant then comes out multiplied by the index. This
     is the whole residual failure — with a subset, `L6a4` and `L7a1` each throw
     a stray factor of exactly 2 in roughly one randomised triangulation in
     thirty. A Hermite-normal-form basis of the lattice generated by all N edge
     rows fixes it.

  The specialised row depends only on the Neumann-Zagier pair
  `(a, b) = (G - G'', G' - G'')`, so the relevant lattice lives in `Z^{2N}`.

WHAT MAKES THIS MORE THAN SELF-CONSISTENCY

Triangulation invariance (section C) is necessary but weak — it cannot see a
wrong overall constant, and it compares the construction only against itself.
Section D tests the CHANGE-OF-CURVE LAW instead: swapping the meridian row of
cusp k alone for that cusp's longitude row must multiply tau by the conjugate of
the CUSP SHAPE of cusp k, which SnapPy computes from the cusp cross-section
geometry. That is an outside quantity, and the test is per-cusp, so it probes
exactly the structure that is new at c >= 2. It holds to ~1e-59 on 13
manifolds.

WHAT THIS DOES NOT SETTLE

The `1/2` is DG's, pinned at c = 1. Neither invariance nor the change-of-curve
law can see a constant that depends only on c — and that is precisely the shape
of the per-cusp factor `2^{(c-1)/2}` the `c_sigma` arc wanted (bean qou-pn5j).
So this probe does NOT revive that factor and must not be cited as pinning it.

Audit-only. No float64 enters the witness.
"""
from __future__ import annotations

import json

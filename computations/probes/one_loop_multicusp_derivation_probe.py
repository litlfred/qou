sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "substrate"))
from _precision import set_compute_dps, fmt  # noqa: E402
from one_loop_torsion import (  # noqa: E402
    _independent, _log_rows, _shapes, _specialise, cusp_shape_residuals,
    flattening, nz_pair, one_loop, row_hnf,
)

set_compute_dps()

N_TRIALS = 25
GEOMETRIC = "all tetrahedra positively oriented"
ONE_CUSP = ["4_1", "5_2", "6_2", "7_4"]
MULTI = ["L5a1", "m125", "L6a2", "L6a1", "L6a4", "s776", "L7a1", "L8a1", "L10n1"]
TARGETS = ONE_CUSP + MULTI


def _parts(M):
    N, c = M.num_tetrahedra(), M.num_cusps()
    R = _log_rows(M)
    return N, c, R, len(R) - 2 * c


def sum_identity(M):
    """Section A: sum over edges of G, G', G'' — DG say 2, and say it needs c=1."""
    N, c, R, ne = _parts(M)
    sums = []
    for off in (0, 1, 2):
        sums.append({sum(R[I][3 * j + off] for I in range(ne)) for j in range(N)})
    return sums, all(s == {2} for s in sums)


def rank_facts(M):
    """Section B: the specialised edge rows sum to zero and have rank N - c."""
    N, c, R, ne = _parts(M)
    z = _shapes(M)
    zeta = [1 / x for x in z]
    zetap = [1 / (1 - x) for x in z]
    spec = [_specialise(nz_pair(R[i], N), N, zeta, zetap) for i in range(ne)]
    colsum = max(abs(sum(spec[I][j] for I in range(ne))) for j in range(N))
    rank = len(_independent(spec, ne))
    return colsum, rank


def tau_subset(M):
    """Section C control: the same construction with a greedy SUBSET of edge rows."""
    N, c, R, ne = _parts(M)
    z = _shapes(M)
    zeta = [1 / x for x in z]
    zetap = [1 / (1 - x) for x in z]
    zetapp = [1 / (x * (x - 1)) for x in z]
    spec = [_specialise(nz_pair(R[i], N), N, zeta, zetap) for i in range(ne)]
    keep = _independent(spec, N - c)
    if len(keep) < N - c:
        raise ValueError("rank short")
    periph = [_specialise(nz_pair(R[ne + 2 * i], N), N, zeta, zetap) for i in range(c)]
    A = mp.matrix(N, N)
    rows = [spec[i] for i in keep] + periph
    for i in range(N):
        for j in range(N):
            A[i, j] = rows[i][j]
    fv, fpv, fppv = flattening(M)
    den = mp.mpc(1)
    for j in range(N):
        den *= zeta[j] ** fv[j] * zetap[j] ** fpv[j] * zetapp[j] ** fppv[j]
    return mp.det(A) / (2 * den)


def main() -> int:
    import snappy

    results = {}
    print(f"1-loop multi-cusp derivation probe — dps={mp.mp.dps}, "
          f"{N_TRIALS} randomised triangulations per manifold\n")

    print("A. sum_I G_Ii = sum_I G'_Ii = sum_I G''_Ii = 2 — DG call this one-cusped")
    all_hold = True
    for name in TARGETS:
        M = snappy.Manifold(name)
        sums, holds = sum_identity(M)
        all_hold &= holds
        print(f"   {name:8} c={M.num_cusps()} N={M.num_tetrahedra():2d}  "
              f"G,G',G'' sums = {sums[0]},{sums[1]},{sums[2]}  "
              f"{'HOLDS' if holds else 'FAILS'}")
        results.setdefault(name, {})["sum_identity_holds"] = holds
    print(f"   => holds at every cusp number: {all_hold}."
          f" The c>=2 blocker asserted in PR #4708 is withdrawn.\n")

    print("B. specialised edge rows: column sums vanish, rank = N - c")
    for name in TARGETS:
        M = snappy.Manifold(name)
        N, c = M.num_tetrahedra(), M.num_cusps()
        colsum, rank = rank_facts(M)
        ok = rank == N - c
        print(f"   {name:8} max|column sum| = {mp.nstr(colsum, 4):<12} "
              f"rank = {rank} (N-c = {N - c})  {'OK' if ok else 'MISMATCH'}")
        results[name].update({"cusps": c, "tetrahedra": N,
                              "edge_rank": rank, "edge_rank_is_N_minus_c": ok,
                              "edge_column_sum": fmt(colsum)})
    print()

    print("C. triangulation invariance: HNF lattice basis vs greedy edge subset")
    for name in TARGETS:
        M0 = snappy.Manifold(name)
        hnf = {mp.nstr(abs(one_loop(M0)), 25)}
        sub = {mp.nstr(abs(tau_subset(M0)), 25)}
        n = 0
        for _ in range(N_TRIALS):
            M = snappy.Manifold(name)
            M.randomize()
            if str(M.solution_type()) != GEOMETRIC:
                continue
            if not M.is_isometric_to(snappy.Manifold(name)):
                continue
            try:
                h = abs(one_loop(M))
                s = abs(tau_subset(M))
            except Exception:
                continue
            hnf.add(mp.nstr(h, 25))
            sub.add(mp.nstr(s, 25))
            n += 1
        base = mp.mpf(min(hnf, key=lambda t: mp.mpf(t)))
        ratios = sorted(mp.nstr(mp.mpf(v) / base, 8) for v in sub)
        print(f"   {name:8} trials={n:2d}  HNF basis: {len(hnf)} value(s)"
              f"   subset: {len(sub)} value(s)"
              f"{'' if len(sub) == 1 else '  ratios ' + ','.join(ratios)}")
        results[name].update({
            "trials": n,
            "hnf_basis_distinct_values": len(hnf),
            "greedy_subset_distinct_values": len(sub),
            "tau_abs": fmt(base),
        })
    print("   NOTE: `trials` counts randomisations that stayed geometric AND")
    print("   isometric to the original; a 0 there means the row is untested.\n")

    print("D. change-of-curve law, per cusp, vs SnapPy's cusp shapes")
    worst = mp.mpf(0)
    for name in TARGETS:
        M = snappy.Manifold(name)
        devs = cusp_shape_residuals(M)
        d = max(devs)
        worst = max(worst, d)
        print(f"   {name:8} c={M.num_cusps()}  max rel dev = {mp.nstr(d, 4)}"
              f"   {'OK' if d < mp.mpf('1e-25') else '*** MISMATCH ***'}")
        results[name]["cusp_shape_max_rel_dev"] = fmt(d)
    print(f"   => worst over all {len(TARGETS)} manifolds: {mp.nstr(worst, 6)}\n")

    print("-" * 72)
    print("The multi-cusp construction is: an HNF BASIS of the edge lattice in")
    print("Neumann-Zagier (a,b) coordinates (rank N-c), plus one peripheral row")
    print("per cusp, over the DG flattening monomial, times 1/2.")
    print()
    print("NOT settled: the overall constant at c >= 2. Invariance and the")
    print("change-of-curve law are both blind to a factor depending only on c —")
    print("which is exactly the shape of the 2^{(c-1)/2} per-cusp factor. This")
    print("probe does not revive it. (bean qou-pn5j was later closed as DERIVATION")
    print("on the JONES side instead -- see the per-cusp dissolution probe and")
    print("docs/audits/2026-08-08-c-sigma-derivation-status.md. Nothing here changes.)")

    wit = {
        "description": (
            "Derivation and validation of the Dimofte-Garoufalidis 1-loop "
            "invariant for manifolds with c >= 2 cusps, which DG state only for "
            "one cusp. Withdraws the c>=2 blocker asserted in PR #4708 (the "
            "sum-to-2 identity holds at every cusp number), identifies the real "
            "obstruction as a lattice-index effect in the choice of edge rows, "
            "and validates per cusp against SnapPy's cusp shapes."
        ),
        "computation": "one_loop_multicusp_derivation_probe",
        "audit_only": True,
        "trials_per_manifold": N_TRIALS,
        "sum_identity_holds_at_every_cusp_number": all_hold,
        "worst_cusp_shape_rel_dev": fmt(worst),
        "results": results,
        "normalization_not_settled": (
            "the 1/2 is inherited from c=1; invariance and the change-of-curve "
            "law cannot see a constant depending only on c"
        ),
        "bears_on": ["bean qou-fl4t", "bean qou-pn5j", "PR #4691", "PR #4697",
                     "PR #4707", "PR #4708"],
        "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    out = (Path(__file__).resolve().parent.parent
           / "one-loop-multicusp-derivation.witness.json")

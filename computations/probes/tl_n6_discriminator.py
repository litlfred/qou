# NEW: the O(n!^2) row recursion for the same Gram matrix.
#
#   psi_w[v] := tr(T_w T_v)  is the w-th ROW of G.
#   psi_e[v] = tr(T_v) = tau[v].
#   For l(w s_i) > l(w),  T_{w s_i} = T_w T_{s_i}, so
#       psi_{w s_i}[v] = tr(T_w T_{s_i} T_v) = sum_u (L_i)_{u,v} tr(T_w T_u)
#                      = (L_i^T psi_w)[v],
#   where L_i is left multiplication by T_{s_i}:
#       T_{s_i} T_v = T_{s_i v}            if l(s_i v) > l(v)
#                   = h T_v + T_{s_i v}    otherwise.
#   Hence  (L_i^T psi)[v] = psi[s_i v] + (h psi[v] if l(s_i v) < l(v) else 0).
#
# One O(n!) application per row, n! rows: the whole matrix in O(n!^2).
# ══════════════════════════════════════════════════════════════════════

def _tables(n):
    """Index maps for left/right multiplication by each generator."""
    Pl = sorted(perms(n), key=length)
    idx = {w: i for i, w in enumerate(Pl)}
    N = len(Pl)
    simg, sdown, rimg, rdown = [], [], [], []
    for i in range(n - 1):
        s = s_gen(n, i)
        simg.append(np.array([idx[mul(s, v)] for v in Pl]))
        sdown.append(np.array([length(mul(s, v)) < length(v) for v in Pl]))
        rimg.append(np.array([idx[mul(v, s)] for v in Pl]))
        rdown.append(np.array([length(mul(v, s)) < length(v) for v in Pl]))
    return Pl, idx, N, simg, sdown, rimg, rdown


def fast_gram(F, n):
    """G[w][v] = tr_M(T_w T_v) via the row recursion. Backend-agnostic."""
    Pl, idx, N, simg, sdown, _, _ = _tables(n)
    tau = trace_table(F, n)
    h = F.h
    simg = [g.tolist() for g in simg]
    sdown = [m.tolist() for m in sdown]

    def applyLT(psi, i):
        g, m = simg[i], sdown[i]
        return [_norm(F, psi[g[j]] + (h * psi[j] if m[j] else F.zero))
                for j in range(N)]

    e = tuple(range(n))
    rows = {e: [tau[v] for v in Pl]}
    qd = [e]
    while qd:
        w = qd.pop(0)
        for i in range(n - 1):
            ws = mul(w, s_gen(n, i))
            if length(ws) > length(w) and ws not in rows:
                rows[ws] = applyLT(rows[w], i)
                qd.append(ws)
    return [rows[w] for w in Pl], Pl, idx


def gram_mod_np(qv, n):
    """The same Gram matrix as an exact int64 array over GF(P_MOD)."""
    F = GFp(qv)
    Pl, idx, N, simg, sdown, rimg, rdown = _tables(n)
    tau = trace_table(F, n)
    h = F.h
    G = np.zeros((N, N), dtype=np.int64)
    e = tuple(range(n))
    assert Pl[0] == e
    G[0] = np.array([tau[v] for v in Pl], dtype=np.int64)
    seen = {e}
    qd = [e]
    while qd:
        w = qd.pop(0)
        for i in range(n - 1):
            ws = mul(w, s_gen(n, i))
            if length(ws) > length(w) and ws not in seen:
                psi = G[idx[w]]
                out = psi[simg[i]].copy()
                m = sdown[i]
                out[m] = (out[m] + h * psi[m]) % P_MOD
                G[idx[ws]] = out
                seen.add(ws)
                qd.append(ws)
    return G, Pl, idx, F, (simg, sdown, rimg, rdown)


def rank_mod(M):
    """Exact rank over GF(P_MOD). int64 throughout; no float dtype."""
    A = (M % P_MOD).astype(np.int64).copy()
    rows, cols = A.shape
    r = 0
    for c in range(cols):
        nz = np.nonzero(A[r:, c])[0]
        if nz.size == 0:
            continue
        p0 = r + int(nz[0])
        if p0 != r:
            A[[r, p0]] = A[[p0, r]]
        A[r] = A[r] * pow(int(A[r, c]), P_MOD - 2, P_MOD) % P_MOD
        col = A[:, c].copy()
        col[r] = 0
        nzr = np.nonzero(col)[0]
        if nzr.size:
            A[nzr] = (A[nzr] - col[nzr, None] * A[r][None, :]) % P_MOD
        r += 1
        if r == rows:
            break
    return r


class Echelon:
    """Incremental echelon basis over GF(P_MOD); span dimension only."""

    def __init__(self):
        self.rows, self.piv = [], []

    def add(self, x):
        x = x % P_MOD
        for r, c in zip(self.rows, self.piv):
            xc = x[c]
            if xc:
                x = (x - xc * r) % P_MOD
        nz = np.nonzero(x)[0]
        if nz.size == 0:
            return False
        c = int(nz[0])
        self.rows.append(x * pow(int(x[c]), P_MOD - 2, P_MOD) % P_MOD)
        self.piv.append(c)
        return True

    def __len__(self):
        return len(self.rows)


def two_sided_ideal_dim(qv, n, tabs=None, F=None, want_right_only=False):
    """dim over GF(p) of the two-sided ideal <E_b : b> = span{T_a E_b T_c}."""
    if tabs is None:
        _, idx, N, simg, sdown, rimg, rdown = _tables(n)
        F = GFp(qv)
    else:
        Pl, idx, N, simg, sdown, rimg, rdown = tabs
    h = F.h

    def Lmul(x, i):
        out = np.zeros(N, dtype=np.int64)
        out[simg[i]] = x
        m = sdown[i]
        out[m] = (out[m] + h * x[m]) % P_MOD
        return out

    def Rmul(x, i):
        out = np.zeros(N, dtype=np.int64)
        out[rimg[i]] = x
        m = rdown[i]
        out[m] = (out[m] + h * x[m]) % P_MOD
        return out

    ech = Echelon()
    queue = []
    for b in range(n - 2):
        E = antisymmetriser(F, n, b)
        v0 = np.zeros(N, dtype=np.int64)
        for w, c in E.items():
            v0[idx[w]] = c % P_MOD
        queue.append(v0)
    while queue:
        x = queue.pop()
        if ech.add(x):
            xx = ech.rows[-1]
            for i in range(n - 1):
                queue.append(Rmul(xx, i))
                if not want_right_only:
                    queue.append(Lmul(xx, i))
    return len(ech)


def hook_dim(lam):
    """dim of the Specht/Wedderburn block V_lambda, by the hook-length formula."""
    n = sum(lam)
    conj = [sum(1 for r in lam if r > j) for j in range(lam[0])]
    prod = 1
    for i, r in enumerate(lam):
        for j in range(r):
            prod *= (r - j) + (conj[j] - i) - 1
    return factorial(n) // prod


def partitions(n, cap=None):
    cap = n if cap is None else cap
    if n == 0:
        yield ()
        return
    for first in range(min(n, cap), 0, -1):
        for rest in partitions(n - first, first):
            yield (first,) + rest



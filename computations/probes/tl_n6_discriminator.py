def perms(n):
    return list(itertools.permutations(range(n)))


def mul(w, u):
    return tuple(w[u[i]] for i in range(len(w)))


def length(w):
    n = len(w)
    return sum(1 for i in range(n) for j in range(i + 1, n) if w[i] > w[j])


def s_gen(n, i):
    p = list(range(n))
    p[i], p[i + 1] = p[i + 1], p[i]
    return tuple(p)


def catalan(n):
    return comb(2 * n, n) // (n + 1)


class QQ:
    name = "Q (exact Fraction)"

    def __init__(self, qv):
        self.q = Fraction(qv)
        self.one, self.zero = Fraction(1), Fraction(0)
        self.h = self.q - 1 / self.q
        self.z = self.q ** 3 / (self.q ** 2 + 1)

    def inv_q_pow(self, k):
        return (-1 / self.q) ** k


class GFp:
    name = f"GF({P_MOD})"

    def __init__(self, qv):
        num, den = Fraction(qv).numerator, Fraction(qv).denominator
        self.q = num * pow(den, P_MOD - 2, P_MOD) % P_MOD
        self.one, self.zero = 1, 0
        qi = pow(self.q, P_MOD - 2, P_MOD)
        self.h = (self.q - qi) % P_MOD
        self.z = self.q ** 3 % P_MOD * pow((self.q ** 2 + 1) % P_MOD,
                                           P_MOD - 2, P_MOD) % P_MOD
        self._qi = qi

    def inv_q_pow(self, k):
        return pow((-self._qi) % P_MOD, k, P_MOD)


class SymQ:
    name = "Q(q) (symbolic)"

    def __init__(self, _=None):
        self.q = sp.Symbol("q", positive=True)
        self.one, self.zero = sp.Integer(1), sp.Integer(0)
        self.h = self.q - 1 / self.q
        self.z = self.q ** 3 / (self.q ** 2 + 1)

    def inv_q_pow(self, k):
        return (-1 / self.q) ** k


def _norm(F, v):
    return v % P_MOD if isinstance(F, GFp) else v


def rmul_gen(F, elt, i, n):
    out = {}
    s = s_gen(n, i)
    h, zero = F.h, F.zero
    for w, c in elt.items():
        ws = mul(w, s)
        if length(ws) > length(w):
            out[ws] = _norm(F, out.get(ws, zero) + c)
        else:
            out[w] = _norm(F, out.get(w, zero) + h * c)
            out[ws] = _norm(F, out.get(ws, zero) + c)
    return {w: c for w, c in out.items() if c != zero}


def reduced_word(w, n):
    w = list(w)
    word = []
    changed = True
    while changed:
        changed = False
        for i in range(n - 1):
            if w[i] > w[i + 1]:
                w[i], w[i + 1] = w[i + 1], w[i]
                word.append(i)
                changed = True
                break
    return list(reversed(word))


def t_of_perm(F, w, n):
    elt = {tuple(range(n)): F.one}
    for i in reduced_word(w, n):
        elt = rmul_gen(F, elt, i, n)
    return elt


def hmul(F, a, b, n):
    out = {}
    for wb, cb in b.items():
        cur = dict(a)
        for i in reduced_word(wb, n):
            cur = rmul_gen(F, cur, i, n)
        for w, c in cur.items():
            out[w] = _norm(F, out.get(w, F.zero) + cb * c)
    return {w: c for w, c in out.items() if c != F.zero}


def trace_table(F, n):
    """tr_M(T_w) for every w in S_n, as a dict."""
    tables = {1: {(0,): F.one}}
    for m in range(2, n + 1):
        tb = {}
        prev = tables[m - 1]
        for w in perms(m):
            if w[m - 1] == m - 1:
                tb[w] = prev[w[: m - 1]]
            else:
                k = w.index(m - 1)
                dk = tuple(range(m))
                for i in range(m - 2, k - 1, -1):
                    dk = mul(dk, s_gen(m, i))
                dki = tuple(sorted(range(m), key=lambda t: dk[t]))
                u = mul(w, dki)
                assert u[m - 1] == m - 1 and length(u) + length(dk) == length(w)
                dp = tuple(range(m - 1))
                for i in range(m - 3, k - 1, -1):
                    dp = mul(dp, s_gen(m - 1, i))
                prod = hmul(F, t_of_perm(F, u[: m - 1], m - 1),
                            t_of_perm(F, dp, m - 1), m - 1)
                acc = F.zero
                for v, c in prod.items():
                    acc = _norm(F, acc + c * prev[v])
                tb[w] = _norm(F, F.z * acc)
        tables[m] = tb
    return tables[n]


def slow_gram(F, n):
    """S2's Gram builder: G[w][v] = tr_M(T_w T_v). The reference implementation.

    O(n!^2 * support) -- correct, and the thing `fast_gram` is checked against,
    but it does not reach n = 6.
    """
    Pl = sorted(perms(n), key=length)
    idx = {w: i for i, w in enumerate(Pl)}
    tr = trace_table(F, n)
    N = len(Pl)
    G = [[F.zero] * N for _ in range(N)]
    pred = {tuple(range(n)): None}
    order = [tuple(range(n))]
    seen = {tuple(range(n))}
    qd = [tuple(range(n))]
    while qd:
        v = qd.pop(0)
        for i in range(n - 1):
            vs = mul(v, s_gen(n, i))
            if length(vs) > length(v) and vs not in seen:
                seen.add(vs)
                pred[vs] = (v, i)
                order.append(vs)
                qd.append(vs)
    for w in Pl:
        prods = {tuple(range(n)): t_of_perm(F, w, n)}
        for v in order:
            if pred[v] is None:
                continue
            pv, i = pred[v]
            prods[v] = rmul_gen(F, prods[pv], i, n)
        iw = idx[w]
        for v in order:
            acc = F.zero
            for u, c in prods[v].items():
                acc = _norm(F, acc + c * tr[u])
            G[iw][idx[v]] = acc
    return G, Pl, idx


def antisymmetriser(F, n, base):
    """E on strands (base, base+1, base+2): SUM_{w in S_3} (-1/q)^len(w) T_w."""
    elt = {}
    for w3 in itertools.permutations(range(3)):
        full = list(range(n))
        for t in range(3):
            full[base + t] = base + w3[t]
        wf = tuple(full)
        coef = F.inv_q_pow(length(wf))
        for u, c in t_of_perm(F, wf, n).items():
            elt[u] = _norm(F, elt.get(u, F.zero) + coef * c)
    return {w: c for w, c in elt.items() if c != F.zero}


def partB_pin(out, ns=(3, 4, 5, 6)):
    say()
    say("=" * 78)
    say("PART B2 - the two bounds, and where they meet")
    say("=" * 78)
    for n in ns:
        N = factorial(n)
        cat = catalan(n)
        pred = N - cat
        t0 = time.time()
        qv = Fraction(11, 10)

        # --- exact over Q: the generators are in the radical, and G is symmetric
        Fq = QQ(qv)
        Gq, Pl, idx = fast_gram(Fq, n)
        gens_ok = True
        for b in range(n - 2):
            E = antisymmetriser(Fq, n, b)
            for v in range(N):
                if sum(c * Gq[idx[w]][v] for w, c in E.items()) != 0:
                    gens_ok = False
                    break
            if not gens_ok:
                break
        sym = all(Gq[i][j] == Gq[j][i] for i in range(N) for j in range(N))
        t1 = time.time()

        # --- modular: the ideal dimension, and the rank
        G, Pl2, idx2, F, tabs = gram_mod_np(qv, n)
        tabs_full = (Pl2, idx2, N) + tabs
        d_two = two_sided_ideal_dim(qv, n, tabs=tabs_full, F=F)
        d_right = two_sided_ideal_dim(qv, n, tabs=tabs_full, F=F,
                                      want_right_only=True)
        rp = rank_mod(G)
        t2 = time.time()

        say(f"  n={n} N={N:3d}")
        say(f"      EXACT over Q: tr(E_b T_v) = 0 for all v, all b : {gens_ok}")
        say(f"      EXACT over Q: G symmetric (=> tr cyclic => radical is a")
        say(f"                    TWO-SIDED ideal)                  : {sym}")
        say(f"      dim_p  right ideal  sum_b E_b H                  = {d_right:3d}"
            f"   (too small -- the two-sided one is the radical)")
        say(f"      dim_p  two-sided ideal <E_b>  = ker(H_{n} ->> TL_{n})  = {d_two:3d}"
            f"   => corank_Q >= {d_two}")
        say(f"      rank_p G                                         = {rp:3d}"
            f"   => corank_Q <= {N - rp}")
        pinned = gens_ok and sym and (d_two == N - rp)
        say(f"      => corank_Q = {N - rp} EXACTLY: {pinned}"
            f"    n!-Catalan({n}) = {pred}"
            f"  [{'MATCH' if pinned and N-rp == pred else 'MISMATCH'}]")
        say(f"      exact pass {t1-t0:.1f}s / modular pass {t2-t1:.1f}s")
        out["runs"].append({"part": "B2_pin", "n": n, "dim": N,
                            "generators_in_radical_exact": gens_ok,
                            "gram_symmetric_exact": sym,
                            "right_ideal_dim_p": d_right,
                            "two_sided_ideal_dim_p": d_two,
                            "rank_p": rp, "corank": N - rp,
                            "n_fact_minus_catalan": pred,
                            "pinned": pinned,
                            "match": pinned and N - rp == pred})


def partB_everyq(out, n=6):
    """Pin the corank at EVERY q sample, not just one, and at a second prime.

    Each bound is one-sided and rigorous on its own, so a single prime already
    suffices; the second prime is a guard against a coding error in the
    elimination, not a rigour requirement.
    """
    global P_MOD
    say()
    say("=" * 78)
    say(f"PART B3 - n = {n}: pin the corank at EVERY q, and at a second prime")
    say("=" * 78)
    N = factorial(n)
    pred = N - catalan(n)
    for prime, tag in ((P_MOD, "2^31-1"), ((1 << 31) - 99, "2^31-99")):
        P_MOD = prime
        rows = []
        t0 = time.time()
        for qv in QS:
            G, Pl, idx, F, tabs = gram_mod_np(qv, n)
            d = two_sided_ideal_dim(qv, n, tabs=(Pl, idx, N) + tabs, F=F)
            rp = rank_mod(G)
            rows.append((str(qv), d, rp, N - rp, d == N - rp == pred))
        allok = all(r[4] for r in rows)
        say(f"  p = {tag} ({prime}, prime={sp.isprime(prime)})   {time.time()-t0:.1f}s")
        for qv, d, rp, ck, ok in rows:
            say(f"      q={qv:>7s}  dim<E>={d:3d}  rank={rp:3d}  "
                f"=> corank={ck:3d}  [{'MATCH' if ok else 'MISMATCH'}]")
        say(f"      corank = {pred} at all {len(QS)} samples: {allok}")
        out["runs"].append({"part": "B3_every_q", "n": n, "prime": prime,
                            "per_sample": [{"q": a, "ideal_dim": b, "rank": c,
                                            "corank": d_, "match": e}
                                           for a, b, c, d_, e in rows],
                            "all_match": allok,
                            "n_fact_minus_catalan": pred})
    P_MOD = (1 << 31) - 1



def partB_blocktable(out, ns=(3, 4, 5, 6)):
    say()
    say("=" * 78)
    say("PART B0 - the block arithmetic the TL hypothesis has to satisfy")
    say("=" * 78)
    say("  If the radical is exactly the sum of blocks with >= 3 rows, then")
    say("  corank = SUM (dim V_lambda)^2 over those lambda. Independent of any")
    say("  Gram computation -- this is just the hook-length formula.")
    say("")
    for n in ns:
        dead = [(l, hook_dim(l)) for l in partitions(n) if len(l) >= 3]
        alive = [(l, hook_dim(l)) for l in partitions(n) if len(l) <= 2]
        sd = sum(d * d for _, d in dead)
        sa = sum(d * d for _, d in alive)
        say(f"  n={n}: <=2 rows {[(list(l), d) for l, d in alive]}")
        say(f"        sum dim^2 = {sa} = Catalan({n}) = {catalan(n)}"
            f"  [{'ok' if sa == catalan(n) else 'MISMATCH'}]")
        say(f"        >=3 rows sum dim^2 = {sd} = {n}!-Catalan({n})"
            f" = {factorial(n)-catalan(n)}"
            f"  [{'ok' if sd == factorial(n)-catalan(n) else 'MISMATCH'}]")
        out["runs"].append({"part": "B0_block_arithmetic", "n": n,
                            "sum_dim2_le2rows": sa, "catalan": catalan(n),
                            "sum_dim2_ge3rows": sd,
                            "n_fact_minus_catalan": factorial(n) - catalan(n)})



import _path_bridge as _bridge  # noqa: E402, F401
del _sys, _Path, _bridge

import sys
from q_parameter import Q_50_DIGIT_STR
from pathlib import Path

import sympy as sp

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))

from witness_base import WitnessBuilder  # noqa: E402


def main() -> int:
    # Symbolic q
    q = sp.Symbol("q", positive=True)
    qi = 1 / q

    # σ as an abstract algebra element satisfying σ² = (q − q⁻¹)·σ + 1.
    # Work in the basis {1, σ} of H_2(q): an element a·1 + b·σ is
    # represented as the pair (a, b).  Multiplication:
    #   (a₁ + b₁σ)(a₂ + b₂σ) = a₁a₂ + (a₁b₂ + b₁a₂)·σ + b₁b₂·σ²
    #                        = (a₁a₂ + b₁b₂)·1
    #                        + (a₁b₂ + a₂b₁ + (q − q⁻¹)·b₁b₂)·σ
    h = q - qi  # the Markov h

    def mul(x, y):
        a1, b1 = x
        a2, b2 = y
        a = a1 * a2 + b1 * b2
        b = a1 * b2 + a2 * b1 + h * b1 * b2
        return (sp.simplify(a), sp.simplify(b))

    def add(x, y):
        return (sp.simplify(x[0] + y[0]), sp.simplify(x[1] + y[1]))

    def scale(s, x):
        return (sp.simplify(s * x[0]), sp.simplify(s * x[1]))

    # Idempotents in the (1, σ) basis
    denom = q + qi
    # e_+ = (σ + q⁻¹) / (q + q⁻¹)
    e_plus = (sp.simplify(qi / denom), sp.simplify(1 / denom))
    # e_- = (q − σ) / (q + q⁻¹)
    e_minus = (sp.simplify(q / denom), sp.simplify(-1 / denom))
    one = (sp.Integer(1), sp.Integer(0))

    # Verify completeness, orthogonality, idempotency
    sum_e = add(e_plus, e_minus)
    completeness_a = sp.simplify(sum_e[0] - 1)
    completeness_b = sp.simplify(sum_e[1] - 0)
    orth = mul(e_plus, e_minus)
    orth_a = sp.simplify(orth[0])
    orth_b = sp.simplify(orth[1])
    e_plus_sq = mul(e_plus, e_plus)
    e_minus_sq = mul(e_minus, e_minus)
    idem_plus_a = sp.simplify(e_plus_sq[0] - e_plus[0])
    idem_plus_b = sp.simplify(e_plus_sq[1] - e_plus[1])
    idem_minus_a = sp.simplify(e_minus_sq[0] - e_minus[0])
    idem_minus_b = sp.simplify(e_minus_sq[1] - e_minus[1])

    # Markov trace: tr_M(1) = 1, tr_M(σ) = z = 1 / (q^{1/2} + q^{-1/2})
    z = 1 / (sp.sqrt(q) + 1 / sp.sqrt(q))

    def tr_M(x):
        return sp.simplify(x[0] + x[1] * z)

    tr_e_plus = tr_M(e_plus)
    tr_e_minus = tr_M(e_minus)
    tr_total = sp.simplify(tr_e_plus + tr_e_minus)  # should = tr(1) = 1

    # Numerical evaluation at the substrate q_0 ≈ 1.110
    q_0 = sp.Float(Q_50_DIGIT_STR, 50)
    tr_e_plus_num = float(sp.N(tr_e_plus.subs(q, q_0), 30))
    tr_e_minus_num = float(sp.N(tr_e_minus.subs(q, q_0), 30))
    tr_total_num = float(sp.N(tr_total.subs(q, q_0), 30))

    b = (
        WitnessBuilder("gauge-coupling-uniqueness-probe", engine="sympy")
        .set_description(
            "I1 probe for cor:gauge-coupling-uniqueness.  Verifies "
            "the H_2(q) idempotent decomposition that underpins the "
            "corollary: σ² = (q − q⁻¹)σ + 1 admits exactly two "
            "central idempotents e_± projecting onto V_± with "
            "V_- ≅ 𝟏 the unique singlet.  Confirms completeness, "
            "orthogonality, idempotency symbolically, and that "
            "tr_M(e_-) ≠ 0 numerically at q_0 — so the singlet "
            "coupling is non-degenerate, and uniqueness up to "
            "global scaling λ ∈ R is structural."
        )
        .set_content_block("cor:gauge-coupling-uniqueness")
        .add_parameter("q_0_50dps", str(q_0))
        .add_parameter("e_plus_symbolic", f"({e_plus[0]}) + ({e_plus[1]})·σ")
        .add_parameter("e_minus_symbolic", f"({e_minus[0]}) + ({e_minus[1]})·σ")
        .add_parameter("tr_M_e_plus_symbolic", str(tr_e_plus))
        .add_parameter("tr_M_e_minus_symbolic", str(tr_e_minus))
        .add_parameter("tr_M_e_plus_at_q0", tr_e_plus_num)
        .add_parameter("tr_M_e_minus_at_q0", tr_e_minus_num)
        .add_data("symbolic_checks", {
            "completeness_residue_a": str(completeness_a),
            "completeness_residue_b": str(completeness_b),
            "orthogonality_residue_a": str(orth_a),
            "orthogonality_residue_b": str(orth_b),
            "idempotency_plus_residue_a": str(idem_plus_a),
            "idempotency_plus_residue_b": str(idem_plus_b),
            "idempotency_minus_residue_a": str(idem_minus_a),
            "idempotency_minus_residue_b": str(idem_minus_b),
        })
        .add_assertion(
            name="completeness_e_plus_plus_e_minus_eq_1",
            computed=float(sp.N(sp.Abs(completeness_a) + sp.Abs(completeness_b))),
            expected=0.0, tolerance=1e-30,
            unit="|residue of (e_+ + e_-) − 1|",
            source="Idempotent completeness in H_2(q).",
        )
        .add_assertion(
            name="orthogonality_e_plus_e_minus_eq_0",
            computed=float(sp.N(sp.Abs(orth_a) + sp.Abs(orth_b))),
            expected=0.0, tolerance=1e-30,
            unit="|residue of e_+ · e_-|",
            source="Central-idempotent orthogonality.",
        )
        .add_assertion(
            name="idempotency_both_residues_zero",
            computed=float(sp.N(
                sp.Abs(idem_plus_a) + sp.Abs(idem_plus_b) +
                sp.Abs(idem_minus_a) + sp.Abs(idem_minus_b)
            )),
            expected=0.0, tolerance=1e-30,
            unit="|sum of (e_±² − e_±) residues|",
            source="e_+² = e_+ and e_-² = e_-.",
        )
        .add_assertion(
            name="tr_M_e_minus_nonzero_at_q_0",
            computed=1.0 if abs(tr_e_minus_num) > 1e-6 else 0.0,
            expected=1.0, tolerance=0.0,
            unit="boolean (1 = singlet-coupling is non-degenerate)",
            source=(
                "tr_M(e_-) is the scalar multiplier in the "
                "corollary's uniqueness statement; if it vanished, "
                "the only braid-invariant scalar coupling would "
                "be zero."
            ),
        )
    )
    out = b.save()
    print(f"\nWitness: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

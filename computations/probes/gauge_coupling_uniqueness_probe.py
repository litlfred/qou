#!/usr/bin/env python3
"""Probe: gauge-coupling-uniqueness (cor:gauge-coupling-uniqueness).

The corollary says: any R-linear, braid-invariant scalar coupling
A ⊗ A → 𝟏 is a multiple of `tr_τ(e_-) · e_-`, where e_- is the
projector onto the unique singlet summand V_- ≅ 𝟏 of A ⊗ A.

Numerical witness (H_2(q) idempotent decomposition at q_0):

The 2-strand Hecke algebra is generated by σ = σ_1 subject to
`σ² = (q − q⁻¹)·σ + 1`.  The two central idempotents are:

    e_+ = (σ + q⁻¹) / (q + q⁻¹)      (symmetric channel V_+)
    e_- = (q   − σ) / (q + q⁻¹)      (antisymmetric channel V_-)

We verify:

  1. e_+ + e_- = 1                    (completeness)
  2. e_+ · e_- = 0                    (orthogonality)
  3. e_+² = e_+ and e_-² = e_-        (idempotency)
  4. tr_M(e_-) ≠ 0                    (the singlet-channel Markov
                                       trace is nonzero — so any
                                       λ ∈ R determines a distinct
                                       coupling; uniqueness up to
                                       scaling is non-degenerate)

The corollary's uniqueness then follows: any braid-invariant scalar
coupling φ: A⊗A → 𝟏 factors through projection onto V_- (since V_+
is a non-singlet representation), and is therefore determined by
the single scalar φ(e_-) = λ · tr_M(e_-).

Emits `gauge-coupling-uniqueness-probe.witness.json`.
"""
from __future__ import annotations


# Path bridge (subdirectory refactor — Phase 1, 2026-06-02).
# Keeps flat-namespace imports (`from witness_base import …`)
# working from the `probes/` cluster subdirectory. The bridge
# module also puts every other cluster subdir on sys.path so
# cross-cluster bare-name imports resolve. Idempotent.

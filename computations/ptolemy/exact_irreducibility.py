"""Is the L6a4 class-1 representation ABSOLUTELY IRREDUCIBLE?  Exactly, over K.

WHY IT MATTERS FOR THE Sym^2 GATE.  Complex type -- established by
exact_character_selfduality.py without either GGZ hypothesis -- is the NECESSARY
condition the gate demands: it says the 3-dimensional object carries no invariant
bilinear form, symmetric or otherwise.  It is not sufficient, and a reducible
representation would not be a flavour triple at all: if rho preserved a line or a plane
its "3-dimensional object" would be a direct sum or extension of smaller ones, and the
SU(3) the eightfold needs could not act faithfully on it.

The test is Burnside: rho is absolutely irreducible over a field iff the K-algebra
generated by its image is ALL of M_3(K), i.e. the span of the matrices rho(w) has
dimension 9.  So build the span by multiplying in generators until it stops growing and
read off the rank.  This is exact linear algebra over K -- Gaussian elimination with
Fraction entries and equality tests, no tolerance and no rank threshold.

Rank 9 is a POSITIVE result and means absolutely irreducible.  Rank < 9 is equally a
result: it names the dimension of the invariant subalgebra and says the representation
factors, which would close this branch.  Either way it is a measurement, not a search
that can quietly fail.

AND THEN THE ZARISKI CLOSURE, which is what "genuinely 3-dimensional" actually means.
Let G be the Zariski closure of rho(pi_1) in SL(3,C).  Three MEASURED facts pin it:

  (H1) rho(b) is unipotent and not the identity -- charpoly (x-1)^3, (M-I)^3 = 0,
       M - I != 0.  Checked here, not assumed from boundary-unipotency.
  (H2) rho is absolutely irreducible -- the Burnside rank above.
  (H3) rho is complex type -- no invariant bilinear form (exact_character_selfduality).

In a linear algebraic group every unipotent element lies in the IDENTITY COMPONENT, so
(H1) puts a non-trivial unipotent in G^0, and a torus contains none.  By Clifford
theory rho|G^0 is semisimple; in dimension 3 the alternatives are that G^0 acts
irreducibly, or splits it as 1+1+1 permuted by G/G^0 (so G^0 lies in a torus, excluded
by the unipotent), or as 1+2 -- impossible, since summands of different dimensions
cannot be permuted transitively and would both be G-invariant, contradicting (H2).  So
G^0 acts irreducibly, and the connected irreducible subgroups of SL(3,C) are SL(3,C)
and SO(3,C).  SO(3,C) preserves a symmetric form, which (H3) forbids.  Hence
G^0 = SL(3,C): the image is ZARISKI-DENSE.

That is the sharpest computable sense in which this object is a 3-dimensional thing and
not something smaller wearing three dimensions -- it is not a Sym^2 of an SL(2)
representation, not monomial, and not finite.  It is an ARGUMENT from standard
structure theory over three checked hypotheses, not a machine-checked proof, and it is
still NOT an identification with the flavour triple: no SU(3) real form, and no
connection to the eightfold's category, is exhibited anywhere here.

NO FLOAT64: Fraction and K only.
"""
import json
import pathlib
import sys

import snappy
import sympy as sp
from snappy.ptolemy.coordinates import PtolemyCoordinates

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import exact_character_selfduality as X            # noqa: E402
from numberfield import NumberField                # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent


def flatten(M):
    return [M[i][j] for i in range(3) for j in range(3)]


def rank_over_K(K, rows):
    """Gaussian elimination over K.  Exact: pivots are chosen by non-zero-ness, never
    by magnitude, because K has no ordering and no notion of a small pivot."""
    rows = [list(r) for r in rows]
    piv, r = [], 0
    for c in range(9):
        p = None
        for i in range(r, len(rows)):
            if not K.is_zero(rows[i][c].v):
                p = i
                break
        if p is None:
            continue
        rows[r], rows[p] = rows[p], rows[r]
        inv = X.Elt(K, K.inv(rows[r][c].v))
        rows[r] = [x * inv for x in rows[r]]
        for i in range(len(rows)):
            if i != r and not K.is_zero(rows[i][c].v):
                f = rows[i][c]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
        piv.append(c)
        r += 1
        if r == 9:
            break
    return r, piv


def main():
    name = sys.argv[1] if len(sys.argv) > 1 else 'L6a4'
    kcls = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    d = json.loads((HERE / f'{name}-c{kcls}-ptolemy-in-K.json').read_text())
    gen = sp.Symbol('t')
    fe = sp.sympify(d['field']['min_poly'])
    K = NumberField([X._frac(c)
                     for c in reversed(sp.Poly(sp.expand(fe), gen).all_coeffs())])
    pt = {k: X.poly_to_elt(K, sp.sympify(v), gen) for k, v in d['ptolemy'].items()}
    M = snappy.Manifold(name)
    V = M.ptolemy_variety(3, obstruction_class=kcls, eliminate_fixed_ptolemys=True)
    dd = dict(pt)
    dd['1'] = X.Elt(K, K.one())
    C = PtolemyCoordinates(dd, is_numerical=False,
                           py_eval_section=eval(V.py_eval_section()),
                           manifold_thunk=lambda: M,
                           non_trivial_generalized_obstruction_class=(kcls != 0))
    G = M.fundamental_group()

    # Relator gate first -- see exact_character_selfduality.py for why.
    for rel in G.relators():
        R = C.evaluate_word(rel, G)
        if any(not (R[i][j] == 0) for i in range(3) for j in range(3) if i != j) \
                or not (R[0][0] == R[1][1] == R[2][2]):
            print(f"  RELATOR GATE FAILED on {rel} -- not a representation.")
            return 1

    gens = G.generators()
    letters = list(gens) + [g.upper() for g in gens]
    print(f"{name} c{kcls}: K degree {K.deg}; generators {gens}")

    words = ['']
    span, seen = [], set()
    rank = 0
    for L in range(0, 7):
        nxt = []
        for w in words:
            for a in letters:
                if w and w[-1].swapcase() == a:
                    continue
                nxt.append(w + a)
        cand = words if L == 0 else nxt
        for w in cand:
            if w in seen:
                continue
            seen.add(w)
            span.append(flatten(C.evaluate_word(w, G) if w else
                                [[X.Elt(K, K.one()) if i == j else X.Elt(K, K.zero())
                                  for j in range(3)] for i in range(3)]))
        rank, _ = rank_over_K(K, span)
        print(f"  words of length <= {L}: {len(seen)} matrices, span rank {rank} of 9",
              flush=True)
        if rank == 9:
            break
        words = nxt

    # (H1): a non-trivial unipotent in the image.  Checked, not inferred from the
    # boundary-unipotent construction.
    one, zeroE = X.Elt(K, K.one()), X.Elt(K, K.zero())

    def e2(Mx):
        acc = zeroE
        for i, j in ((0, 1), (0, 2), (1, 2)):
            acc = acc + (Mx[i][i] * Mx[j][j] - Mx[i][j] * Mx[j][i])
        return acc

    unipotents = []
    for g in gens:
        Mg = C.evaluate_word(g, G)
        N = [[Mg[i][j] - (one if i == j else zeroE) for j in range(3)] for i in range(3)]
        if all(N[i][j] == zeroE for i in range(3) for j in range(3)):
            continue                                  # identity: not a witness
        if (X.trace(K, Mg) == 3) and (e2(Mg) == 3) and (X.det3(K, Mg) == one):
            unipotents.append(g)
    print(f"  non-trivial unipotent generators (charpoly (x-1)^3): "
          f"{unipotents if unipotents else 'NONE'}")

    absirred = (rank == 9)
    verdict = ("ABSOLUTELY IRREDUCIBLE (Burnside: the image spans M_3(K))" if absirred
               else f"span rank {rank} of 9 -- NOT absolutely irreducible; the image"
                    f" generates a proper subalgebra")
    print(f"\n  VERDICT: {verdict}")
    if absirred:
        print("    Combined with the complex-type certificate, the 3-dimensional object")
        print("    is irreducible AND carries no invariant bilinear form.  That is the")
        print("    shape the Sym^2 gate demands.")
    if absirred and unipotents:
        print(f"\n  ZARISKI CLOSURE: (H1) non-trivial unipotent {unipotents[0]},"
              " (H2) absolutely irreducible,\n    (H3) complex type => G^0 = SL(3,C),"
              " i.e. the image is ZARISKI-DENSE.")
        print("    See the module docstring for the derivation.  It is an argument from")
        print("    standard structure theory over three CHECKED hypotheses, not a")
        print("    machine-checked proof, and it is NOT an identification with the")
        print("    flavour triple: no SU(3) real form and no link to the eightfold's")
        print("    category is exhibited anywhere here.")
    elif absirred:
        print("\n  ZARISKI CLOSURE: undetermined -- no non-trivial unipotent found among")
        print("    the generators, so (H1) is unavailable and a finite or monomial image")
        print("    is not excluded.")

    out = HERE / f'{name}-c{kcls}-irreducibility.json'
    out.write_text(json.dumps({
        "manifold": name, "obstruction_class": kcls, "field": d["field"],
        "matrices_spanned": len(seen), "span_rank": rank, "full_rank": 9,
        "absolutely_irreducible": absirred, "verdict": verdict,
        "method": "Burnside: absolutely irreducible iff the image spans M_3(K)",
        "zariski": {
            "unipotent_generators": unipotents,
            "H1_nontrivial_unipotent": bool(unipotents),
            "H2_absolutely_irreducible": bool(absirred),
            "H3_complex_type": "established separately in"
                               " <manifold>-c<class>-character-selfduality.json",
            "conclusion": ("G^0 = SL(3,C); the image is Zariski-dense"
                           if (absirred and unipotents) else "undetermined"),
            "status": "argument from standard structure theory over checked"
                      " hypotheses; NOT machine-checked, and NOT an identification"
                      " with the flavour triple",
        },
    }, indent=2) + "\n")
    print(f"  wrote {out.name}")
    return 0 if absirred else 2


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Is the SL(3)-lift obstruction of sigma_b's gauge element the mu_3 OBSTRUCTION TWIST,
or something else?  The question decides whether non-liftability is evidence at all.

WHAT IS ALREADY ESTABLISHED (main f7fee734c3, and NOT re-derived here).  On the exact
L6a4 class-1 Ptolemy point over K = Q[T]/(f), sigma_b's ratio r = sigma_b(x)/D(x) IS a
coboundary for the GGZ decoration torus: r is a homomorphism L -> K^x on the row lattice
L = {e in Z^6 : sum e = 0 mod 3}, all 128 equations verified.  It does NOT lift to a
diagonal SL(3) matrix over K, because

    w := r(3 e_0) = 256*T^3/189404296875 + 308/3879

is not a cube in K.

WHY THAT SINGLE NON-CUBE IS NOT YET A STATEMENT ABOUT MAPS.  w is the value at ONE
lattice vector.  A map-level claim needs an invariant, and there is one:
[Z^6 : L] = 3, so a homomorphism r : L -> K^x extends to Z^6 exactly when r(3 e_0) has a
cube root in K, and replacing e_0 by e_0 + l (l in L) multiplies w by r(l)^3.  So the
obstruction is a well-defined class

    [w]  in  K^x / (K^x)^3,

independent of the lift chosen (formalised sorry-free in
QOU/Eightfold/SubgroupExtensionObstruction.lean).  Whether it is TRIVIAL is what decides
liftability, and that is basis-independent.

THE QUESTION THIS FILE ANSWERS.  K contains zeta_3 (= u, the obstruction cube root), so
by Kummer theory K^x/(K^x)^3 = H^1(K, mu_3) -- the obstruction is mu_3-cohomological,
exactly like the representation-level class in H^2(M, dM; Z/3).  So the sharp question is
not "is w a cube" (answered: no) but

    is [w] in the subgroup generated by [u]?

  * YES -> the non-liftability IS the mu_3 obstruction twist.  It is then STRUCTURALLY
    EXPECTED and is NOT evidence against duality inducing sigma_b: the twist is exactly
    what a non-trivial obstruction class should contribute.
  * NO  -> the obstruction is something else, and it needs an explanation before any
    map-level identity can be asserted.

Note the test is only meaningful if [u] is itself non-trivial, i.e. u is not a cube in K.
Expected, since a cube root of zeta_3 is zeta_9 and [Q(zeta_9):Q] = 6 does not divide
[K:Q] = 4 -- but that is an argument, so this file MEASURES it rather than assuming it.

METHOD, exact in K, no floats and no tolerances -- REDUCTION MOD PRIMES.
If v = y^3 with y in K, then reducing modulo any prime of K above a rational prime p
gives vbar = ybar^3 in the residue field.  So a single prime where vbar is NOT a cube
REFUTES outright, exactly, with no tolerance and no Groebner basis.

Choosing the primes is the whole content, and one condition is easy to miss:

  * p = 1 mod 3, so that cubes are an index-3 subgroup of F_p^x and the test
    vbar^((p-1)/3) = 1 has content.  (For p = 2 mod 3 every element is a cube and the
    prime says nothing.)
  * f has a root mod p, so the residue field is F_p and reduction is evaluation.
  * p != 1 mod 9.  An element of order 3 is a cube in the cyclic group F_p^x exactly
    when 9 | p-1, so at a prime with 9 | p-1 the class of u is TRIVIAL mod p and the
    three candidates w, w*u, w*u^2 become indistinguishable.  Such a prime cannot
    separate them and is skipped -- this is the condition that makes the test sharp
    rather than merely valid.

WHAT THIS CAN AND CANNOT DO.  Reduction can only REFUTE: surviving every prime tried is
evidence, never proof, because a non-cube in K can be a cube modulo each prime of a
finite set.  A survivor is therefore reported as "survives N primes, NOT proved", never
as "is a cube" -- and the Groebner decision is run on the survivor alone, where it is one
call rather than four.

A previous version of this file ran the Groebner stage first, gated on a norm test.  That
was the wrong algorithm: N(u) = 1 is a rational cube, so the norm test is inconclusive
for u by construction, and the Groebner over Q on a quartic with coefficients up to
2.5e13 did not finish.  The norm test is kept below as a cheap extra refuter, not as the
gate.
"""
import json
import sys
import warnings

warnings.filterwarnings('ignore')
import sympy as sp

T = sp.Symbol('T')
NPRIMES = 40
WIT = 'computations/ptolemy/ptolemy-duality-sigma-coboundary-test.witness.json'
PT = 'computations/ptolemy/L6a4-c1-ptolemy-in-K.json'


def main():
    wit = json.load(open(WIT))
    pt = json.load(open(PT))
    f = sp.expand(sp.sympify(wit['field']['min_poly'].replace('t', 'T')))
    assert sp.Poly(f, T).is_irreducible, "f must be irreducible for K to be a field"
    red = lambda e: sp.expand(sp.rem(sp.expand(e), f, T))
    lc = sp.LC(sp.Poly(f, T))

    b = wit['results']['sigma_b']['B_torus']
    assert b['coboundary_on_row_lattice'] is True
    assert b['w_is_cube_in_K'] is False
    w = sp.expand(sp.sympify(b['w_eq_r_of_3e0'].replace('t', 'T')))
    idx = b['row_lattice_index_in_Zk']
    u = sp.expand(sp.sympify(pt['ptolemy']['u'].replace('t', 'T')))
    assert red(u ** 2 + u + 1) == 0, "u is not a primitive cube root of unity"
    print(f"K = Q[T]/(f), deg 4, irreducible;  [Z^k : L] = {idx}", flush=True)
    print(f"w = r(3 e_0) = {w}", flush=True)

    def norm(g):
        g = sp.expand(g)
        dg = sp.degree(sp.Poly(g, T)) if g.free_symbols else 0
        return sp.nsimplify(sp.resultant(f, g, T) / lc ** dg)

    def is_rational_cube(x):
        x = sp.nsimplify(x)
        if x == 0:
            return True
        n_, d_ = sp.fraction(sp.Rational(x))
        rn, ok1 = sp.integer_nthroot(abs(n_), 3)
        rd, ok2 = sp.integer_nthroot(abs(d_), 3)
        return bool(ok1 and ok2)

    # ---- the separating primes -------------------------------------------------
    fp = sp.Poly(f, T)
    fden = sp.lcm([sp.denom(sp.nsimplify(c)) for c in fp.all_coeffs()])
    primes, pr = [], 5
    while len(primes) < NPRIMES and pr < 200000:
        pr = sp.nextprime(pr)
        if pr % 3 != 1 or pr % 9 == 1:      # need order-3 subgroup, and u NOT a cube
            continue
        if int(fden) % pr == 0 or int(lc) % pr == 0:
            continue
        roots = [x for x in range(pr)
                 if sum(int(c) * pow(x, len(fp.all_coeffs()) - 1 - i, pr)
                        for i, c in enumerate(
                            [sp.Integer(sp.nsimplify(cc)) for cc in fp.all_coeffs()])) % pr == 0]
        if roots:
            primes.append((pr, roots[0]))
    print(f"separating primes (p=1 mod 3, p!=1 mod 9, f has a root mod p): "
          f"{len(primes)} found, first {[p for p, _ in primes[:6]]}", flush=True)
    assert primes, "no separating prime found; the test cannot run"

    def reduce_at(v, pr, th):
        v = red(v)
        co = sp.Poly(v, T).all_coeffs()[::-1] if v.free_symbols else [v]
        acc = 0
        for i, c in enumerate(co):
            c = sp.nsimplify(c)
            n_, d_ = sp.fraction(c)
            if int(d_) % pr == 0:
                return None
            acc += int(n_) * pow(int(d_), -1, pr) % pr * pow(th, i, pr)
        return acc % pr

    def refuted_mod_p(v):
        """Return (p, th) of a prime where v is NOT a cube, or None if none refutes."""
        for pr, th in primes:
            vb = reduce_at(v, pr, th)
            if vb is None or vb == 0:
                continue
            if pow(vb, (pr - 1) // 3, pr) != 1:
                return (pr, th)
        return None

    def groebner_decides(v):
        a0, a1, a2, a3 = sp.symbols('a0 a1 a2 a3')
        y = a0 + a1 * T + a2 * T ** 2 + a3 * T ** 3
        pc = sp.Poly(sp.expand(sp.rem(sp.expand(y ** 3), f, T) - red(v)), T)
        G = sp.groebner([sp.expand(c) for c in pc.all_coeffs()],
                        a0, a1, a2, a3, order='grevlex')
        return list(G.exprs) != [sp.Integer(1)]

    def is_cube_in_K(v, label):
        v = red(v)
        r_ = refuted_mod_p(v)
        if r_:
            print(f"   {label:14s} NOT a cube in K -- refuted exactly at p = {r_[0]}",
                  flush=True)
            return False
        nv = norm(v)
        if not is_rational_cube(nv):
            print(f"   {label:14s} NOT a cube in K -- norm {nv} is not a rational cube",
                  flush=True)
            return False
        print(f"   {label:14s} survives all {len(primes)} primes and the norm test "
              f"-- NOT proved a cube; deciding by Groebner", flush=True)
        ok = groebner_decides(v)
        print(f"   {label:14s} Groebner: {'a cube EXISTS' if ok else 'NO solution'}",
              flush=True)
        return ok

    # ---- POSITIVE CONTROL, before any verdict is believed ----------------------
    # A test that can only ever answer "not a cube" is indistinguishable from a broken
    # one.  Feed it a KNOWN cube -- y^3 for an explicit y in K -- and require it to say
    # so.  If this fails, every verdict below is uninterpretable and the run aborts.
    print("positive control: an explicit cube must be RECOGNISED", flush=True)
    y_ctrl = 2 + T
    v_ctrl = red(y_ctrl ** 3)
    if refuted_mod_p(v_ctrl) is not None:
        print("   CONTROL FAILED: (2+T)^3 was 'refuted' as a non-cube.")
        print("   The reduction is wrong; no verdict below can be trusted.  Aborting.")
        return 1
    print(f"   (2+T)^3 survives all {len(primes)} primes, as it must", flush=True)
    # and a NEGATIVE control: the test must not pass everything
    if refuted_mod_p(red(y_ctrl ** 3 * u)) is None:
        print("   CONTROL FAILED: (2+T)^3 * u was not refuted at any prime, yet u is")
        print("   not a cube, so the test is not separating.  Aborting.")
        return 1
    print("   (2+T)^3 * u IS refuted, so the test separates cube classes", flush=True)

    print("\nIs u itself a cube in K?  (the test below is vacuous if it is)", flush=True)
    u_cube = is_cube_in_K(u, 'u')
    if u_cube:
        print("\nu IS a cube in K, so [u] is trivial and the membership test below")
        print("cannot distinguish anything.  Report and stop.")
        return 1
    print("   => [u] is a NON-TRIVIAL element of K^x/(K^x)^3.", flush=True)

    print("\nIs [w] in the subgroup generated by [u]?", flush=True)
    hits = []
    for j in (0, 1, 2):
        v = red(w * red(u ** j))
        if is_cube_in_K(v, f'w * u^{j}'):
            hits.append(j)

    print()
    if hits:
        j = hits[0]
        print(f"[w] = [u^{(-j) % 3}] in K^x/(K^x)^3  (w * u^{j} is a cube).")
        print("So the SL(3)-lift obstruction IS the mu_3 obstruction twist.")
        print("CONSEQUENCE: non-liftability is STRUCTURALLY EXPECTED and is NOT evidence")
        print("against duality inducing sigma_b.  The lift fails for the same reason the")
        print("obstruction class is non-trivial, not because the two maps differ.")
    else:
        print("[w] is NOT in <[u]>: w, w*u and w*u^2 are all non-cubes in K.")
        print("So the SL(3)-lift obstruction is NOT the mu_3 obstruction twist.  It is a")
        print("SEPARATE class in K^x/(K^x)^3 and must be explained before any map-level")
        print("identity is asserted.  Scope: this point, this class -- a point-level")
        print("obstruction, not yet a statement about maps on the variety.")
    return 0


if __name__ == '__main__':
    sys.exit(main())

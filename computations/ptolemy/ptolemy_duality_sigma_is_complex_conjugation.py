#!/usr/bin/env python3
"""WHICH automorphism is the duality sigma?  It is COMPLEX CONJUGATION of K. (qou-qjhc)

THE QUESTION THIS ANSWERS.  `ptolemy_duality_generic.py` finds, per manifold, that
exactly one non-identity element of Aut(K/Q) carries the duality intertwiner.  It
does not say WHICH, so "the duality sigma" has been a thing located by search
rather than by a criterion.

THE CORPUS'S EXISTING CRITERION DOES NOT SELECT, and that is the point.
`ptolemy_duality_galois_check.py` establishes that cocycle negation is the
substitution u -> u^2 -- "the nontrivial automorphism of mu_3, i.e. complex
conjugation OF THE CUBE ROOT OF UNITY".  That is a statement about the action on
mu_3 alone.  When Gal(K/Q) = Z/2 x Z/2, TWO of its three involutions invert
zeta_3, so the criterion halves the candidates and stops.  Measured on L6a4 class
1, where the older probes hardcode exactly that pair:

    sigma_a   inverts zeta_3: True    is conj(K): False   intertwiner: False
    sigma_b   inverts zeta_3: True    is conj(K): True    intertwiner: True

"Complex conjugation of mu_3" and "complex conjugation of K" are different claims
and only the second one selects.

TWO NOTIONS OF "COMPLEX CONJUGATION", AND THEY COME APART HERE.  Both are
reported; they are NOT collapsed into one column, because on one of the corpus's
own points they disagree.

  (CM)  EMBEDDING-INDEPENDENT.  K is totally imaginary and Fix(sigma) is TOTALLY
        REAL -- i.e. K is a CM field with maximal real subfield Fix(sigma), and
        sigma is its canonical conjugation, the same element at every embedding.
        Decided EXACTLY, with no tolerance: Fix(sigma) is generated by
        y = x + sigma(x) for a suitable x, its minimal polynomial over Q comes
        from exact linear algebra in the power basis (the least m for which
        1, y, ..., y^m are Q-linearly dependent), and "totally real" is
        `Poly.count_roots()` -- Sturm sequences, not a numeric scan.

  (EMB) EMBEDDING-DEPENDENT.  sigma(alpha) = conj(alpha) at ONE chosen embedding,
        checked at 60 digits.  On a CM field this holds at every embedding and
        agrees with (CM).  On a merely totally-imaginary field it need not.

MEASURED, and this is why the two are kept apart: `5_2` class 1 ORBIT 1 has
[K:Q] = 6, r1 = 0 (totally imaginary), |Aut| = 2 -- and Fix(sigma) has degree 3
and is NOT totally real.  So K is totally imaginary but NOT CM, (CM) is False and
(EMB) is True, and an earlier version of this probe asserted they must agree and
crashed.  The crash was correct: collapsing them would have reported a uniform
"sigma is complex conjugation" across the corpus on a criterion that silently
means different things per case.  The probe reports the per-embedding profile for
such a field instead, so the weaker claim is visibly weaker.

No float64 anywhere: sympy Rationals and `sp.N(..., 60)`.

WHAT THIS IS AND IS NOT.  It is a measured regularity over every exact point the
corpus holds, not a theorem.  It says nothing about WHY duality should be
realised by conjugation -- and on a non-normal K (5_2 class 1 orbit 1) it is a
weaker statement than it looks, because there Aut(K/Q) has order 2 and cannot
select anything: one candidate is the winner by default.  Only a case with more
than one non-identity candidate TESTS the criterion.  Those cases are reported
separately below for exactly that reason.
"""
import argparse
import glob
import json
import pathlib
import sys
import warnings

import sympy as sp

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
warnings.filterwarnings('ignore')

from ptolemy_duality_generic import automorphisms                            # noqa: E402

t = sp.Symbol('t')
PREC = 60


def _red(e, fp):
    return sp.expand(sp.rem(sp.Poly(sp.expand(e), t), fp).as_expr())


def _coords(y, deg, fp):
    p = sp.Poly(_red(y, fp), t)
    return [sp.Rational(p.coeff_monomial(t ** i)) for i in range(deg)]


def min_poly_exact(y, deg, fp):
    """Minimal polynomial of y in K over Q, by exact linear algebra in the power basis.

    The least m such that 1, y, ..., y^m are Q-linearly dependent; the dependency
    coefficients ARE the minimal polynomial.  No AlgebraicNumber round-trip (which
    is what broke an earlier attempt) and no numerics.
    """
    pows, cur = [_coords(sp.Integer(1), deg, fp)], sp.Integer(1)
    for m in range(1, deg + 1):
        cur = _red(cur * y, fp)
        pows.append(_coords(cur, deg, fp))
        M = sp.Matrix(pows).T                      # deg x (m+1)
        ns = M.nullspace()
        if ns:
            v = ns[0]
            v = v / v[m] if v[m] != 0 else v
            if v[m] == 0:
                continue
            return sp.Poly([sp.Rational(v[i]) for i in range(m, -1, -1)], t)
    return None


def fixed_field(g, deg, fp):
    """Minimal polynomial of a generator of Fix(g), or None if no generator found."""
    want = None
    for x in [t, _red(t * t, fp), _red(t ** 3, fp), _red(t + t * t, fp),
              _red(t * t + t ** 3, fp), _red(t + t ** 3, fp)]:
        y = _red(x + x.subs(t, g), fp)
        mp_ = min_poly_exact(y, deg, fp)
        if mp_ is None:
            continue
        if want is None or mp_.degree() > want.degree():
            want = mp_
        if want.degree() * 2 == deg:               # the full index-2 subfield
            break
    return want


def analyse(stem):
    pf = HERE / f'{stem}-ptolemy-in-K.json'
    d = json.loads(pf.read_text())
    fe, deg = sp.sympify(d['field']['min_poly']), d['field']['degree']
    fp = sp.Poly(fe, t)
    autos = automorphisms(fe, deg)

    fpoly = sp.Poly(fe, t)
    k_real = int(fpoly.count_roots())              # exact (Sturm), not a numeric scan
    tot_imag = (k_real == 0)

    rep_path = HERE / f'{stem}-duality-generic.json'
    winner = None
    if rep_path.exists():
        rows = json.loads(rep_path.read_text())['rows']
        w = [k[len('t -> '):] for k, v in rows.items()
             if v.get('untwisted_found') and not v.get('is_identity')]
        if len(w) == 1:
            winner = sp.expand(sp.sympify(w[0]))

    all_roots = fpoly.all_roots()
    a0 = sp.N(all_roots[0], PREC)
    tol = sp.Float(10) ** (-(PREC - 15))

    rows = []
    for i, g in enumerate(autos):
        is_id = sp.expand(g - t) == 0
        mp_fix = None if is_id else fixed_field(g, deg, fp)
        fix_deg = None if mp_fix is None else mp_fix.degree()
        fix_real = None if mp_fix is None else int(mp_fix.count_roots())
        fix_tot_real = None if mp_fix is None else (fix_real == fix_deg)
        num_conj = bool(abs(sp.N(g.subs(t, a0), PREC) - sp.conjugate(a0)) < tol)
        # (CM): exact, embedding-independent.  (EMB): numeric, per-embedding.
        # They are reported separately and never collapsed -- see the module
        # docstring for the measured case where they disagree.
        cm_conj = bool(tot_imag and fix_tot_real) if not is_id else False
        emb_profile = None
        if not is_id and tot_imag and not cm_conj:
            # not CM: say at HOW MANY of the embeddings sigma acts as conjugation,
            # so the embedding-dependence is visible rather than implied.
            hits = 0
            for r_ in all_roots:
                rN = sp.N(r_, PREC)
                if abs(sp.N(g.subs(t, rN), PREC) - sp.conjugate(rN)) < tol:
                    hits += 1
            emb_profile = f'{hits}/{deg} embeddings'
        rows.append({
            'complex_conjugation_CM_exact': cm_conj,
            'complex_conjugation_at_embedding_0_60dps': num_conj,
            'embedding_profile': emb_profile,
            'index': i, 'sigma': str(sp.expand(g)), 'is_identity': is_id,
            'fixed_field_min_poly': None if mp_fix is None else str(mp_fix.as_expr()),
            'fixed_field_degree': None if fix_deg is None else int(fix_deg),
            'fixed_field_real_embeddings': fix_real,
            'fixed_field_totally_real': fix_tot_real,
            'CM_and_embedding_agree': cm_conj == num_conj,
            'carries_untwisted_intertwiner':
                None if winner is None else bool(sp.expand(g - winner) == 0),
        })

    cands = len(autos) - 1
    conj_rows = [r for r in rows if r['complex_conjugation_CM_exact']]
    emb_rows = [r for r in rows if r['complex_conjugation_at_embedding_0_60dps']
                and not r['is_identity']]
    verdict = 'NO_DUALITY_REPORT'
    if winner is not None:
        if len(conj_rows) == 1 and conj_rows[0]['carries_untwisted_intertwiner']:
            # the strong, embedding-independent form
            verdict = 'CM_HOLDS_SELECTING' if cands > 1 else 'CM_HOLDS_NOT_SELECTING'
        elif conj_rows:
            verdict = 'CM_FAILS'
        elif len(emb_rows) == 1 and emb_rows[0]['carries_untwisted_intertwiner']:
            # K is not CM: only the weaker per-embedding statement is available
            verdict = ('EMB_ONLY_SELECTING' if cands > 1 else 'EMB_ONLY_NOT_SELECTING')
        elif emb_rows:
            verdict = 'EMB_FAILS'
        else:
            verdict = 'CONJUGATION_NOT_IN_AUT'
    return {
        'stem': stem, 'field_degree': deg, 'min_poly': str(fe),
        'n_automorphisms': len(autos), 'K_over_Q_normal': len(autos) == deg,
        'K_real_embeddings': k_real, 'K_totally_imaginary': tot_imag,
        'K_is_CM': any(r['complex_conjugation_CM_exact'] for r in rows),
        'non_identity_candidates': cands,
        'criterion_is_testable_here': cands > 1,
        'rows': rows, 'verdict': verdict,
    }


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('stems', nargs='*', help='e.g. m004-c1; default: every point file')
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    stems = a.stems or sorted(
        p.name[:-len('-ptolemy-in-K.json')]
        for p in HERE.glob('*-ptolemy-in-K.json'))

    out = []
    for s in stems:
        r = analyse(s)
        out.append(r)
        print(f"\n{s}: [K:Q] = {r['field_degree']}, |Aut| = {r['n_automorphisms']}, "
              f"r1 = {r['K_real_embeddings']}, normal = {r['K_over_Q_normal']}")
        print(f"   non-identity candidates: {r['non_identity_candidates']}  "
              f"-> {'TESTS the criterion' if r['criterion_is_testable_here'] else 'cannot select; corroborates only'}")
        for row in r['rows']:
            if row['is_identity']:
                continue
            print(f"   sigma_{row['index']}: Fix deg {row['fixed_field_degree']}, "
                  f"tot.real {row['fixed_field_totally_real']}  "
                  f"CM-conj {row['complex_conjugation_CM_exact']}  "
                  f"emb-conj {row['complex_conjugation_at_embedding_0_60dps']}"
                  f"{' (' + row['embedding_profile'] + ')' if row['embedding_profile'] else ''}  "
                  f"intertwiner {row['carries_untwisted_intertwiner']}")
        print(f"   VERDICT: {r['verdict']}")

    g = lambda *v: [r['stem'] for r in out if r['verdict'] in v]
    print(f"\n=== summary ===")
    print(f"   CM-conjugation, TESTABLE (>1 candidate), HOLDS : {len(g('CM_HOLDS_SELECTING'))} {g('CM_HOLDS_SELECTING')}")
    print(f"   CM-conjugation, corroborates, cannot select    : {len(g('CM_HOLDS_NOT_SELECTING'))} {g('CM_HOLDS_NOT_SELECTING')}")
    print(f"   K NOT CM -- per-embedding statement only       : {len(g('EMB_ONLY_SELECTING','EMB_ONLY_NOT_SELECTING'))} {g('EMB_ONLY_SELECTING','EMB_ONLY_NOT_SELECTING')}")
    print(f"   FAILS                                          : {len(g('CM_FAILS','EMB_FAILS','CONJUGATION_NOT_IN_AUT'))} {g('CM_FAILS','EMB_FAILS','CONJUGATION_NOT_IN_AUT')}")
    if a.write:
        p = HERE / 'ptolemy-duality-sigma-is-complex-conjugation.json'
        p.write_text(json.dumps({'probe': 'ptolemy_duality_sigma_is_complex_conjugation',
                                 'cases': out}, indent=1) + "\n")
        print(f"   report -> {p}")

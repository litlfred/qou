def qint_sym(m):
    return sp.simplify((q**m - q**(-m)) / (q - q**(-1)))


def qint_fake(m):
    return sp.simplify(sum(q**i for i in range(m)))


def qfact(n, qi):
    out = sp.Integer(1)
    for m in range(1, n + 1):
        out *= qi(m)
    return sp.simplify(out)


def n_lambda(lam) -> int:
    """n(λ) = Σ_i (i−1)·λ_i."""
    return sum(i * r for i, r in enumerate(lam))


def dim_q(lam, conv="sym"):
    """q-hook-length formula, in either corpus convention."""
    n = sum(lam)
    qi = qint_sym if conv == "sym" else qint_fake
    den = sp.Integer(1)
    for h in hooks(lam):
        den *= qi(h)
    base = sp.cancel(sp.simplify(qfact(n, qi) / den))
    if conv == "fake":
        base = sp.cancel(sp.simplify(q**n_lambda(lam) * base))
    return base



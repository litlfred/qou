# ------------------------------------------------------------- partitions

def partitions(n: int, cap: int | None = None):
    if cap is None:
        cap = n
    if n == 0:
        yield ()
        return
    for first in range(min(n, cap), 0, -1):
        for rest in partitions(n - first, first):
            yield (first,) + rest


def conj(lam):
    """Conjugate partition."""
    if not lam:
        return ()
    return tuple(sum(1 for r in lam if r > j) for j in range(lam[0]))


def gb_depth(lam) -> int:
    """gbDepth λ = λ₁ + λ'₁ − 1.  `QOU.BraidKnot.gbDepth_eq_corner`."""
    return lam[0] + len(lam) - 1


def hooks(lam):
    """Hook lengths of every cell."""
    c = conj(lam)
    return [lam[i] - j + c[j] - i - 1 for i, row in enumerate(lam) for j in range(row)]


def f_lambda(lam) -> int:
    """# standard Young tableaux, by the hook-length formula."""
    n = sum(lam)
    num = sp.factorial(n)
    den = 1
    for h in hooks(lam):
        den *= h
    return int(num // den)



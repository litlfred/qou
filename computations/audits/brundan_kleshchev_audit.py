"""Brundan–Kleshchev isomorphism audit witness.

The Brundan–Kleshchev theorem
[brundankleshchev2009] proves that the cyclotomic Hecke algebra
$H_n(R, q)$ at level 1 is isomorphic to a cyclotomic Khovanov–
Lauda–Rouquier (KLR) algebra $R_\\alpha^\\Lambda$ as graded
algebras.  This isomorphism is the upstream conjectural input
axiomatised by `class CrystalGraphRealization` in
`thm:confinement-grading-correspondence-conditional` (this PR).

A *full* Lean-level instance of the BK isomorphism is
out-of-scope for this audit.  This script collects a battery of
**necessary structural consequences** of the isomorphism that we
can verify combinatorially as empirical evidence:

1. **Dimension match.**  $\\dim H_n(R, q) = n!$ on both sides.
2. **Centre dimension.**  The centre $Z(H_n)$ has dimension
   $p(n)$ (number of partitions), matching the KLR centre's
   dimension in the principal block.  Computed structurally as
   $|\\mathrm{Part}(n)|$.
3. **Jucys–Murphy content separation.**  The content multisets
   $\\{c(x) : x \\in \\lambda\\}$ are pairwise distinct across
   $\\lambda \\vdash n$.  This is the combinatorial shadow of the
   KLR centre being generated by elementary symmetric functions
   of Jucys–Murphy elements (Jucys's content theorem).
4. **Z-grading on dimensions.**  For each $n$, the graded
   character of the cyclotomic KLR specialises to the
   $q$-dimension formula $\\dim_q V_\\lambda = \\prod_x [h(x)]_q^{-1}
   \\cdot [n]_q!$ (hook formula).  We verify the sum
   $\\sum_\\lambda \\dim_q V_\\lambda^2 / [n]_q!$ at $q_0$ is
   bar-invariant (cf. `prop:bar-involution-invariance`).

These are *not* a proof of the BK isomorphism — they are
necessary conditions whose failure would falsify the upstream
conjecture.  Their cumulative pass status feeds the
`CrystalGraphRealization` empirical-evidence dossier.

Output: `brundan-kleshchev-audit.witness.json` with one
assertion per consequence.

References
----------
- [brundankleshchev2009] Brundan & Kleshchev, "Blocks of
  cyclotomic Hecke algebras and Khovanov–Lauda algebras"
- [khovanovlauda2009] Khovanov–Lauda I (KLR algebra definition)
- [jucys1974] Jucys, "Symmetric polynomials and the centre of the
  symmetric group ring", Rep. Math. Phys.
- conj:crystal-graph-realization
- thm:confinement-grading-correspondence-conditional
"""




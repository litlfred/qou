"""Turn the dps-floor scope lists into a regeneration queue (bean qou-zbws).

Maps each moving producer to the witness stem it writes, so the regeneration
phase is a list of commands rather than a research task. Static: reads source,
runs nothing.
"""
import os, re, sys

ROOT = "/workspace/qou"
SP = os.path.dirname(os.path.abspath(__file__))
STEM = re.compile(r'WitnessBuilder\(\s*[\'"]([A-Za-z0-9._\-/]+)[\'"]')
LIT = re.compile(r'[\'"]([A-Za-z0-9._\-/]+)\.witness\.json[\'"]')


def stems(path):
    try:
        src = open(os.path.join(ROOT, path), encoding="utf-8", errors="replace").read()
    except OSError:
        return []
    out = list(dict.fromkeys(STEM.findall(src) + LIT.findall(src)))
    return out


def load(name):
    p = os.path.join(SP, name)
    if not os.path.exists(p):
        return []
    return [l.strip() for l in open(p) if l.strip()]


tier1, tier2 = load("tier1.txt"), load("tier2.txt")
# The constants_only cone: producers that reach qou_substrate.constants
# WITHOUT going through the q_parameter shim. They move for the same reason
# and were the argument for putting the floor in constants.py.
tier1c, tier2c = load("tier1c.txt"), load("tier2c.txt")
seen = set(tier1) | set(tier2)
tier1c = [f for f in tier1c if f not in seen]
tier2c = [f for f in tier2c if f not in seen]
rows = []
for tier, files in (("1-definite", tier1), ("2-probable", tier2),
                    ("1-definite (constants-only cone)", tier1c),
                    ("2-probable (constants-only cone)", tier2c)):
    for f in files:
        st = stems(f)
        rows.append((tier, f, st))

with_w = [r for r in rows if r[2]]
without = [r for r in rows if not r[2]]
print(f"q_parameter cone: tier1={len(tier1)} tier2={len(tier2)}")
print(f"constants-only cone (new): tier1={len(tier1c)} tier2={len(tier2c)}")
print(f"total producers: {len(rows)}")
print(f"  witness stem resolved: {len(with_w)}   unresolved: {len(without)}")

out = [
    "# dps-floor regeneration queue (bean `qou-zbws`)",
    "",
    "Generated by `scratchpad/build_queue.py` from",
    "`computations/audits/q_parameter_dps_floor_scope.py --list`. Static: it",
    "reads source and runs nothing.",
    "",
    "Landing the 50-dps floor moved these producers from mpmath's default 15",
    "dps to 50, so the numbers in the witnesses they emit change in their",
    "trailing digits. **Tier 1** build their own mpmath values and never raise",
    "dps — their numbers definitely move. **Tier 2** reach mpmath through a",
    "helper and probably move.",
    "",
    "Regenerate ONE AT A TIME: the standing rule is no two producers at once in",
    "a checkout, and several of these are heavy.",
    "",
    "## What this queue does and does not cover",
    "",
    "- **Both import cones, all 264 moving producers.** 229 reach",
    "  `qou_substrate.constants` through the `q_parameter` shim; 35 reach it",
    "  directly and are listed under the \"constants-only cone\" headings. The",
    "  audit's `--list` defaults to the `q_parameter` cone, so an earlier version",
    "  of this document covered only those 229. The other 35 are not a residue to",
    "  wave at: they were precisely the argument for landing the floor in",
    "  `constants.py` rather than in the shim, so omitting them would have",
    "  reintroduced the hole that placement decision closed.",
    "- **Not every producer here has a resolvable witness stem.** Those that do",
    "  not are listed in their own section: the stem is built dynamically,",
    "  written by a helper, or the producer emits none. Each needs a look, not a",
    "  guess.",
    "- **Witness counts, not producer counts, are what matters downstream.** The",
    "  scope audit attributes 48 witnesses to tier 1 and 135 to tier 2, 183 in",
    "  all - and could not attribute 813 of 3104 witnesses to any producer, so",
    "  183 is a LOWER bound on what actually moves.",
    "- **Tier 2 is \"probably\", not \"definitely\".** A producer reaching mpmath",
    "  through a helper may or may not have its emitted numbers change. The",
    "  cheapest discriminator is to regenerate and diff, not to reason about it.",
    "",
]
for tier in ("1-definite", "2-probable",
             "1-definite (constants-only cone)",
             "2-probable (constants-only cone)"):
    sel = [r for r in with_w if r[0] == tier]
    out += [f"## Tier {tier} — {len(sel)} producers", ""]
    for _, f, st in sorted(sel):
        out.append(f"- [ ] `{f}` -> {', '.join('`' + s + '.witness.json`' for s in st[:3])}")
    out.append("")
if without:
    out += [f"## No witness stem found by static scan — {len(without)}", "",
            "These are in the moving set but the scan could not name their",
            "witness (dynamic stem, helper-written, or they emit none).", ""]
    for _, f, _ in sorted(without):
        out.append(f"- [ ] `{f}` — resolve stem by hand")
    out.append("")
open(os.path.join(ROOT, "docs/audits/2026-09-03-dps-floor-regeneration-queue.md"),
     "w", encoding="utf-8").write("\n".join(out))
print("wrote docs/audits/2026-09-03-dps-floor-regeneration-queue.md")
